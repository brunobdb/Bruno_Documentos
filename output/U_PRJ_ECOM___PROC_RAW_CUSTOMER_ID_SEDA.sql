CREATE PROCEDURE U_PRJ_ECOM.PROC_RAW_CUSTOMER_ID_SEDA
 LANGUAGE SQLSCRIPT AS
 BEGIN
CREATE COLUMN TABLE U_PRJ_ECOM.TMP_VTEX_SEDA_EPP2_SMB AS (	
SELECT * FROM (
 SELECT  DISTINCT 
 'BRA' AS "COUNTRY_CD" ,
ORDER_ID,
USER_PROFILE_ID  ,
HOSTNAME,
CREATION_TIMESTAMP  AS "ORDER_CREATION_DATE",
CURRENT_TIMESTAMP AS "INSERT_DATE",
CURRENT_TIMESTAMP AS "LAST_UPDATE",
CURRENT_TIMESTAMP AS LOAD_DATE
 
FROM U_PRJ_ECOM.RAW_VTEX_SSG_BR_EPP2_SALES_ORDER  A   
 
UNION ALL
 
 (	                                 
 SELECT  DISTINCT 
'BRA' AS "COUNTRY_CD" ,
ORDER_ID,
USER_PROFILE_ID  ,
HOSTNAME,
CREATION_TIMESTAMP  AS "ORDER_CREATION_DATE",
CURRENT_TIMESTAMP AS "INSERT_DATE",
CURRENT_TIMESTAMP AS "LAST_UPDATE",
CURRENT_TIMESTAMP AS LOAD_DATE
 
FROM U_PRJ_ECOM.RAW_VTEX_SSG_BR_B2B_SALES_ORDER  
)
)A
 WHERE CAST (A."ORDER_CREATION_DATE" AS DATE) >= '2024-08-01'
AND NOT EXISTS 
(
	                  SELECT 1
	                    from "U_PRJ_ECOM"."RAW_CUSTOMER_ID_SEDA" AA
	                   where AA."ORDER_ID"        = A."ORDER_ID"
	                     AND AA."USER_PROFILE_ID" = A."USER_PROFILE_ID"
	                     AND AA."HOSTNAME"        = A."HOSTNAME"
	            )
	            )
	            
;
INSERT INTO "U_PRJ_ECOM"."RAW_CUSTOMER_ID_SEDA"
(
SELECT * FROM U_PRJ_ECOM.TMP_VTEX_SEDA_EPP2_SMB
)
;
DROP TABLE U_PRJ_ECOM.TMP_VTEX_SEDA_EPP2_SMB;
END
	(TO_DATE(FVPOT.CREATION_TIMESTAMP)= DC.YYYYMMDD)
LEFT JOIN OW_MD.DIM_VTEX_AFFILIATE DVA ON
	(FVPOT.SUR_KEY_AFFILIATE = DVA.SUR_KEY)
LEFT JOIN OW_MD.DIM_VTEX_ORDER_STATUS DVOS ON
	(FVPOT.SUR_KEY_ORDER_STATUS = DVOS.SUR_KEY)
LEFT JOIN OW_MD.DIM_VTEX_PAYMENT_STATUS DVPS ON
	(FVPOT.SUR_KEY_PAYMENT_STATUS = DVPS.SUR_KEY)
LEFT JOIN OW_MD.DIM_VTEX_PURCHASE_ORDER_DOMAIN DVPOD ON
	(FVPOT.SUR_KEY_ORDER_DOMAIN = DVPOD.SUR_KEY)
LEFT JOIN OW_MD.DIM_VTEX_PURCHASE_ORDER_REGION DVPOR ON
	(FVPOT.SUR_KEY_ORDER_REGION = DVPOR.SUR_KEY)
LEFT JOIN OW_MD.DIM_VTEX_PURCHASE_ORDER_TRADE_IN DVPOTI ON
	(FVPOT.SUR_KEY_ORDER_TRADE_IN = DVPOTI.SUR_KEY)
LEFT JOIN OW_MD.FT_VTEX_PURCHASE_ORDER_PAYMENT FVPOP ON
	(FVPOT.SUR_KEY = FVPOP.SUR_KEY_VTEX_PURCHASE_ORDER_TRACKING)
LEFT JOIN OW_MD.FT_VTEX_PURCHASE_ORDER_TRACKING_ITEM FVPOTI ON
	(FVPOT.SUR_KEY = FVPOTI.SUR_KEY_PURCHASE_ORDER_TRACKING)
LEFT JOIN OW_MD.DIM_VTEX_PAYMENT_GROUP DVPG ON
	(FVPOP.SUR_KEY_VTEX_PAYMENT_GROUP = DVPG.SUR_KEY)
LEFT JOIN OW_MD.OLD_DIM_PRODUCT ODP ON
	(FVPOTI.SUR_KEY_PRODUCT = ODP.SUR_KEY)
LEFT JOIN OW_MD.DIM_VTEX_PURCHASE_ORDER_WAREHOUSE DVPOW ON
	(FVPOTI.SUR_KEY_PURCHASE_ORDER_WAREHOUSE = DVPOW.SUR_KEY)
LEFT JOIN OW_MD.DIM_VTEX_PURCHASE_ORDER_COURIER DVPOC ON
	(FVPOTI.SUR_KEY_PURCHASE_ORDER_COURIER = DVPOC.SUR_KEY)
LEFT JOIN OW_MD.DIM_PRODUCT_GROUP DPG ON
	(ODP.SUR_KEY_PRODUCT_GROUP = DPG.SUR_KEY)
LEFT JOIN OW_MD.DIM_PRODUCT_DIVISION DPD ON
	(DPG.SUR_KEY_PRODUCT_DIVISION = DPD.SUR_KEY)

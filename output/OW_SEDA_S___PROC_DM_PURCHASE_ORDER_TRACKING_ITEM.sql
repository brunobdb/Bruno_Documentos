	DVPOTI.IS_TRADE_IN,
	FVPOP.SUR_KEY AS SUR_KEY_FT_VTEX_PURCHASE_ORDER_PAYMENT,
	FVPOP.SUR_KEY_VTEX_PURCHASE_ORDER_TRACKING,
	FVPOP.SUR_KEY_VTEX_PAYMENT_GROUP,
	FVPOP.CREATE_DATE AS CREATE_DATE_FT_VTEX_PURCHASE_ORDER_PAYMENT,
	FVPOP.UPDATE_DATE AS UPDATE_DATE_FT_VTEX_PURCHASE_ORDER_PAYMENT,
	FVPOTI.PRODUCT_ID,
	FVPOTI.QUANTITY,
	FVPOTI.IS_GIFT,
	FVPOTI.COMMERCIAL_CONDITION_ID,
	FVPOTI.PRICE,

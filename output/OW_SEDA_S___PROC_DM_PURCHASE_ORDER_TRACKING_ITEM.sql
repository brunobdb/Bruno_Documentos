	DC.YYYYMMDD,
	DC.YYYYMM_NORMAL_CALENDAR,
	DC.YYYYQQ_NORMAL_CALENDAR,
	DC.YYYYWW_NORMAL_CALENDAR,
	DC.YYYY_NORMAL_CALENDAR,
	DC.YYYYMM,
	DC.YYYYQQ,
	DC.YYYYWW,
	DC.YYYYSS,
	DC.YYYY,
	DC.SUR_KEY AS SUR_KEY_DIM_CALENDAR,
	DC.DAY_NAME,
	DC.WEEK_DAY,
	DC.WORK_DAY_SEDA,
	DVA.SUR_KEY AS SUR_KEY_DIM_VTEX_AFFILIATE,
	DVA.AFFILIATE_ID,
	DVA.COMMERCIAL_POLICY,
	DVA.SELLER_NAME,
	DVA.DETAILS,
	DVA.MARKETPLACE,
	DVA.SITE,
	DVA.CHANNEL,
	DVA.CREATE_DATE AS CREATE_DATE_DIM_VTEX_AFFILIATE,
	DVA.UPDATE_DATE AS UPDATE_DATE_DIM_VTEX_AFFILIATE,
	DVOS.SUR_KEY AS SUR_KEY_DIM_VTEX_ORDER_STATUS,
	DVOS.STATUS,
	DVOS.STATUS_DESCRIPTION,
	DVOS.CREATE_DATE AS CREATE_DATE_DIM_VTEX_ORDER_STATUS,

	DVPS.SUR_KEY AS SUR_KEY_DIM_VTEX_PAYMENT_STATUS,
	DVPS.PAYMENT_STATUS,
	DVPS.CREATE_DATE AS CREATE_DATE_DIM_VTEX_PAYMENT_STATUS,
	DVPS.UPDATE_DATE AS UPDATE_DATE_DIM_VTEX_PAYMENT_STATUS,

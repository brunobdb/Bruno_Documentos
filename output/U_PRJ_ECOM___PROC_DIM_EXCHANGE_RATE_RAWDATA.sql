CREATE PROCEDURE U_PRJ_ECOM.PROC_DIM_EXCHANGE_RATE_RAWDATA
 LANGUAGE SQLSCRIPT AS
 BEGIN     
 
 truncate TABLE U_PRJ_ECOM.DIM_EXCHANGE_RATE_RAWDATA
;
 insert into U_PRJ_ECOM.DIM_EXCHANGE_RATE_RAWDATA
SELECT  DISTINCT
	B.ID AS "SUBSIDIARY_ID",
	B.CURRENCY, 
	A.FROM_CURRENCY AS "REFERENCE_CURRENCY",
 	a.VALID_FROM  AS "REFERENCE_DATE",
a.VALID_FROM  AS "INSERT_DATE",
	TO_DECIMAL (A.EXCHANGE_RATE ) AS "VALUE"
	 
	
	FROM "OW_LAO"."FT_AP2_EXCHANGE_RATE" A
	LEFT JOIN
	(
	SELECT DISTINCT 
	SU.ID, 
	SU.COUNTRY, 
	CASE WHEN SU.COUNTRY = 'Panama' THEN 'USD' ELSE SU.CURRENCY  END AS "CURRENCY" 
	FROM U_PRJ_ECOM.DIM_SUBSIDIARY SU
	)
	B ON A.TO_CURRENCY = B.CURRENCY 
	
	
	WHERE 
	B.CURRENCY IS NOT NULL
 
	;
		 
	
 insert into U_PRJ_ECOM.DIM_EXCHANGE_RATE_RAWDATA
SELECT  DISTINCT
	B.ID AS "SUBSIDIARY_ID",
	B.CURRENCY, 
	A.FROM_CURRENCY AS "REFERENCE_CURRENCY",
 	CURRENT_DATE AS "REFERENCE_DATE",
 	CURRENT_TIMESTAMP AS "INSERT_DATE",
	TO_DECIMAL (A.EXCHANGE_RATE ) AS "VALUE"
	 
	
	FROM "OW_LAO"."FT_AP2_EXCHANGE_RATE" A
	LEFT JOIN
	(
	SELECT DISTINCT 
	SU.ID, 
	SU.COUNTRY, 
	CASE WHEN SU.COUNTRY = 'Panama' THEN 'USD' ELSE SU.CURRENCY  END AS "CURRENCY" 
	FROM U_PRJ_ECOM.DIM_SUBSIDIARY SU
	)
	B ON A.TO_CURRENCY = B.CURRENCY 
	
	
	WHERE 
	B.CURRENCY IS NOT NULL
	AND CAST (A.VALID_FROM AS DATE) = (SELECT MAX(CAST ( R.VALID_FROM  AS DATE)) 
	FROM "OW_LAO".FT_AP2_EXCHANGE_RATE R)
	
	AND not exists(                        
                        select 1
                          from U_PRJ_ECOM.DIM_EXCHANGE_RATE_RAWDATA
                         where A.VALID_FROM = CURRENT_DATE 
                   )
 
 
;
	
	
	END
CREATE PROCEDURE U_PRJ_ECOM.PROC_ODS_SALES_CONTROL_TOWER_TABLE_RAW_VTEX_SSG_BR_SHOP
LANGUAGE SQLSCRIPT AS
BEGIN
DROP TABLE U_PRJ_ECOM.TMP_ECOM_HQ_ORDERS_PRODUCTS_COMBO;
CREATE COLUMN TABLE U_PRJ_ECOM.TMP_ECOM_HQ_ORDERS_PRODUCTS_COMBO AS (
SELECT
  "Country_cd",
  "Order_Id",
  "Product_Name",
  "Reference_Code(combo_sku)",
  "SKU(product_code)",
  "ORDER_CREATION_DATE"
FROM (
  SELECT  
    COUNTRY_CD AS "Country_cd",
    PO_ORDERID AS "Order_Id",
    PO_PRODNAME AS "Product_Name",
    PO_SKU_KIT AS "Reference_Code(combo_sku)",
    PO_SKU AS "SKU(product_code)",
    PO_DATE AS ORDER_CREATION_DATE
  FROM OW_LAO.ODS_SALES_CONTROL_TOWER_TABLE 
  WHERE CLIENT_SUBSIDIARY_ID IN (1,6)
    AND PO_SKU_KIT LIKE 'F-%'
  UNION ALL 
  SELECT
    COUNTRY_CD AS "Country_cd",
    PO_ORDERID AS "Order_Id",
    PO_PRODNAME AS "Product_Name",
    PO_SKU_KIT AS "Reference_Code(combo_sku)",
    PO_SKU AS "SKU(product_code)",
    PO_DATE AS ORDER_CREATION_DATE
  FROM OW_LAO.ODS_SALES_CONTROL_TOWER_TABLE 
  WHERE CLIENT_SUBSIDIARY_ID = 1
    AND PO_SKU_KIT LIKE '%combo%'
) a
WHERE NOT EXISTS (
  SELECT 1
  FROM U_PRJ_ECOM.RAW_ECOM_HQ_ORDERS_PRODUCTS_COMBO AA
  WHERE AA.ORDER_ID = a."Order_Id"
    AND AA.REFERENCE_CODE = a."Reference_Code(combo_sku)"
    AND AA.SKU = a."SKU(product_code)"
    AND AA.COUNTRY_CD = a."Country_cd"
)
AND CAST("ORDER_CREATION_DATE" AS DATE) BETWEEN CAST(ADD_DAYS(NOW(), -15) AS DATE)
                                            AND CAST(ADD_DAYS(NOW(), 0) AS DATE)
);
INSERT INTO U_PRJ_ECOM.RAW_ECOM_HQ_ORDERS_PRODUCTS_COMBO
SELECT 
  a.COUNTRY_CD, 
  a.ORDER_ID,
  a.PRODUCT_NAME,
  a.REFERENCE_CODE,
  a.SKU,
  a.ORDER_CREATION_DATE,
  CURRENT_TIMESTAMP AS "INSERT_DATE"
FROM U_PRJ_ECOM.TMP_ECOM_HQ_ORDERS_PRODUCTS_COMBO a
WHERE NOT EXISTS (
  SELECT 1
  FROM U_PRJ_ECOM.RAW_ECOM_HQ_ORDERS_PRODUCTS_COMBO AA
  WHERE AA.ORDER_ID = a.ORDER_ID
    AND AA.REFERENCE_CODE = a.REFERENCE_CODE
    AND AA.SKU = a.SKU
    AND AA.COUNTRY_CD = a.COUNTRY_CD
);
END;

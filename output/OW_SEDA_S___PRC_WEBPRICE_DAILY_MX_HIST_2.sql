CREATE PROCEDURE OW_SEDA_S.PRC_WEBPRICE_DAILY_MX_HIST_2 (IN PREVIOUS_DAYS INT, DATE_REF VARCHAR(10)) AS
--DO 
BEGIN
	
tmp_mx=
SELECT
	mmwci.MARCA,
	mmwci.CATEGORY,
	ocwa.ITEM,
	mmwci.MARKETING_NAME,
	mmwci.STORAGE,
	mmwci.COLOR,
	ocwa.STORE_NAME,
	CASE WHEN ocwa.STORE_NAME = 'Mercado Livre' AND UPPER(ocwa.MARKETPLACE_NAME) LIKE '%MERCADO LIVRE ELETRONICOS%' THEN NULL ELSE ocwa.MARKETPLACE_NAME END MARKETPLACE_NAME,
	ocwa.PRECO_A_VISTA,
	ocwa.PRECO_A_PRAZO,
	ocwa.PARCELAS,
	ocwa.PRECO_PARCELAS,
	ocwa.INPUT_DATE 
FROM OW_SEDA_S.ODS_CE_WEBPRICE_API ocwa 
INNER JOIN OW_SEDA_S.MAP_MX_WEBPRICE_CODIGO_INTERNO mmwci ON ocwa.ITEM = mmwci.CODIGO_INTERNO
WHERE TO_DATE(INPUT_DATE) BETWEEN TO_DATE('2025-04-05') AND TO_DATE('2025-04-06');
	
tmp_complete = 
SELECT * FROM (
SELECT 
	wb.MARCA BRAND,
	UPPER(wb.STORE_NAME) STORE_NAME,
	COALESCE(UPPER(CASE WHEN wb.STORE_NAME = wb.MARKETPLACE_NAME THEN '-' ELSE wb.MARKETPLACE_NAME END),'-') MARKETPLACE_NAME,
	wb.CATEGORY,
	wb.ITEM,
	wb.MARKETING_NAME,
	wb.STORAGE,
	wb.COLOR,
	TO_DATE(wb.INPUT_DATE) DATE_COLLECTED,
	'Preco a Vista' PRICE_TYPE,
	MAX(wb.PRECO_A_VISTA) MAX_PRICE,
	AVG(wb.PRECO_A_VISTA) AVG_PRICE,
	MIN(wb.PRECO_A_VISTA) MIN_PRICE,
	MAX(moda.MODA_PRECO_A_VISTA) MODA,
	MIN(recent.PRECO_A_VISTA) RECENT_PRICE,
	MAX(COALESCE(recent.LOAD_DATE, wb.INPUT_DATE)) LOAD_DATE
FROM :tmp_mx wb
LEFT JOIN 
(
SELECT ITEM, STORE_NAME, MARKETPLACE_NAME, INPUT_DATE, AVG(PRECO_A_VISTA) MODA_PRECO_A_VISTA FROM (
	SELECT 
		ITEM, 
		STORE_NAME STORE_NAME, 
		MARKETPLACE_NAME MARKETPLACE_NAME, 
		TO_DATE(INPUT_DATE) INPUT_DATE, 
		PRECO_A_VISTA, 
		COUNT(*), 
		ROW_NUMBER() OVER (PARTITION BY ITEM, STORE_NAME, MARKETPLACE_NAME, TO_DATE(INPUT_DATE) ORDER BY COUNT(*) DESC) ROW_NUM
	FROM :tmp_mx ocwa 
	WHERE 1=1
		--AND ITEM = '32LM625B'
		--AND STORE_NAME = 'Americanas'
		--AND MARKETPLACE_NAME = 'Fast Shop'
	GROUP BY ITEM, STORE_NAME, MARKETPLACE_NAME, TO_DATE(INPUT_DATE), PRECO_A_VISTA)
WHERE row_num = 1
GROUP BY ITEM, STORE_NAME, MARKETPLACE_NAME, INPUT_DATE
) moda
ON 1=1
	AND wb.ITEM = moda.ITEM
	AND wb.STORE_NAME = moda.STORE_NAME
	AND COALESCE(wb.MARKETPLACE_NAME,'-') = COALESCE(moda.MARKETPLACE_NAME,'-')
	AND TO_DATE(wb.INPUT_DATE) = moda.INPUT_DATE
LEFT JOIN 
(
	SELECT 
		ITEM, 
		STORE_NAME STORE_NAME, 
		MARKETPLACE_NAME MARKETPLACE_NAME, 
		TO_DATE(INPUT_DATE) INPUT_DATE, 
		PRECO_A_VISTA,
		ROW_NUMBER() OVER (PARTITION BY ITEM, STORE_NAME, MARKETPLACE_NAME, TO_DATE(INPUT_DATE) ORDER BY PRECO_A_VISTA ASC) ROW_NUM,
		INPUT_DATE LOAD_DATE
	FROM :tmp_mx ocwa 
	WHERE SERIES_ROUND(INPUT_DATE, 'INTERVAL 10 MINUTE') IN (
						SELECT MAX_INPUT_DATE FROM (
							SELECT 
								TO_DATE(INPUT_DATE), 
								SERIES_ROUND(MAX(INPUT_DATE), 'INTERVAL 10 MINUTE') MAX_INPUT_DATE
							FROM :tmp_mx
							GROUP BY
								TO_DATE(INPUT_DATE)
							)
						)
) recent
ON 1=1
	AND wb.ITEM = recent.ITEM
	AND wb.STORE_NAME = recent.STORE_NAME
	AND COALESCE(wb.MARKETPLACE_NAME,'-') = COALESCE(recent.MARKETPLACE_NAME,'-')
	AND to_date(wb.INPUT_DATE) = recent.INPUT_DATE
	AND recent.ROW_NUM = 1
--WHERE wb.MARKETPLACE_NAME IS NULL 
GROUP BY wb.MARCA, wb.STORE_NAME, wb.MARKETPLACE_NAME, wb.CATEGORY, wb.ITEM, wb.MARKETING_NAME, wb.STORAGE, wb.COLOR, TO_DATE(wb.INPUT_DATE)
--HAVING max(moda.MODA_PRECO_A_VISTA) > 0
UNION ALL 
SELECT
	wb.MARCA BRAND,
	UPPER(wb.STORE_NAME) STORE_NAME,
	COALESCE(UPPER(CASE WHEN wb.STORE_NAME = wb.MARKETPLACE_NAME THEN '-' ELSE wb.MARKETPLACE_NAME END),'-') MARKETPLACE_NAME,
	wb.CATEGORY,
	wb.ITEM,
	wb.MARKETING_NAME,
	wb.STORAGE,
	wb.COLOR,
	TO_DATE(wb.INPUT_DATE),
	'Preco a Prazo' PRICE_TYPE,
	MAX(wb.PRECO_A_PRAZO),
	AVG(wb.PRECO_A_PRAZO),
	MIN(wb.PRECO_A_PRAZO),
	MAX(moda.MODA_PRECO_A_PRAZO) MODA,
	MAX(recent.PRECO_A_PRAZO) RECENT_PRICE,
	MAX(COALESCE(recent.LOAD_DATE, wb.INPUT_DATE))
FROM :tmp_mx wb
LEFT JOIN 
(
SELECT ITEM, STORE_NAME, MARKETPLACE_NAME, INPUT_DATE, avg(PRECO_A_PRAZO) MODA_PRECO_A_PRAZO FROM (
	SELECT 
		ITEM, 
		STORE_NAME STORE_NAME, 
		MARKETPLACE_NAME MARKETPLACE_NAME, 
		TO_DATE(INPUT_DATE) INPUT_DATE, 
		PRECO_A_PRAZO, 
		COUNT(*), 
		ROW_NUMBER() OVER (PARTITION BY ITEM, STORE_NAME, MARKETPLACE_NAME, TO_DATE(INPUT_DATE) ORDER BY COUNT(*) DESC) ROW_NUM
	FROM :tmp_mx ocwa 
	WHERE 1=1
		--AND ITEM = '32LM625B'
		--AND STORE_NAME = 'Americanas'
		--AND MARKETPLACE_NAME = 'Fast Shop'
	GROUP BY ITEM, STORE_NAME, MARKETPLACE_NAME, TO_DATE(INPUT_DATE), PRECO_A_PRAZO)
WHERE row_num = 1
GROUP BY ITEM, STORE_NAME, MARKETPLACE_NAME, INPUT_DATE
) moda
ON 1=1
	AND wb.ITEM = moda.ITEM
	AND wb.STORE_NAME = moda.STORE_NAME
	AND COALESCE(wb.MARKETPLACE_NAME,'-') = COALESCE(moda.MARKETPLACE_NAME,'-')
	AND TO_DATE(wb.INPUT_DATE) = moda.INPUT_DATE
LEFT JOIN 
(
	SELECT 
		ITEM, 
		STORE_NAME STORE_NAME, 
		MARKETPLACE_NAME MARKETPLACE_NAME, 
		TO_DATE(INPUT_DATE) INPUT_DATE, 
		PRECO_A_PRAZO,
		ROW_NUMBER() OVER (PARTITION BY ITEM, STORE_NAME, MARKETPLACE_NAME, to_date(INPUT_DATE) ORDER BY PRECO_A_PRAZO ASC) ROW_NUM,
		INPUT_DATE LOAD_DATE
	FROM :tmp_mx ocwa 
	WHERE SERIES_ROUND(INPUT_DATE, 'INTERVAL 10 MINUTE') IN (
						SELECT MAX_INPUT_DATE FROM (
							SELECT 
								TO_DATE(INPUT_DATE), 
								SERIES_ROUND(MAX(INPUT_DATE), 'INTERVAL 10 MINUTE') MAX_INPUT_DATE
							FROM :tmp_mx
							GROUP BY
								TO_DATE(INPUT_DATE)
							)
						)
) recent
ON 1=1
	AND wb.ITEM = recent.ITEM
	AND wb.STORE_NAME = recent.STORE_NAME
	AND COALESCE(wb.MARKETPLACE_NAME,'-') = COALESCE(recent.MARKETPLACE_NAME,'-')
	AND TO_DATE(wb.INPUT_DATE) = recent.INPUT_DATE
	AND recent.ROW_NUM = 1
--WHERE wb.MARKETPLACE_NAME IS NULL 
GROUP BY wb.MARCA, wb.STORE_NAME, wb.MARKETPLACE_NAME, wb.CATEGORY, wb.ITEM, wb.MARKETING_NAME, wb.STORAGE, wb.COLOR, TO_DATE(wb.INPUT_DATE)
--HAVING max(moda.MODA_PRECO_A_PRAZO) > 0
)
--WHERE DATE_COLLECTED BETWEEN ADD_DAYS(CURRENT_DATE, -1 * PREVIOUS_DAYS) AND CURRENT_DATE;
;
DELETE FROM OW_SEDA_S.ODS_WEBPRICE_TRACKING_DAILY_MX owtdt 
WHERE EXISTS (SELECT 1 FROM :TMP_COMPLETE t WHERE owtdt.DATE_COLLECTED = t.DATE_COLLECTED);
INSERT INTO OW_SEDA_S.ODS_WEBPRICE_TRACKING_DAILY_MX
SELECT
	BRAND,
	STORE_NAME,
	MARKETPLACE_NAME,
	CATEGORY,
	ITEM,
	MARKETING_NAME,
	CASE 
		WHEN CATEGORY = 'HHP' THEN REPLACE(REPLACE(REPLACE(MARKETING_NAME, 'Galaxy ', ''), 'Galaxy-', ''), 'Ultra', 'U') || ' (' || STORAGE  || ')'
		WHEN CATEGORY = 'TAB' THEN MARKETING_NAME || ' (' || STORAGE  || ')'
		ELSE MARKETING_NAME 
	END MODEL_NAME,
	STORAGE,
	COLOR,
	DATE_COLLECTED,
	vcc.YEARWEEK,
	PRICE_TYPE,
	MAX_PRICE,
	AVG_PRICE,
	MIN_PRICE,
	MODA,
	RECENT_PRICE,
	CASE 
		WHEN PRICE_TYPE = 'Preco a Prazo' THEN REFERENCE_PRICE_INSTALLMENT
		WHEN PRICE_TYPE = 'Preco a Vista' THEN REFERENCE_PRICE_SPOT
	END REFERENCE_PRICE
FROM :TMP_COMPLETE tc
INNER JOIN OW_SEDA_S.VW_CE_CALENDAR vcc ON vcc."DATE" = tc.DATE_COLLECTED
LEFT JOIN OW_SEDA_S.ODS_MX_REFERENCE_PRICE omrp 
ON 1=1
	AND omrp.WEEKNUM = vcc.YEARWEEK
	AND omrp.PRODUCT_NAME = CASE 
								WHEN CATEGORY = 'HHP' THEN REPLACE(REPLACE(REPLACE(MARKETING_NAME, 'Galaxy ', ''), 'Galaxy-', ''), 'Ultra', 'U') || ' (' || STORAGE  || ')'
								WHEN CATEGORY = 'TAB' THEN MARKETING_NAME || ' (' || STORAGE  || ')'
								WHEN CATEGORY = 'NPC' THEN ITEM
								ELSE MARKETING_NAME 
							END
WHERE STORE_NAME IS NOT NULL;
	
END
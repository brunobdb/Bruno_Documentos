CREATE PROCEDURE OW_SEDA_S.PRC_TT_AV_CHECKLIST_DE_EXECUCAO_785 AS
--DO 
BEGIN
	
TMP=
SELECT
	otabf.CAMPAIGN_ID,
	otq.CYCLE_ID,
	otabf.ITEM_ID,
	otabf.VISIT_ID,
	ots.CODE,
	otc.NAME COLLABORATOR_NAME,
	otc.ROLE_NAME,
	otc.COORDINATOR,
	otc.SUPERVISOR,
	otq.FORMULARY_ID,
	otf.NAME FORMULARY_NAME,
	otabf.PRODUCT_ID,
	otp.NAME ITEM_NAME,
	otabf.ITEM_VALIDATED,
	otabf.ITEM_USER_VALIDATED,
	otabf.ITEM_DATE_VALIDATION,
	otabf.ITEM_OBSERVATION,
	MAX(otabf.ANSWERED_AT) ANSWERED_AT,
	MAX(otabf.LOAD_DATE) LOAD_DATE,
	CASE
		WHEN otq.NAME LIKE '%QUAIS TIPOS DE SELO/ADESIVO %' THEN 'SELO/ADESIVO'
		WHEN otq.NAME LIKE '%QUAIS TIPOS DE TESTEIRA/ORELHA/TOPPER %' THEN 'TESTEIRA/ORELHA/TOPPER'
		WHEN otq.NAME LIKE '%QUAIS TIPOS DE MATERIAL POP GERAL ESTÃO %' THEN 'MATERIAL POP GERAL'
		WHEN otq.NAME LIKE '%QUAIS TIPOS DE DISPLAY ESTÃO POSITIVADOS%' THEN 'DISPLAY'			 
	END MATERIAIS_POSITIVADOS,
	CASE 
		WHEN 
			 otq.NAME LIKE '%QUAIS TIPOS DE SELO/ADESIVO %'
			OR 
			 otq.NAME LIKE '%QUAIS TIPOS DE TESTEIRA/ORELHA/TOPPER %'
			OR 
			 otq.NAME LIKE '%QUAIS TIPOS DE MATERIAL POP GERAL ESTÃO %'
			OR
			 otq.NAME LIKE '%QUAIS TIPOS DE DISPLAY ESTÃO POSITIVADOS%'
		THEN CONTENT
	END TIPO_DO_MATERIAL_POSITIVADO,
	MAX(CASE WHEN otq.NAME LIKE '%INFORME O SKU DO PRODUTO:%' THEN CONTENT END) AS SKU_DO_PRODUTO,
	MAX(CASE WHEN otq.NAME LIKE '%INFORME A MARCA DO SKU:%' THEN CONTENT END) AS MARCA_DO_PRODUTO,
	MAX(CASE WHEN otq.NAME LIKE '%QUAL OUTRA MARCA?%' THEN CONTENT END) AS OUTRA_MARCA_DO_PRODUTO,
	MAX(CASE WHEN otq.NAME LIKE '%ATENTE-SE PARA OS DETALHES DA COLETA DE PRODUTOS%' THEN CONTENT END) AS CONFIRMACAO_COLETA,
	MAX(CASE WHEN otq.NAME LIKE '%ONDE ESTE SKU ESTÁ EXPOSTO?%' THEN CONTENT END) AS ONDE_ESTE_SKU_ESTA_EXPOSTO,
	MAX(CASE WHEN otq.NAME LIKE '%QUAL OUTRO?%'AND otq."POSITION" IN (6, 25) THEN CONTENT END) AS ONDE_ESTE_SKU_ESTA_EXPOSTO_OUTRO,
	MAX(CASE WHEN otq.NAME LIKE '%FOTO PRÓXIMA DO SOUNDBAR:%' THEN COALESCE(FILE_URL, FILE_URL_PERMANENT) END) AS FOTO_PROXIMA_DO_SOUNDBAR,
	MAX(CASE WHEN otq.NAME LIKE '%FOTO AMPLA DO SOUNDBAR:%' THEN COALESCE(FILE_URL, FILE_URL_PERMANENT) END) AS FOTO_AMPLA_DO_SOUNDBAR,
	MAX(CASE WHEN otq.NAME LIKE '%PREÇO À VISTA:%' THEN CONTENT END) AS PRECO_A_VISTA,
	MAX(CASE WHEN otq.NAME LIKE '%FOTO DA ETIQUETA DE PREÇO:%' THEN COALESCE(FILE_URL, FILE_URL_PERMANENT) END) AS FOTO_DA_ETIQUETA_DE_PRECO,
	MAX(CASE WHEN otq.NAME LIKE '%ESTE SKU POSSUI MATERIAL POSITIVADO?%' THEN CONTENT END) AS ESTE_SKU_POSSUI_MATERIAL_POSITIVADO,
	MAX(CASE WHEN otq.NAME LIKE '%O PRODUTO ESTÁ LIMPO (SEM MARCAS DE DEDO, SEM COLA E SEM POEIRA)?%' THEN CONTENT END) AS O_PRODUTO_ESTA_LIMPO,
	MAX(CASE WHEN otq.NAME LIKE '%FOTO DA SUJEIRA DO PRODUTO:%' THEN COALESCE(FILE_URL, FILE_URL_PERMANENT) END) AS FOTO_DA_SUJEIRA_DO_PRODUTO,
	MAX(CASE WHEN otq.NAME LIKE '%O MOBILIÁRIO ESTÁ LIMPO (SEM MARCAS DE DEDO, SEM COLA E SEM POEIRA)?%' THEN CONTENT END) AS O_MOBILIARIO_ESTA_LIMPO,
	MAX(CASE WHEN otq.NAME LIKE '%FOTO DA SUJEIRA DO MOBILIÁRIO:%' THEN COALESCE(FILE_URL, FILE_URL_PERMANENT) END) AS FOTO_DA_SUJEIRA_DO_MOBILIARIO,
	MAX(CASE WHEN otq.NAME LIKE '%O PRODUTO E O RESPECTIVO MOBILIÁRIO ESTÃO COM OS FIOS E CABOS ORGANIZADOS?%' THEN CONTENT END) AS O_PRODUTO_E_O_RESPECTIVO_MOBILIARIO_ESTAO_LIMPOS_E_COM_FIOS_E_CABOS_ORGANIZADOS,
	MAX(CASE WHEN otq.NAME LIKE '%FOTO DOS FIOS E CABOS DESORGANIZADOS:%' THEN COALESCE(FILE_URL, FILE_URL_PERMANENT) END) AS FOTO_DOS_FIOS_E_CABOS_DESORGANIZADOS,
	MAX(CASE WHEN otq.NAME LIKE '%FOTO DO SKU COM OS MATERIAIS POSITIVADOS:%' THEN COALESCE(FILE_URL, FILE_URL_PERMANENT) END) AS FOTO_DO_SKU_COM_OS_MATERIAIS_POSITIVADOS,
	MAX(CASE WHEN otq.NAME LIKE '%FOTO DE TODOS MATERIAIS POSITIVADOS:%' THEN COALESCE(FILE_URL, FILE_URL_PERMANENT) END) AS FOTOS_DE_TODOS_MATERIAIS_POSITIVADOS
FROM OW_SEDA_S.ODS_TT_ANSWERS otabf 
	INNER JOIN OW_SEDA_S.ODS_TT_QUESTIONS otq ON otq.ID = otabf.QUESTION_ID 
	INNER JOIN OW_SEDA_S.ODS_TT_FORMULARY otf ON otf.ID = otq.FORMULARY_ID
	INNER JOIN OW_SEDA_S.ODS_TT_PROMOTER_CHECKIN otpc ON otpc.ID = otabf.VISIT_ID 
	INNER JOIN OW_SEDA_S.ODS_TT_STORE ots ON ots.ID = otpc.STORE_ID AND ots.CAMPAIGN_ID = otabf.CAMPAIGN_ID 
	LEFT JOIN OW_SEDA_S.ODS_TT_COLLABORATOR otc ON otc.ID = otpc.COLLABORATOR_ID
	LEFT JOIN OW_SEDA_S.ODS_TT_PRODUCTS otp ON otabf.PRODUCT_ID = otp.ID 
	WHERE 1=1 
			AND otabf.CAMPAIGN_ID = 785
			AND otf.NAME = 'SOUNDBAR - CHECKLIST DE EXECUÇÃO'
			--AND ITEM_ID = 89274264 -- 89283791
GROUP BY 
	otabf.CAMPAIGN_ID,
	otq.CYCLE_ID,
	otabf.ITEM_ID,
	otabf.VISIT_ID,
	ots.CODE,
	otc.NAME,
	CASE
		WHEN otq.NAME LIKE '%QUAIS TIPOS DE SELO/ADESIVO %' THEN 'SELO/ADESIVO'
		WHEN otq.NAME LIKE '%QUAIS TIPOS DE TESTEIRA/ORELHA/TOPPER %' THEN 'TESTEIRA/ORELHA/TOPPER'
		WHEN otq.NAME LIKE '%QUAIS TIPOS DE MATERIAL POP GERAL ESTÃO %' THEN 'MATERIAL POP GERAL'
		WHEN otq.NAME LIKE '%QUAIS TIPOS DE DISPLAY ESTÃO POSITIVADOS%' THEN 'DISPLAY'			 
	END,
	CASE 
		WHEN 
			 otq.NAME LIKE '%QUAIS TIPOS DE SELO/ADESIVO %'
			OR 
			 otq.NAME LIKE '%QUAIS TIPOS DE TESTEIRA/ORELHA/TOPPER %'
			OR 
			 otq.NAME LIKE '%QUAIS TIPOS DE MATERIAL POP GERAL ESTÃO %'
			OR
			 otq.NAME LIKE '%QUAIS TIPOS DE DISPLAY ESTÃO POSITIVADOS%'
		THEN CONTENT
	END,
	otc.ROLE_NAME,
	otc.COORDINATOR,
	otc.SUPERVISOR,
	otq.FORMULARY_ID,
	otf.NAME,
	otabf.PRODUCT_ID,
	otp.NAME,
	otabf.ITEM_VALIDATED,
	otabf.ITEM_USER_VALIDATED,
	otabf.ITEM_DATE_VALIDATION,
	otabf.ITEM_OBSERVATION;
TMP_COMPLETE=
SELECT
	CAMPAIGN_ID,
	CYCLE_ID,
	ITEM_ID,
	VISIT_ID,
	CODE,
	COLLABORATOR_NAME,
	ROLE_NAME,
	COORDINATOR,
	SUPERVISOR,
	FORMULARY_ID,
	FORMULARY_NAME,
	PRODUCT_ID,
	ITEM_NAME,
	CASE 
		WHEN ITEM_NAME = 'OUTRO CONCORRENTE' THEN 'OUTRO'
		ELSE COALESCE(MARCA_DO_PRODUTO, LEFT(ITEM_NAME, LOCATE(ITEM_NAME, ' ') - 1)) 
	END BRAND,
	CASE 
		WHEN ITEM_NAME = 'OUTRO CONCORRENTE' THEN ITEM_NAME
		ELSE COALESCE(REPLACE(SKU_DO_PRODUTO, MARCA_DO_PRODUTO, ''), RIGHT(ITEM_NAME, LENGTH(ITEM_NAME) - LOCATE(ITEM_NAME, ' - ') - 2) )
	END ITEM,
	ITEM_VALIDATED,
	ITEM_USER_VALIDATED,
	ITEM_DATE_VALIDATION,
	ITEM_OBSERVATION,
	ANSWERED_AT,
	LOAD_DATE,
	MAX(CONFIRMACAO_COLETA) OVER (PARTITION BY ITEM_ID) AS CONFIRMACAO_COLETA,
	MAX(ONDE_ESTE_SKU_ESTA_EXPOSTO) OVER (PARTITION BY ITEM_ID) AS ONDE_ESTE_SKU_ESTA_EXPOSTO,
	MAX(ONDE_ESTE_SKU_ESTA_EXPOSTO_OUTRO) OVER (PARTITION BY ITEM_ID) AS ONDE_ESTE_SKU_ESTA_EXPOSTO_OUTRO,
	MAX(FOTO_PROXIMA_DO_SOUNDBAR) OVER (PARTITION BY ITEM_ID) AS FOTO_PROXIMA_DO_SOUNDBAR,
	MAX(FOTO_AMPLA_DO_SOUNDBAR) OVER (PARTITION BY ITEM_ID) AS FOTO_AMPLA_DO_SOUNDBAR,
	MAX(PRECO_A_VISTA) OVER (PARTITION BY ITEM_ID) AS PRECO_A_VISTA,
	MAX(FOTO_DA_ETIQUETA_DE_PRECO) OVER (PARTITION BY ITEM_ID) AS FOTO_DA_ETIQUETA_DE_PRECO,
	MAX(ESTE_SKU_POSSUI_MATERIAL_POSITIVADO) OVER (PARTITION BY ITEM_ID) AS ESTE_SKU_POSSUI_MATERIAL_POSITIVADO,
	MATERIAIS_POSITIVADOS,
	TIPO_DO_MATERIAL_POSITIVADO,
	MAX(O_PRODUTO_ESTA_LIMPO) OVER (PARTITION BY ITEM_ID) AS O_PRODUTO_ESTA_LIMPO,
	MAX(FOTO_DA_SUJEIRA_DO_PRODUTO) OVER (PARTITION BY ITEM_ID) AS FOTO_DA_SUJEIRA_DO_PRODUTO,
	MAX(O_MOBILIARIO_ESTA_LIMPO) OVER (PARTITION BY ITEM_ID) AS O_MOBILIARIO_ESTA_LIMPO,
	MAX(FOTO_DA_SUJEIRA_DO_MOBILIARIO) OVER (PARTITION BY ITEM_ID) AS FOTO_DA_SUJEIRA_DO_MOBILIARIO,
	MAX(O_PRODUTO_E_O_RESPECTIVO_MOBILIARIO_ESTAO_LIMPOS_E_COM_FIOS_E_CABOS_ORGANIZADOS) OVER (PARTITION BY ITEM_ID) AS O_PRODUTO_E_O_RESPECTIVO_MOBILIARIO_ESTAO_LIMPOS_E_COM_FIOS_E_CABOS_ORGANIZADOS,
	MAX(FOTO_DOS_FIOS_E_CABOS_DESORGANIZADOS) OVER (PARTITION BY ITEM_ID) AS FOTO_DOS_FIOS_E_CABOS_DESORGANIZADOS,
	MAX(FOTO_DO_SKU_COM_OS_MATERIAIS_POSITIVADOS) OVER (PARTITION BY ITEM_ID) AS FOTO_DO_SKU_COM_OS_MATERIAIS_POSITIVADOS,
	MAX(FOTOS_DE_TODOS_MATERIAIS_POSITIVADOS) OVER (PARTITION BY ITEM_ID) AS FOTOS_DE_TODOS_MATERIAIS_POSITIVADOS,
	DENSE_RANK() OVER (PARTITION BY CODE ORDER BY VISIT_ID DESC) LAST_VISIT_ID,
	vcc.YEARWEEK WEEKNUM,
	DENSE_RANK() OVER (PARTITION BY CODE, vcc.YEARWEEK ORDER BY VISIT_ID DESC) LAST_VISIT_ID_BY_WEEKNUM,
	DENSE_RANK() OVER (PARTITION BY CODE, YEAR(vcc."DATE"), MONTH(vcc."DATE") ORDER BY VISIT_ID DESC) LAST_VISIT_ID_BY_MONTH
FROM :TMP otabf
INNER JOIN OW_SEDA_S.VW_CE_CALENDAR vcc ON TO_DATE(otabf.ANSWERED_AT) = vcc."DATE";
tmp_delete=
SELECT 
	*
FROM (
	SELECT DISTINCT 
		ITEM_ID, 
		CONFIRMACAO_COLETA,
		ESTE_SKU_POSSUI_MATERIAL_POSITIVADO, MATERIAIS_POSITIVADOS,
		ROW_NUMBER() OVER (PARTITION BY ITEM_ID ORDER BY MATERIAIS_POSITIVADOS ASC) row_num,
		COUNT(1) OVER (PARTITION BY ITEM_ID) contagem
	FROM :TMP_COMPLETE
)
WHERE 1=1
	AND row_num = 1
	AND contagem > 1;
	
TRUNCATE TABLE OW_SEDA_S.FT_TT_AV_CHECKLIST_DE_EXECUCAO_785;
INSERT INTO OW_SEDA_S.FT_TT_AV_CHECKLIST_DE_EXECUCAO_785
SELECT * FROM :TMP_COMPLETE tc
WHERE 1=1
	--AND LAST_VISIT_ID = 1
	AND EXISTS (SELECT 1 FROM OW_SEDA_S.MAP_CE_STORES mcp WHERE mcp.SITE_ID = tc.CODE)
	AND NOT EXISTS (SELECT 1 FROM :TMP_DELETE td WHERE 1=1
												AND tc.ITEM_ID = td.ITEM_ID
												AND tc.CONFIRMACAO_COLETA = td.CONFIRMACAO_COLETA
												AND tc.ESTE_SKU_POSSUI_MATERIAL_POSITIVADO = td.ESTE_SKU_POSSUI_MATERIAL_POSITIVADO
												AND COALESCE(tc.MATERIAIS_POSITIVADOS, '1') = COALESCE(td.MATERIAIS_POSITIVADOS, '1'));
END;
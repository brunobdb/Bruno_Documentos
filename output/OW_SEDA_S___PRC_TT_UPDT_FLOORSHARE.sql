CREATE PROCEDURE OW_SEDA_S.PRC_TT_UPDT_FLOORSHARE AS
--DO 
BEGIN
  
	 
TMP=
  SELECT
 	TO_DATE(ANSWERED_AT) EXECUTION_DATE,
 	TO_TIME(ANSWERED_AT) EXECUTION_TIME,
 	CODE SITE_ID,
 	'CTV' CATEGORY,
 	ITEM,
 	PRECO_A_VISTA SPOT_PRICE,
 	NULL INSTALLMENT_PRICE,
 	BRAND,
 	WEEKNUM,
 	ONDE_ESTE_SKU_ESTA_EXPOSTO LOCATION,
 	FOTO_AMPLA_DA_TV FOTO_AMPLA,
 	ESTE_SKU_ESTA_EXPOSTO_NA_ENTRADA_DA_LOJA EXPOSTO_NA_ENTRADA_DA_LOJA
  FROM OW_SEDA_S.FT_TT_TV_CHECKLIST_DE_EXECUCAO_785
 
 UNION ALL 
 
   SELECT
 	TO_DATE(ANSWERED_AT) EXECUTION_DATE,
 	TO_TIME(ANSWERED_AT) EXECUTION_TIME,
 	CODE SITE_ID,
 	'SOUNDBAR' CATEGORY,
 	ITEM,
 	PRECO_A_VISTA SPOT_PRICE,
 	NULL INSTALLMENT_PRICE,
 	BRAND,
 	WEEKNUM,
 	ONDE_ESTE_SKU_ESTA_EXPOSTO LOCATION,
 	FOTO_AMPLA_DO_SOUNDBAR FOTO_AMPLA,
 	NULL EXPOSTO_NA_ENTRADA_DA_LOJA
  FROM OW_SEDA_S.FT_TT_AV_CHECKLIST_DE_EXECUCAO_785
 
 UNION ALL 
 
   SELECT
 	TO_DATE(ANSWERED_AT) EXECUTION_DATE,
 	TO_TIME(ANSWERED_AT) EXECUTION_TIME,
 	CODE SITE_ID,
 	'AR CONDICIONADO' CATEGORY,
 	ITEM,
 	PRECO_A_VISTA SPOT_PRICE,
 	NULL INSTALLMENT_PRICE,
 	BRAND,
 	WEEKNUM,
 	ONDE_ESTE_SKU_ESTA_EXPOSTO LOCATION,
 	FOTO_AMPLA_DO_AR_CONDICIONADO FOTO_AMPLA,
 	NULL EXPOSTO_NA_ENTRADA_DA_LOJA
  FROM OW_SEDA_S.FT_TT_RAC_CHECKLIST_DE_EXECUCAO_785
  
  
  UNION ALL 
 
   SELECT
 	TO_DATE(ANSWERED_AT) EXECUTION_DATE,
 	TO_TIME(ANSWERED_AT) EXECUTION_TIME,
 	CODE SITE_ID,
 	'REFRIGERADOR' CATEGORY,
 	ITEM,
 	PRECO_A_VISTA SPOT_PRICE,
 	NULL INSTALLMENT_PRICE,
 	BRAND,
 	WEEKNUM,
 	ONDE_ESTE_SKU_ESTA_EXPOSTO LOCATION,
 	FOTO_EXTERNA_DO_REFRIGERADOR FOTO_AMPLA,
 	NULL EXPOSTO_NA_ENTRADA_DA_LOJA
  FROM OW_SEDA_S.FT_TT_REF_CHECKLIST_DE_EXECUCAO_785
  
  UNION ALL 
 
   SELECT
 	TO_DATE(ANSWERED_AT) EXECUTION_DATE,
 	TO_TIME(ANSWERED_AT) EXECUTION_TIME,
 	CODE SITE_ID,
 	'LAVADORAS' CATEGORY,
 	ITEM,
 	PRECO_A_VISTA SPOT_PRICE,
 	NULL INSTALLMENT_PRICE,
 	BRAND,
 	WEEKNUM,
 	ONDE_ESTE_SKU_ESTA_EXPOSTO LOCATION,
 	FOTO_AMPLA_DA_LAVADORA FOTO_AMPLA,
 	NULL EXPOSTO_NA_ENTRADA_DA_LOJA
  FROM OW_SEDA_S.FT_TT_WM_CHECKLIST_DE_EXECUCAO_785;
 
TMP_COMPLETE=
SELECT 
	EXECUTION_DATE,
	MAX(EXECUTION_TIME) EXECUTION_TIME,
	SITE_ID,
	CATEGORY,
	ITEM,
	SPOT_PRICE,
	INSTALLMENT_PRICE,
	BRAND,
	WEEKNUM,
	LOCATION,
	FOTO_AMPLA,
	EXPOSTO_NA_ENTRADA_DA_LOJA
FROM (
	SELECT DISTINCT
		EXECUTION_DATE,
		EXECUTION_TIME,
		SITE_ID,
		CATEGORY,
		CASE 
			WHEN LENGTH(COALESCE(mtsr.ITEM, TRIM(UPPER(t.ITEM)))) > 30 THEN 'OUTRO'
			ELSE COALESCE(mtsr.ITEM, TRIM(UPPER(t.ITEM)))
		END ITEM,
		SPOT_PRICE,
		INSTALLMENT_PRICE,
		BRAND,
		WEEKNUM,
		LOCATION,
		FOTO_AMPLA,
		CASE
			WHEN EXPOSTO_NA_ENTRADA_DA_LOJA LIKE '%SIM%' THEN 'YES'
			WHEN EXPOSTO_NA_ENTRADA_DA_LOJA LIKE '%NÃO%' THEN 'NO'
		END EXPOSTO_NA_ENTRADA_DA_LOJA
	FROM :TMP t
	LEFT JOIN OW_SEDA_S.MAP_TT_SKU_RENAME mtsr ON mtsr.ITEM_RAW = t.ITEM
	WHERE 1=1
		--AND to_date(EXECUTION_DATE) = '2023-10-03'
		--AND SITE_ID = 'C820_33041260124726'
		AND COALESCE(mtsr.ITEM, TRIM(UPPER(t.ITEM))) IS NOT NULL
)
GROUP BY
	EXECUTION_DATE,
	SITE_ID,
	CATEGORY,
	ITEM,
	SPOT_PRICE,
	INSTALLMENT_PRICE,
	BRAND,
	WEEKNUM,
	LOCATION,
	FOTO_AMPLA,
	EXPOSTO_NA_ENTRADA_DA_LOJA;
DELETE FROM OW_SEDA_S.FT_CE_PRICE_STORE fcps
WHERE 1=1
	AND EXISTS (SELECT 1 FROM :TMP_COMPLETE t 
						LEFT JOIN OW_SEDA_S.MAP_TT_SKU_RENAME mtsr ON mtsr.ITEM_RAW = t.ITEM
					WHERE 1=1
						AND fcps."SITE ID" = t.SITE_ID
						--AND fcps.ITEM = COALESCE(mtsr.ITEM, TRIM(UPPER(t.ITEM))) 
						AND fcps."EXECUTION DATE" = t.EXECUTION_DATE
				);
 
INSERT INTO OW_SEDA_S.FT_CE_PRICE_STORE("EXECUTION DATE", "EXECUTION TIME", "SITE ID", CATEGORY, ITEM, "SPOT PRICE", "INSTALLMENT PRICE", BRAND, WEEKNUM, LOCATION , FOTO_AMPLA, EXPOSTO_NA_ENTRADA_DA_LOJA)
SELECT * FROM :TMP_COMPLETE;
 
END;
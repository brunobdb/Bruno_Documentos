CREATE PROCEDURE OW_SEDA_S.PRC_TV_UPDT_INCH_RANGE AS 
  BEGIN
  UPDATE mcp SET 
  INCH_RANGE_ITEM =
  	CASE
	WHEN INCHES_ITEM < 32 THEN '< 32"'
	WHEN INCHES_ITEM = 32 THEN '32"'
	WHEN INCHES_ITEM > 32 AND INCHES_ITEM <= 39 THEN '33" - 39"'
	WHEN INCHES_ITEM >= 40 AND INCHES_ITEM <= 43 THEN '40" - 43"'
	WHEN INCHES_ITEM >= 44 AND INCHES_ITEM <= 46 THEN '44" - 46"'
	WHEN INCHES_ITEM >= 47 AND INCHES_ITEM <= 49 THEN '47" - 49"'
	WHEN INCHES_ITEM >= 50 AND INCHES_ITEM <= 54 THEN '50" - 54"'
	WHEN INCHES_ITEM >= 50 AND INCHES_ITEM <= 54 THEN '50" - 54"'
	WHEN INCHES_ITEM >= 55 AND INCHES_ITEM <= 59 THEN '55" - 59"'
	WHEN INCHES_ITEM >= 60 AND INCHES_ITEM <= 69 THEN '60" - 69"'
	WHEN INCHES_ITEM >= 70 AND INCHES_ITEM <= 74 THEN '70" - 74"'
	WHEN INCHES_ITEM = 75 THEN '75"'
	WHEN INCHES_ITEM >= 76 AND INCHES_ITEM <= 79 THEN '76" - 79"'
	WHEN INCHES_ITEM >= 80 AND INCHES_ITEM <= 90 THEN '80" - 90"'
	WHEN INCHES_ITEM > 90 THEN '> 90"'
END
  FROM OW_SEDA_S.MAP_CE_PRODUCTS mcp 
  WHERE 1=1
  		AND CATEGORY_ITEM = 'TV'
  		AND INCHES_ITEM IS NOT NULL;
	END

CREATE  PROCEDURE OW_SEDA_S.PROC_NERP_ZRSDD6A120_OUTBOUND_TRACKING_SCM 
LANGUAGE SQLSCRIPT AS
BEGIN
 --Inserir dados no RAW_DATA a partir da tabela TMP
  --Delete dados da tabela RAW_DATA que tenham o mesmo FILE_NAME que o da tabela TMP 
  DELETE FROM OW_SEDA_S.RAW_NERP_ZRSDD6A120_SALES_ORDER_TRACKING_SCM RD
  WHERE RD.FILE_NAME = (SELECT DISTINCT FILE_NAME FROM OW_SEDA_S.TMP_NERP_ZRSDD6A120_SALES_ORDER_TRACKING_SCM);
 
 --Inserir dados na tabela 
 INSERT INTO OW_SEDA_S.RAW_NERP_ZRSDD6A120_SALES_ORDER_TRACKING_SCM
 SELECT * FROM OW_SEDA_S.TMP_NERP_ZRSDD6A120_SALES_ORDER_TRACKING_SCM;
TRUNCATE TABLE OW_SEDA_S.TF1_NERP_ZRSDD6A120_SALES_ORDER_TRACKING_SCM
;
TRUNCATE TABLE OW_SEDA_S.TF2_NERP_ZRSDD6A120_SALES_ORDER_TRACKING_SCM
;
/* ==========================================================
  get distinct values only
========================================================== */
INSERT INTO OW_SEDA_S.TF1_NERP_ZRSDD6A120_SALES_ORDER_TRACKING_SCM
SELECT DISTINCT
       IFNULL(RAW.SALES_DOCUMENT,'') ||'||'|| IFNULL(RAW.DELIVERY,'') ||'||'|| IFNULL(RAW.MATERIAL,'') ||'||'|| IFNULL(RAW.ITEM,'') AS "ID",
       RAW.*
    FROM
    	OW_SEDA_S.TMP_NERP_ZRSDD6A120_SALES_ORDER_TRACKING_SCM RAW
    WHERE
    	1=1
    	AND RAW.SALES_DOCUMENT IS NOT NULL
    	--AND RAW.DELIVERY IS NOT NULL
    	AND RAW.MATERIAL IS NOT NULL
    	AND RAW.ITEM IS NOT NULL
      	  	
;
/* ==========================================================
  get row_number = 1
========================================================== */
INSERT INTO OW_SEDA_S.TF2_NERP_ZRSDD6A120_SALES_ORDER_TRACKING_SCM
SELECT
	ID
	, CUSTOMER_PO
	, SALES_DOCUMENT
	, DELIVERY
	, ITEM
	, MATERIAL
	, ITEM_DESCR
	, ITEM_DIVISION
	, SALES_DOC_TYPE
	, SOLD_TO_PARTY
	, NAME
	, SHIP_TO_PARTY
	, SHIP_TO_PARTY_NAME
	, ORDER_QTY_BASE
	, BASE_UNIT
	, OPEN_QTY_BASE
	, SO_NET_PRICE
	, SO_NET_VALUE
	, COST
	, MARGIN_RATE
	, SO_CURR
	, SO_CREATE_ON
	, SO_CREATE_ON_TIME
	, FIRST_SC_DATE
	, SALES_ORG
	, DISTR_CHANNEL
	, DIVISION
	, PLANT
	, STOR_LOC
	, ACCOUNT_CODE
	, ACCOUNT_NAME
	, GC_ID_GSCM
	, GC_NAME
	, AP1_CODE
	, AP1_NAME
	, AP2_CODE
	, AP2_NAME
	, SCM_SITE_ID
	, TRANSPORT_ZONE
	, ITEM_1
	, DELIVERY_QTY_BASE
	, DOCUMENT_DATE
	, DO_CREATE_ON
	, DO_CREATE_ON_TIME
	, SR_NO
	, SR_ITEM
	, SR_DATE
	, SR_TYPE
	, "1ST_GI_NO"
	, ITEM_2
	, "1ST_GI_DATE"
	, "1ST_GI_QTY"
	, "1ST_GI_CREATE_ON"
	, "1ST_GI_CREATE_ON_TIM"
	, "1ST_SCH_TYPE"
	, "2ND_GI_NO"
	, ITEM_3
	, "2ND_GI_QTY"
	, "2ND_GI_CREATE_ON"
	, "2ND_GI_CREATE_ON_TIM"
	, BILLING_DOC
	, BILLED_QTY_BASE
	, BILLING_NET_VALUE
	, BILLING_CURR
	, BILLING_DATE
	, BILLING_CREATE_ON
	, BILLING_CREATE_ON_TI
	, PARTIAL_DELIVERY_SEQ
	, DELIVERY_BLOCK
	, ORDER_REASON
	, REJECT_REASON_1
	, REJECT_REASON_2
	, REJECTION_STS
	, ORDER_QTY
	, CONFIRMED_QTY
	, SPEC_PROCESSING
	, MAT_AVAIL_DATE
	, ITEM_CATEGORY
	, SHIPPING_TYPE
	, "1ST_SCH_DATE"
	, YOUR_REFERENCE
	, FINAL_SCH_DATE
	, DO_LOCAL_CREATE_ON_D
	, DO_LOCAL_CREATE_ON_T
	, "1ST_GI_LOCAL_CREATE"
	, "1ST_GI_LOCAL_CREATE_1"
	, PAYT_TERMS
	, INCOTERMS
	, INCOTERMS_2
	, DELIVERY_TYPE
	, NET_VALUE_DOC_BASE
	, DELIVERY_DATE
	, REASON
	, GR_COMPLETED
	, BILLING_BLOCK
	, POSTING_DATE
	, REJECTION_REASON
	, RDD_HEADER
	, SR_TYPE_DESC
	, MATERIAL_GROUP
	, SO_LOCAL_CREATE_ON_D
	, SO_LOCAL_CREATE_ON_T
	, CREATED_BY
	, FILE_NAME
	, LOAD_DATE
	, CHANGED_ON
FROM
	(
	SELECT
		ROW_NUMBER() OVER(PARTITION BY ID ORDER BY LOAD_DATE DESC) AS ROW_NUMBER
		, TF1.*
	FROM
		OW_SEDA_S.TF1_NERP_ZRSDD6A120_SALES_ORDER_TRACKING_SCM TF1
	)
WHERE
	1=1
	AND ROW_NUMBER = 1
;
/* ==========================================================
  delete from ods the rows with same key as in the tf2
========================================================== */
DELETE FROM
	OW_SEDA_S.ODS_NERP_ZRSDD6A120_SALES_ORDER_TRACKING_SCM ODS
WHERE
    ODS.ID IN (
    	SELECT DISTINCT ID FROM OW_SEDA_S.TF2_NERP_ZRSDD6A120_SALES_ORDER_TRACKING_SCM
    );
/* ==========================================================
  insert into ods the updated data from tf2
========================================================== */
INSERT INTO OW_SEDA_S.ODS_NERP_ZRSDD6A120_SALES_ORDER_TRACKING_SCM
SELECT * FROM OW_SEDA_S.TF2_NERP_ZRSDD6A120_SALES_ORDER_TRACKING_SCM
;
END;
--DO 
BEGIN
	
TMP=
SELECT
	otabf.CAMPAIGN_ID,
	otq.CYCLE_ID,
	otabf.ITEM_ID,
	otabf.VISIT_ID,
	ots.CODE,
	otc.NAME COLLABORATOR_NAME,
	otc.ROLE_NAME,
	otc.COORDINATOR,
	otc.SUPERVISOR,
	otq.FORMULARY_ID,
	otf.NAME FORMULARY_NAME,
	otabf.PRODUCT_ID,
	otp.NAME ITEM_NAME,
	otabf.ITEM_VALIDATED,
	otabf.ITEM_USER_VALIDATED,
	otabf.ITEM_DATE_VALIDATION,
	otabf.ITEM_OBSERVATION,
	MAX(otabf.ANSWERED_AT) ANSWERED_AT,
	MAX(otabf.LOAD_DATE) LOAD_DATE,
	CASE
		WHEN otq.NAME LIKE '%QUAIS TIPOS DE INFOPANEL %' THEN 'INFOPANEL'
		WHEN otq.NAME LIKE '%QUAIS TIPOS DE SELO/ADESIVO %' THEN 'SELO/ADESIVO'
		WHEN otq.NAME LIKE '%QUAIS TIPOS DE TESTEIRA/ORELHA/TOPPER %' THEN 'TESTEIRA/ORELHA/TOPPER'
		WHEN otq.NAME LIKE '%QUAIS TIPOS DE MATERIAL POP GERAL ESTÃO %' THEN 'MATERIAL POP GERAL'
		WHEN otq.NAME LIKE '%QUAIS TIPOS DE PLACA DE LOGO ESTÃO POSITIVADAS%' THEN 'PLACA DE LOGO'
		WHEN otq.NAME LIKE '%QUAIS TIPOS DE LOGO ESTÃO POSITIVADOS%' THEN 'LOGO'
		WHEN otq.NAME LIKE '%QUAIS TIPOS DE DISPLAY/BOTÃO ESTÃO POSITIVADOS%' THEN 'DISPLAY/BOTÃO'			 
		WHEN otq.NAME LIKE '%QUAIS TIPOS DE MOLDURA ESTÃO POSITIVADAS%' THEN 'MOLDURA'
	END MATERIAIS_POSITIVADOS,
	CASE 
		WHEN otq.NAME LIKE '%QUAIS TIPOS DE INFOPANEL %' 
			OR 
			 otq.NAME LIKE '%QUAIS TIPOS DE SELO/ADESIVO %'
			OR 
			 otq.NAME LIKE '%QUAIS TIPOS DE TESTEIRA/ORELHA/TOPPER %'
			OR 
			 otq.NAME LIKE '%QUAIS TIPOS DE MATERIAL POP GERAL ESTÃO %'
			OR
			 otq.NAME LIKE '%QUAIS TIPOS DE PLACA DE LOGO ESTÃO POSITIVADAS%'
			OR
			 otq.NAME LIKE '%QUAIS TIPOS DE LOGO ESTÃO POSITIVADOS%'
			OR 
			 otq.NAME LIKE '%QUAIS TIPOS DE DISPLAY/BOTÃO ESTÃO POSITIVADOS%'
			OR 
			 otq.NAME LIKE '%QUAIS TIPOS DE MOLDURA ESTÃO POSITIVADAS%'
		THEN CONTENT
	END TIPO_DO_MATERIAL_POSITIVADO,
	MAX(CASE WHEN otq.NAME LIKE '%O PRODUTO ESTÁ DISPONÍVEL NESTA LOJA? (SEJA NO ESTOQUE DA LOJA OU EXPOSTO)%' THEN CONTENT END) AS O_PRODUTO_ESTA_DISPONIVEL_NESTA_LOJA_SEJA_NO_ESTOQUE_DA_LOJA_OU_EXPOSTO,
	MAX(CASE WHEN otq.NAME LIKE '%O PRODUTO ESTÁ EXPOSTO?%' THEN CONTENT END) AS O_PRODUTO_ESTA_EXPOSTO,
	MAX(CASE WHEN otq.NAME LIKE '%ONDE ESTE SKU ESTÁ EXPOSTO?%' THEN CONTENT END) AS ONDE_ESTE_SKU_ESTA_EXPOSTO,
	MAX(CASE WHEN otq.NAME LIKE '%SE HÁ ESTOQUE E NÃO ESTÁ EXPOSTO, QUAL O MOTIVO?%' THEN CONTENT END) AS SE_HA_ESTOQUE_E_NAO_ESTA_EXPOSTO_QUAL_O_MOTIVO,
	MAX(CASE WHEN otq.NAME LIKE '%PORQUE NÃO HÁ ESTOQUE DO PRODUTO EM LOJA?%' THEN CONTENT END) AS PORQUE_NAO_HA_ESTOQUE_DO_PRODUTO_EM_LOJA,
	MAX(CASE WHEN otq.NAME LIKE '%QUAL O MÓDULO DO SKU?%' THEN CONTENT END) AS QUAL_O_MODULO_DO_SKU,
	MAX(CASE WHEN otq.NAME LIKE '%QUAL A POSIÇÃO DO SKU?%' THEN CONTENT END) AS QUAL_A_POSICAO_DO_SKU,
	MAX(CASE WHEN otq.NAME LIKE '%QUAL O TIPO DA PAREDE ESPECIAL?%' THEN CONTENT END) AS QUAL_O_TIPO_DA_PAREDE_ESPECIAL,
	MAX(CASE WHEN otq.NAME LIKE '%QUAL O TIPO DE RACK?%' THEN CONTENT END) AS QUAL_O_TIPO_DE_RACK,
	MAX(CASE WHEN otq.NAME LIKE '%FOTO PRÓXIMA DA TV:%' THEN FILE_URL END) AS FOTO_PROXIMA_DA_TV,
	MAX(CASE WHEN otq.NAME LIKE '%FOTO AMPLA DA TV:%' THEN FILE_URL END) AS FOTO_AMPLA_DA_TV,
	MAX(CASE WHEN otq.NAME LIKE '%FOTO DA ETIQUETA:%' THEN FILE_URL END) AS FOTO_DA_ETIQUETA,
	MAX(CASE WHEN otq.NAME LIKE '%ESTE SKU ESTÁ COM O VÍDEO DEMO POSITIVADO E ADEQUADO AO MODELO DA TV?%' THEN CONTENT END) AS ESTE_SKU_ESTA_COM_O_VIDEO_DEMO_POSITIVADO_E_ADEQUADO_AO_MODELO_DA_TV,
	MAX(CASE WHEN otq.NAME LIKE '%PORQUE O VÍDEO DEMO CORRETO NÃO ESTÁ POSITIVADO?%' THEN CONTENT END) AS PORQUE_O_VIDEO_DEMO_CORRETO_NAO_ESTA_POSITIVADO,
	MAX(CASE WHEN otq.NAME LIKE '%ESTE SKU ESTÁ COM O E-POP POSITIVADO E ADEQUADO AO MODELO DA TV?%' THEN CONTENT END) AS ESTE_SKU_ESTA_COM_O_EPOP_POSITIVADO_E_ADEQUADO_AO_MODELO_DA_TV,
	MAX(CASE WHEN otq.NAME LIKE '%PORQUE O E-POP CORRETO NÃO ESTÁ POSITIVADO?%' THEN CONTENT END) AS PORQUE_O_EPOP_CORRETO_NAO_ESTA_POSITIVADO,
	MAX(CASE WHEN otq.NAME LIKE '%ESTA LOJA POSSUI INTERNET DISPONÍVEL?%' THEN CONTENT END) AS ESTA_LOJA_POSSUI_INTERNET_DISPONIVEL,
	MAX(CASE WHEN otq.NAME LIKE '%ESTE SKU ESTÁ COM O QR CODE POSITIVADO E ADEQUADO AO MODELO DA TV?%' THEN CONTENT END) AS ESTE_SKU_ESTA_COM_O_QR_CODE_POSITIVADO_E_ADEQUADO_AO_MODELO_DA_TV,
	MAX(CASE WHEN otq.NAME LIKE '%ESTE SKU POSSUI MATERIAL POSITIVADO?%' THEN CONTENT END) AS ESTE_SKU_POSSUI_MATERIAL_POSITIVADO,
	MAX(CASE WHEN otq.NAME LIKE '%POR QUAL MOTIVO NÃO POSSUI MATERIAL POSITIVADO?%' THEN CONTENT END) AS POR_QUAL_MOTIVO_NAO_POSSUI_MATERIAL_POSITIVADO,
	MAX(CASE WHEN otq.NAME LIKE '%O PRODUTO E O RESPECTIVO MOBILIÁRIO ESTÃO LIMPOS E COM FIOS E CABOS ORGANIZADOS?%' THEN CONTENT END) AS O_PRODUTO_E_O_RESPECTIVO_MOBILIARIO_ESTAO_LIMPOS_E_COM_FIOS_E_CABOS_ORGANIZADOS,
	MAX(CASE WHEN otq.NAME LIKE '%FOTO DO SKU COM OS MATERIAIS POSITIVADOS:%' THEN FILE_URL END) AS FOTO_DO_SKU_COM_OS_MATERIAIS_POSITIVADOS,
	MAX(CASE WHEN otq.NAME LIKE '%ESTA LOJA POSSUI FOLHETO 3 EM 1?%' THEN CONTENT END) AS POSSUI_FOLHETO_3_EM_1,
	MAX(CASE WHEN otq.NAME LIKE '%FOTO DO FOLHETO 3 EM 1:%' THEN FILE_URL END) AS FOTO_FOLHETO_3_EM_1,
	MAX(CASE WHEN otq.NAME LIKE '%A LUVA DE CAIXA 3 EM 1 ESTÁ POSITIVADA%' THEN CONTENT END) AS POSSUI_LUVA_3_EM_1,
	MAX(CASE WHEN otq.NAME LIKE '%FOTO DA LUVA DE CAIXA 3 EM 1:%' THEN FILE_URL END) AS FOTO_LUVA_3_EM_1,
	MAX(CASE WHEN otq.NAME LIKE '%A LUVA DE CAIXA TV PLUS ESTÁ POSITIVADA%' THEN CONTENT END) AS POSSUI_LUVA_TV_PLUS,
	MAX(CASE WHEN otq.NAME LIKE '%FOTO DA LUVA DE CAIXA TV PLUS:%' THEN FILE_URL END) AS FOTO_LUVA_TV_PLUS,
	MAX(CASE WHEN otq.NAME LIKE '%O TAKE ONE – 3 EM 1 ESTÁ POSITIVADO%' THEN CONTENT END) AS POSSUI_TAKE_ONE_3_EM_1,
	MAX(CASE WHEN otq.NAME LIKE '%FOTO DO TAKE ONE 3 EM 1:%' THEN FILE_URL END) AS FOTO_TAKE_ONE_3_EM_1
FROM OW_SEDA_S.ODS_TT_ANSWERS otabf 
	INNER JOIN OW_SEDA_S.ODS_TT_QUESTIONS otq ON otq.ID = otabf.QUESTION_ID 
	INNER JOIN OW_SEDA_S.ODS_TT_FORMULARY otf ON otf.ID = otq.FORMULARY_ID
	INNER JOIN OW_SEDA_S.ODS_TT_PROMOTER_CHECKIN otpc ON otpc.ID = otabf.VISIT_ID 
	INNER JOIN OW_SEDA_S.ODS_TT_STORE ots ON ots.ID = otpc.STORE_ID AND ots.CAMPAIGN_ID = otabf.CAMPAIGN_ID 
	INNER JOIN OW_SEDA_S.ODS_TT_COLLABORATOR otc ON otc.ID = otpc.COLLABORATOR_ID
	LEFT JOIN OW_SEDA_S.ODS_TT_PRODUCTS otp ON otabf.PRODUCT_ID = otp.ID 
	WHERE 1=1 
			AND otabf.CAMPAIGN_ID = 363
			AND otf.NAME = 'TV - CHECKLIST DE EXECUÇÃO'
			--AND ITEM_ID = 97018172
GROUP BY 
	otabf.CAMPAIGN_ID,
	otq.CYCLE_ID,
	otabf.ITEM_ID,
	otabf.VISIT_ID,
	ots.CODE,
	otc.NAME,
	CASE
		WHEN otq.NAME LIKE '%QUAIS TIPOS DE INFOPANEL %' THEN 'INFOPANEL'
		WHEN otq.NAME LIKE '%QUAIS TIPOS DE SELO/ADESIVO %' THEN 'SELO/ADESIVO'
		WHEN otq.NAME LIKE '%QUAIS TIPOS DE TESTEIRA/ORELHA/TOPPER %' THEN 'TESTEIRA/ORELHA/TOPPER'
		WHEN otq.NAME LIKE '%QUAIS TIPOS DE MATERIAL POP GERAL ESTÃO %' THEN 'MATERIAL POP GERAL'
		WHEN otq.NAME LIKE '%QUAIS TIPOS DE PLACA DE LOGO ESTÃO POSITIVADAS%' THEN 'PLACA DE LOGO'
		WHEN otq.NAME LIKE '%QUAIS TIPOS DE LOGO ESTÃO POSITIVADOS%' THEN 'LOGO'
		WHEN otq.NAME LIKE '%QUAIS TIPOS DE DISPLAY/BOTÃO ESTÃO POSITIVADOS%' THEN 'DISPLAY/BOTÃO'			 
		WHEN otq.NAME LIKE '%QUAIS TIPOS DE MOLDURA ESTÃO POSITIVADAS%' THEN 'MOLDURA'
	END,
	CASE 
		WHEN otq.NAME LIKE '%QUAIS TIPOS DE INFOPANEL %' 
			OR 
			 otq.NAME LIKE '%QUAIS TIPOS DE SELO/ADESIVO %'
			OR 
			 otq.NAME LIKE '%QUAIS TIPOS DE TESTEIRA/ORELHA/TOPPER %'
			OR 
			 otq.NAME LIKE '%QUAIS TIPOS DE MATERIAL POP GERAL ESTÃO %'
			OR
			 otq.NAME LIKE '%QUAIS TIPOS DE PLACA DE LOGO ESTÃO POSITIVADAS%'
			OR
			 otq.NAME LIKE '%QUAIS TIPOS DE LOGO ESTÃO POSITIVADOS%'
			OR 
			 otq.NAME LIKE '%QUAIS TIPOS DE DISPLAY/BOTÃO ESTÃO POSITIVADOS%'
			OR 
			 otq.NAME LIKE '%QUAIS TIPOS DE MOLDURA ESTÃO POSITIVADAS%'
		THEN CONTENT
	END,
	otc.ROLE_NAME,
	otc.COORDINATOR,
	otc.SUPERVISOR,
	otq.FORMULARY_ID,
	otf.NAME,
	otabf.PRODUCT_ID,
	otp.NAME,
	otabf.ITEM_VALIDATED,
	otabf.ITEM_USER_VALIDATED,
	otabf.ITEM_DATE_VALIDATION,
	otabf.ITEM_OBSERVATION;
TMP_COMPLETE=
SELECT
	CAMPAIGN_ID,
	CYCLE_ID,
	ITEM_ID,
	VISIT_ID,
	CODE,
	COLLABORATOR_NAME,
	ROLE_NAME,
	COORDINATOR,
	SUPERVISOR,
	FORMULARY_ID,
	FORMULARY_NAME,
	PRODUCT_ID,
	ITEM_NAME,
	LEFT(ITEM_NAME, LOCATE(ITEM_NAME, ' ') - 1) BRAND,
	RIGHT(ITEM_NAME, LENGTH(ITEM_NAME) - LOCATE(ITEM_NAME, ' - ') - 2) ITEM,
	ITEM_VALIDATED,
	ITEM_USER_VALIDATED,
	ITEM_DATE_VALIDATION,
	ITEM_OBSERVATION,
	ANSWERED_AT,
	LOAD_DATE,
	MAX(O_PRODUTO_ESTA_DISPONIVEL_NESTA_LOJA_SEJA_NO_ESTOQUE_DA_LOJA_OU_EXPOSTO) OVER (PARTITION BY ITEM_ID) AS O_PRODUTO_ESTA_DISPONIVEL_NESTA_LOJA_SEJA_NO_ESTOQUE_DA_LOJA_OU_EXPOSTO,
	MAX(O_PRODUTO_ESTA_EXPOSTO) OVER (PARTITION BY ITEM_ID) AS O_PRODUTO_ESTA_EXPOSTO,
	MAX(ONDE_ESTE_SKU_ESTA_EXPOSTO) OVER (PARTITION BY ITEM_ID) AS ONDE_ESTE_SKU_ESTA_EXPOSTO,
	MAX(SE_HA_ESTOQUE_E_NAO_ESTA_EXPOSTO_QUAL_O_MOTIVO) OVER (PARTITION BY ITEM_ID) AS SE_HA_ESTOQUE_E_NAO_ESTA_EXPOSTO_QUAL_O_MOTIVO,
	MAX(PORQUE_NAO_HA_ESTOQUE_DO_PRODUTO_EM_LOJA) OVER (PARTITION BY ITEM_ID) AS PORQUE_NAO_HA_ESTOQUE_DO_PRODUTO_EM_LOJA,
	MAX(QUAL_O_MODULO_DO_SKU) OVER (PARTITION BY ITEM_ID) AS QUAL_O_MODULO_DO_SKU,
	MAX(QUAL_A_POSICAO_DO_SKU) OVER (PARTITION BY ITEM_ID) AS QUAL_A_POSICAO_DO_SKU,
	MAX(QUAL_O_TIPO_DA_PAREDE_ESPECIAL) OVER (PARTITION BY ITEM_ID) AS QUAL_O_TIPO_DA_PAREDE_ESPECIAL,
	MAX(QUAL_O_TIPO_DE_RACK) OVER (PARTITION BY ITEM_ID) AS QUAL_O_TIPO_DE_RACK,
	MAX(FOTO_PROXIMA_DA_TV) OVER (PARTITION BY ITEM_ID) AS FOTO_PROXIMA_DA_TV,
	MAX(FOTO_AMPLA_DA_TV) OVER (PARTITION BY ITEM_ID) AS FOTO_AMPLA_DA_TV,
	MAX(FOTO_DA_ETIQUETA) OVER (PARTITION BY ITEM_ID) AS FOTO_DA_ETIQUETA,
	MAX(ESTE_SKU_ESTA_COM_O_VIDEO_DEMO_POSITIVADO_E_ADEQUADO_AO_MODELO_DA_TV) OVER (PARTITION BY ITEM_ID) AS ESTE_SKU_ESTA_COM_O_VIDEO_DEMO_POSITIVADO_E_ADEQUADO_AO_MODELO_DA_TV,
	MAX(PORQUE_O_VIDEO_DEMO_CORRETO_NAO_ESTA_POSITIVADO) OVER (PARTITION BY ITEM_ID) AS PORQUE_O_VIDEO_DEMO_CORRETO_NAO_ESTA_POSITIVADO,
	MAX(ESTE_SKU_ESTA_COM_O_EPOP_POSITIVADO_E_ADEQUADO_AO_MODELO_DA_TV) OVER (PARTITION BY ITEM_ID) AS ESTE_SKU_ESTA_COM_O_EPOP_POSITIVADO_E_ADEQUADO_AO_MODELO_DA_TV,
	MAX(PORQUE_O_EPOP_CORRETO_NAO_ESTA_POSITIVADO) OVER (PARTITION BY ITEM_ID) AS PORQUE_O_EPOP_CORRETO_NAO_ESTA_POSITIVADO,
	MAX(ESTA_LOJA_POSSUI_INTERNET_DISPONIVEL) OVER (PARTITION BY ITEM_ID) AS ESTA_LOJA_POSSUI_INTERNET_DISPONIVEL,
	MAX(ESTE_SKU_ESTA_COM_O_QR_CODE_POSITIVADO_E_ADEQUADO_AO_MODELO_DA_TV) OVER (PARTITION BY ITEM_ID) AS ESTE_SKU_ESTA_COM_O_QR_CODE_POSITIVADO_E_ADEQUADO_AO_MODELO_DA_TV,
	MAX(ESTE_SKU_POSSUI_MATERIAL_POSITIVADO) OVER (PARTITION BY ITEM_ID) AS ESTE_SKU_POSSUI_MATERIAL_POSITIVADO,
	MATERIAIS_POSITIVADOS,
	TIPO_DO_MATERIAL_POSITIVADO,
	MAX(POR_QUAL_MOTIVO_NAO_POSSUI_MATERIAL_POSITIVADO) OVER (PARTITION BY ITEM_ID) AS POR_QUAL_MOTIVO_NAO_POSSUI_MATERIAL_POSITIVADO,
	MAX(O_PRODUTO_E_O_RESPECTIVO_MOBILIARIO_ESTAO_LIMPOS_E_COM_FIOS_E_CABOS_ORGANIZADOS) OVER (PARTITION BY ITEM_ID) AS O_PRODUTO_E_O_RESPECTIVO_MOBILIARIO_ESTAO_LIMPOS_E_COM_FIOS_E_CABOS_ORGANIZADOS,
	MAX(FOTO_DO_SKU_COM_OS_MATERIAIS_POSITIVADOS) OVER (PARTITION BY ITEM_ID) AS FOTO_DO_SKU_COM_OS_MATERIAIS_POSITIVADOS,
	MAX(POSSUI_FOLHETO_3_EM_1) OVER (PARTITION BY ITEM_ID) AS POSSUI_FOLHETO_3_EM_1,
	MAX(FOTO_FOLHETO_3_EM_1) OVER (PARTITION BY ITEM_ID) AS FOTO_FOLHETO_3_EM_1,
	MAX(POSSUI_LUVA_3_EM_1) OVER (PARTITION BY ITEM_ID) AS POSSUI_LUVA_3_EM_1,
	MAX(FOTO_LUVA_3_EM_1) OVER (PARTITION BY ITEM_ID) AS FOTO_LUVA_3_EM_1,
	MAX(POSSUI_LUVA_TV_PLUS) OVER (PARTITION BY ITEM_ID) AS POSSUI_LUVA_TV_PLUS,
	MAX(FOTO_LUVA_TV_PLUS) OVER (PARTITION BY ITEM_ID) AS FOTO_LUVA_TV_PLUS,
	MAX(POSSUI_TAKE_ONE_3_EM_1) OVER (PARTITION BY ITEM_ID) AS POSSUI_TAKE_ONE_3_EM_1,
	MAX(FOTO_TAKE_ONE_3_EM_1) OVER (PARTITION BY ITEM_ID) AS FOTO_TAKE_ONE_3_EM_1,
	DENSE_RANK() OVER (PARTITION BY CODE ORDER BY VISIT_ID DESC) LAST_VISIT_ID,
	vcc.YEARWEEK WEEKNUM,
	DENSE_RANK() OVER (PARTITION BY CODE, vcc.YEARWEEK ORDER BY VISIT_ID DESC) LAST_VISIT_ID_BY_WEEKNUM
FROM :TMP otabf
INNER JOIN OW_SEDA_S.VW_CE_CALENDAR vcc ON TO_DATE(otabf.ANSWERED_AT) = vcc."DATE";
tmp_delete=
SELECT 
	*
FROM (
	SELECT DISTINCT 
		ITEM_ID, 
		O_PRODUTO_ESTA_DISPONIVEL_NESTA_LOJA_SEJA_NO_ESTOQUE_DA_LOJA_OU_EXPOSTO,
		ESTE_SKU_POSSUI_MATERIAL_POSITIVADO, MATERIAIS_POSITIVADOS,
		ROW_NUMBER() OVER (PARTITION BY ITEM_ID ORDER BY MATERIAIS_POSITIVADOS ASC) row_num,
		COUNT(1) OVER (PARTITION BY ITEM_ID) contagem
	FROM :TMP_COMPLETE
)
WHERE 1=1
	AND row_num = 1
	AND contagem > 1;
	
TRUNCATE TABLE OW_SEDA_S.FT_TT_TV_CHECKLIST_DE_EXECUCAO;
INSERT INTO OW_SEDA_S.FT_TT_TV_CHECKLIST_DE_EXECUCAO
SELECT * FROM :TMP_COMPLETE tc
WHERE 1=1
	--AND LAST_VISIT_ID = 1
	AND EXISTS (SELECT 1 FROM OW_SEDA_S.MAP_CE_STORES mcp WHERE mcp.SITE_ID = tc.CODE)
	AND NOT EXISTS (SELECT 1 FROM :TMP_DELETE td WHERE 1=1
												AND tc.ITEM_ID = td.ITEM_ID
												AND tc.O_PRODUTO_ESTA_DISPONIVEL_NESTA_LOJA_SEJA_NO_ESTOQUE_DA_LOJA_OU_EXPOSTO = td.O_PRODUTO_ESTA_DISPONIVEL_NESTA_LOJA_SEJA_NO_ESTOQUE_DA_LOJA_OU_EXPOSTO
												AND tc.ESTE_SKU_POSSUI_MATERIAL_POSITIVADO = td.ESTE_SKU_POSSUI_MATERIAL_POSITIVADO
												AND COALESCE(tc.MATERIAIS_POSITIVADOS, '1') = COALESCE(td.MATERIAIS_POSITIVADOS, '1'));
END;
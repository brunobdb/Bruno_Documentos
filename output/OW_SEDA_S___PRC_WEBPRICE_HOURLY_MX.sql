CREATE PROCEDURE OW_SEDA_S.PRC_WEBPRICE_HOURLY_MX (IN PREVIOUS_DAYS INT) AS
--DO 
BEGIN
	
tmp_mx=
SELECT
	mmwci.MARCA,
	mmwci.CATEGORY,
	ocwa.ITEM,
	mmwci.MARKETING_NAME,
	CASE 
		WHEN CATEGORY = 'HHP' THEN REPLACE(REPLACE(REPLACE(MARKETING_NAME, 'Galaxy ', ''), 'Galaxy-', ''), 'Ultra', 'U') || ' (' || STORAGE  || ')'
		WHEN CATEGORY = 'TAB' THEN MARKETING_NAME || ' (' || STORAGE  || ')'
		ELSE MARKETING_NAME 
	END PRODUCT_NAME,
	mmwci.STORAGE,
	mmwci.COLOR,
	UPPER(ocwa.STORE_NAME) AS STORE_NAME,
	COALESCE(UPPER(CASE WHEN ocwa.STORE_NAME = ocwa.MARKETPLACE_NAME THEN '-' ELSE CASE WHEN ocwa.STORE_NAME = 'Mercado Livre'AND UPPER(ocwa.MARKETPLACE_NAME) LIKE '%MERCADO LIVRE ELETRONICOS%' THEN NULL ELSE ocwa.MARKETPLACE_NAME END END),'-') AS MARKETPLACE_NAME,
	ocwa.INPUT_DATE AS COLLECT_TIMESTAMP,
	ocwa.PRECO_A_VISTA,
	ocwa.PRECO_A_PRAZO,
	ocwa.PARCELAS,
	ocwa.PRECO_PARCELAS
FROM OW_SEDA_S.ODS_CE_WEBPRICE_API ocwa 
INNER JOIN OW_SEDA_S.MAP_MX_WEBPRICE_CODIGO_INTERNO mmwci ON ocwa.ITEM = mmwci.CODIGO_INTERNO
WHERE TO_DATE(ocwa.INPUT_DATE) BETWEEN ADD_DAYS(CURRENT_DATE, -1 * PREVIOUS_DAYS) AND CURRENT_DATE;
tmp_complete = 
SELECT
	tmx.MARCA,
	tmx.CATEGORY,
	tmx.ITEM,
	tmx.MARKETING_NAME,
	tmx.PRODUCT_NAME,
	tmx.STORAGE,
	tmx.COLOR,
	tmx.STORE_NAME,
	tmx.MARKETPLACE_NAME,
	tmx.COLLECT_TIMESTAMP,
	vcc.YEARWEEK,
	tmx.PRECO_A_VISTA,
	tmx.PRECO_A_PRAZO,
	tmx.PARCELAS,
	tmx.PRECO_PARCELAS,
	omrp.REFERENCE_PRICE_SPOT AS SENSING_A_VISTA,
	omrp.REFERENCE_PRICE_INSTALLMENT AS SENSING_A_PRAZO,
	omrp.RRP 
FROM :tmp_mx tmx
INNER JOIN OW_SEDA_S.VW_CE_CALENDAR vcc ON vcc."DATE" = TO_DATE(tmx.COLLECT_TIMESTAMP)
LEFT JOIN OW_SEDA_S.ODS_MX_REFERENCE_PRICE omrp 
ON 1=1
	AND omrp.WEEKNUM = vcc.YEARWEEK
	AND omrp.PRODUCT_NAME = CASE WHEN tmx.CATEGORY = 'NPC' THEN tmx.ITEM ELSE tmx.PRODUCT_NAME END;
DELETE FROM OW_SEDA_S.FT_WEBPRICE_TRACKING_HOURLY_MX owtdt 
WHERE EXISTS (SELECT 1 FROM :TMP_COMPLETE t WHERE TO_DATE(owtdt.COLLECT_TIMESTAMP) = TO_DATE(t.COLLECT_TIMESTAMP));
	
INSERT INTO OW_SEDA_S.FT_WEBPRICE_TRACKING_HOURLY_MX
SELECT * FROM :TMP_COMPLETE;
	
END; 

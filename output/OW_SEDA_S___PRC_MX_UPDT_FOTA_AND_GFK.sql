
CREATE PROCEDURE OW_SEDA_S.PRC_MX_UPDT_FOTA_AND_GFK(YEAR_REF INT) AS 
--DO
BEGIN
	
TMP_GFK=
SELECT 
		ON_OFF AS "On/Off",
		BRAND,
		PERIOD AS "Period",
		"MONTH" AS "Month",
		"YEAR" AS "Year",
		MONTH_NUMBER AS "MM",
		QUARTER,
		G_BRAND,
		NEW_MARKETING_NAME AS "Marketing Name",
		AMT_ASP_LC AS "AMT ASP <LC>",
		PRICE_TIER_ASP AS "Price Tier ASP",
		SALES_UNITS AS "Sales Units",
		0 AS "Inventory",
		'' AS "Account Group",
		'GFK' AS "Source"
	FROM OW_SEDA_S.FT_GFK_MX_WEEKLY fgmw 
	WHERE 1=1
		AND "YEAR" = YEAR_REF;
	
TMP_PERIOD=
SELECT MAX("Year" || REPLACE("Period", 'W', '')) MAX_WEEKNUM, MIN("Year" || REPLACE("Period", 'W', '')) MIN_WEEKNUM FROM :TMP_GFK;
TMP_FILTER=
	SELECT
		'W' || RIGHT(vcc.YEARWEEK, 2) AS "Period",
		LEFT(INITCAP(MONTHNAME (mcc.CALENDAR)), 3) AS "Month",
		mcc."YEAR" AS "Year"
	FROM OW_SEDA_S.FT_MX_DAILY_FOTA fmdf 
	INNER JOIN OW_SEDA_S.VW_CE_CALENDAR vcc ON fmdf.SELL_OUT_DATE = vcc."DATE"
	INNER JOIN OW_SEDA_S.MAP_CE_CALENDAR mcc ON vcc.YEARWEEK = mcc.YEARWEEK 
	INNER JOIN OW_SEDA_S.MAP_CE_PRODUCTS mcp ON mcp.ITEM = fmdf.ITEM
	WHERE 1=1
		AND mcp.PREFIX_ITEM IS NOT NULL
		AND mcp.CATEGORY_ITEM = 'HHP'
		AND YEAR = 2025
	GROUP BY 
		'W' || RIGHT(vcc.YEARWEEK, 2),
		LEFT(INITCAP(MONTHNAME (mcc.CALENDAR)), 3),
		mcc."YEAR"
	HAVING COUNT(DISTINCT fmdf.SELL_OUT_DATE) = 7;
	
TMP_SELL_OUT=
SELECT 
		CASE 
			WHEN ACCOUNT_GROUP LIKE 'ON_%' THEN 'Online'
			ELSE 'Offline'
		END AS "On/Off",
		mcp.BRAND_ITEM AS BRAND,
		'W' || RIGHT(vcc.YEARWEEK, 2) AS "Period",
		LEFT(INITCAP(MONTHNAME (mcc.CALENDAR)), 3) AS "Month",
		mcc."YEAR" AS "Year",
		mcc."MONTH" AS "MM",
		mcc.QUARTER,
		'1_Samsung' AS G_BRAND,
		mcp.PREFIX_ITEM || ' ' || mcp.CAPACITY_ITEM  AS "Marketing Name",
		0 AS "AMT ASP <LC>",
		'' AS "Price Tier ASP",
		SUM(fmdf.SELL_OUT_QTY) AS "Sales Units",
		0 AS "Inventory",
		ACCOUNT_GROUP AS "Account Group",
		'FOTA' AS "Source"
	FROM OW_SEDA_S.FT_MX_DAILY_FOTA fmdf 
	INNER JOIN OW_SEDA_S.VW_CE_CALENDAR vcc ON fmdf.SELL_OUT_DATE = vcc."DATE"
	INNER JOIN OW_SEDA_S.MAP_CE_CALENDAR mcc ON vcc.YEARWEEK = mcc.YEARWEEK 
	INNER JOIN OW_SEDA_S.MAP_CE_PRODUCTS mcp ON mcp.ITEM = fmdf.ITEM
	WHERE 1=1
		--AND EXISTS (SELECT 1 FROM :TMP_PERIOD gr WHERE vcc.YEARWEEK BETWEEN gr.MIN_WEEKNUM AND gr.MAX_WEEKNUM + 1)
		AND EXISTS (SELECT 1 FROM :TMP_FILTER tf WHERE 'W' || RIGHT(vcc.YEARWEEK, 2) = tf."Period" AND mcc."YEAR" >= tf."Year" - 1)
		AND mcp.PREFIX_ITEM IS NOT NULL
		AND mcp.CATEGORY_ITEM = 'HHP'
	GROUP BY 
		CASE 
			WHEN ACCOUNT_GROUP LIKE 'ON_%' THEN 'Online'
			ELSE 'Offline'
		END,
		mcp.BRAND_ITEM,
		RIGHT(vcc.YEARWEEK, 2),
		INITCAP(MONTHNAME (mcc.CALENDAR)),
		mcc."YEAR",
		mcc."MONTH",
		mcc.QUARTER,
		mcp.PREFIX_ITEM || ' ' || mcp.CAPACITY_ITEM,
		ACCOUNT_GROUP
	HAVING SUM(fmdf.SELL_OUT_QTY) > 0 AND COUNT(DISTINCT fmdf.SELL_OUT_DATE) = 7;
TMP_INVENTORY=
SELECT
		CASE 
			WHEN ACCOUNT LIKE 'ON_%' THEN 'Online'
			ELSE 'Offline'
		END AS "On/Off",
		'SAMSUNG' AS BRAND,
		'W' || RIGHT(fmdf.WEEKNUM, 2) AS "Period",
		LEFT(INITCAP(MONTHNAME (mcc.CALENDAR)), 3) AS "Month",
		mcc."YEAR" AS "Year",
		mcc."MONTH" AS "MM",
		mcc.QUARTER,
		'1_Samsung' AS G_BRAND,
		fmdf.MARKET_NAME || ' ' || fmdf.STORAGE AS "Marketing Name",
		0 AS "AMT ASP <LC>",
		'' AS "Price Tier ASP",
		0 AS "Sales Units",
		SUM(INVENTORY) AS "Inventory",
		ACCOUNT AS "Account Group",
		'FOTA' AS "Source"
	FROM OW_SEDA_S.FT_MX_PIVOT_BY_ITEM fmdf 
	INNER JOIN OW_SEDA_S.MAP_CE_CALENDAR mcc ON mcc.YEARWEEK = fmdf.WEEKNUM
	INNER JOIN OW_SEDA_S.MAP_CE_PRODUCTS mcp ON mcp.ITEM = fmdf.ITEM
	WHERE 1=1
		--AND EXISTS (SELECT 1 FROM :TMP_PERIOD gr WHERE fmdf.WEEKNUM BETWEEN gr.MIN_WEEKNUM AND gr.MAX_WEEKNUM + 1)
		AND EXISTS (SELECT 1 FROM :TMP_FILTER tf WHERE 'W' || RIGHT(fmdf.WEEKNUM, 2) = tf."Period" AND mcc."YEAR" >= tf."Year" - 1)
		AND fmdf.MARKET_NAME || ' ' || fmdf.STORAGE IS NOT NULL
		AND mcp.CATEGORY_ITEM = 'HHP'
	GROUP BY 
		CASE 
			WHEN ACCOUNT LIKE 'ON_%' THEN 'Online'
			ELSE 'Offline'
		END,
		'W' || RIGHT(fmdf.WEEKNUM, 2),
		INITCAP(MONTHNAME (mcc.CALENDAR)),
		mcc."YEAR",
		mcc."MONTH",
		mcc.QUARTER,
		fmdf.MARKET_NAME || ' ' || fmdf.STORAGE,
		ACCOUNT 
	HAVING SUM(INVENTORY) <> 0;
TMP_COMPLETE = 
SELECT * FROM :TMP_GFK
UNION ALL
SELECT * FROM :TMP_SELL_OUT
UNION ALL 
SELECT * FROM :TMP_INVENTORY;
DELETE FROM OW_SEDA_S.VW_MX_FOTA_AND_GFK vfg
WHERE EXISTS (SELECT 1 FROM :TMP_COMPLETE tc WHERE vfg."Year" = tc."Year" AND vfg."Period" = tc."Period" AND vfg."Source" = tc."Source");
INSERT INTO OW_SEDA_S.VW_MX_FOTA_AND_GFK
SELECT * FROM :TMP_COMPLETE;
END;

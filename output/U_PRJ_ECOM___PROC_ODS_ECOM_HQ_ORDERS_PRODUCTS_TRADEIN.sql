CREATE PROCEDURE U_PRJ_ECOM.PROC_ODS_ECOM_HQ_ORDERS_PRODUCTS_TRADEIN
 LANGUAGE SQLSCRIPT AS
 BEGIN
 --TF TRADE IN
 
CREATE COLUMN TABLE  U_PRJ_ECOM.TMP_ECOM_HQ_ORDERS_PRODUCTS_TRADEIN_TST AS
( SELECT * FROM (
SELECT
a.ORDER_ID AS "Order_Id", 
a.PO_CREATION_DATE,
a.sku AS "Reference_Code",
a.TRADE_IN_SKUID AS SKU_ID,
'' AS "CATEGORY_NAME",
a.TRADE_IN_PRODUCT_NAME AS Model,
a.PRODUCT_BRAND AS BRAND,
CASE WHEN a.TRADE_IN_BOOST = 0 THEN a.TRADE_IN_TOTAL 
WHEN a.TRADE_IN_BOOST IS NULL  THEN a.TRADE_IN_TOTAL 
ELSE a.TRADE_IN_BOOST END AS Trade_in_discount,
CASE WHEN a.IS_TRADE_IN = 'true' AND  a.TRADE_IN_SKUID = a.SKU_ID_BR_SHOP  THEN 'TRUE' 
 ELSE 'FALSE' END AS IS_TRADE_IN,
CASE WHEN a.TRADE_IN_SKUID = a.SKU_ID_BR_SHOP  THEN 'TRUE'
 ELSE 'FALSE'   END AS "IS_TRADE_IN_ELIGIBLE",
 
  'SEDA' AS SUBSIDIARY,
  6 AS SUBSIDIARY_ID
 
FROM OW_LAO.TF_D2C_PO_VTEX_TRADE_IN a
WHERE a.TRADE_IN_SKUID IS NOT NULL AND a.TRADE_IN_SKUID = a.SKU_ID_BR_SHOP
UNION ALL 
(
SELECT
a.ORDER_ID AS "Order_Id", 
a.PO_CREATION_DATE,
a.sku AS "Reference_Code",
a.ECO_SKUID AS SKU_ID,
a.ECO_CATEGORY_NAME AS "CATEGORY_NAME",
'' AS Model,
a.ECO_BRAND AS BRAND,
a.ECO_BOOST AS Trade_in_discount,
CASE WHEN a.IS_ECO_TROCA = 'true' AND  a.ECO_SKUID = a.SKU_ID_BR_SHOP  THEN 'TRUE' 
 ELSE 'FALSE' END AS IS_TRADE_IN,
CASE WHEN a.ECO_SKUID = a.SKU_ID_BR_SHOP THEN 'TRUE'
 ELSE 'FALSE'   END AS "IS_TRADE_IN_ELIGIBLE",
  'SEDA' AS SUBSIDIARY,
   6 AS SUBSIDIARY_ID
 
FROM OW_LAO.TF_D2C_PO_VTEX_TRADE_IN a
WHERE a.ECO_SKUID IS NOT NULL AND a.ECO_SKUID = a.SKU_ID_BR_SHOP
) 
UNION ALL 
(
SELECT
a.ORDER_ID AS "Order_Id", 
a.PO_CREATION_DATE,
a.sku AS "Reference_Code",
a.TRADE_IN_SKUID AS SKU_ID,
'' AS "CATEGORY_NAME",
a.TRADE_IN_PRODUCT_NAME AS Model,
a.PRODUCT_BRAND AS BRAND,
CASE WHEN a.TRADE_IN_BOOST = 0 THEN a.TRADE_IN_TOTAL 
WHEN a.TRADE_IN_BOOST IS NULL  THEN a.TRADE_IN_TOTAL 
ELSE a.TRADE_IN_BOOST END AS Trade_in_discount,
CASE WHEN a.IS_TRADE_IN = 'true' AND  a.TRADE_IN_SKUID = a.SKU_ID_EPP2 THEN 'TRUE' 
 ELSE 'FALSE' END AS IS_TRADE_IN,
CASE WHEN a.TRADE_IN_SKUID = a.SKU_ID_EPP2  THEN 'TRUE'
 ELSE 'FALSE'   END AS "IS_TRADE_IN_ELIGIBLE",
 
  'SEDA' AS SUBSIDIARY,
   6 AS SUBSIDIARY_ID
 
FROM OW_LAO.TF_D2C_PO_VTEX_TRADE_IN a
WHERE a.TRADE_IN_SKUID IS NOT NULL AND a.TRADE_IN_SKUID = a.SKU_ID_EPP2
)
UNION ALL 
(
SELECT
a.ORDER_ID AS "Order_Id", 
a.PO_CREATION_DATE,
a.sku AS "Reference_Code",
a.ECO_SKUID AS SKU_ID,
a.ECO_CATEGORY_NAME AS "CATEGORY_NAME",
'' AS Model,
a.ECO_BRAND AS BRAND,
a.ECO_BOOST AS Trade_in_discount,
CASE WHEN a.IS_ECO_TROCA = 'true' AND  a.ECO_SKUID = a.SKU_ID_EPP2  THEN 'TRUE' 
 ELSE 'FALSE' END AS IS_TRADE_IN,
CASE WHEN a.ECO_SKUID =a.SKU_ID_EPP2 THEN 'TRUE'
 ELSE 'FALSE'   END AS "IS_TRADE_IN_ELIGIBLE",
 
  'SEDA' AS SUBSIDIARY,
   6 AS SUBSIDIARY_ID
 
FROM OW_LAO.TF_D2C_PO_VTEX_TRADE_IN a
WHERE a.ECO_SKUID IS NOT NULL AND a.ECO_SKUID = a.SKU_ID_EPP2
) 
UNION ALL 
(
SELECT DISTINCT 
 ORDER_ID AS "Order_Id",
 CREATION_DATE AS PO_CREATION_DATE,
 REFID AS "Reference_Code",
 SKUID AS SKU_ID,
 ''  AS CATEGORY_NAME,
 MODEL_DEVICE AS MODEL,
 BRAND_DEVICE AS BRAND,
 TRADE_IN_DISCOUNT_DEVICE AS TRADE_IN_DISCOUNT,
'TRUE' IS_TRADE_IN,
'TRUE' IS_TRADE_IN_ELIGIBLE,
 'SEASA' AS SUBSIDIARY,
  1 AS SUBSIDIARY_ID
 
 
 FROM  U_PRJ_ECOM.RAW_VTEX_SEASA_TRADEIN_FEED)) a
 
	  WHERE  not exists(
                  select 1
                    from U_PRJ_ECOM.ODS_ECOM_HQ_ORDERS_PRODUCTS_TRADEIN  aa
                  WHERE         aa."Order_Id"            = a."Order_Id"
                           AND  aa."Reference_Code"      = a."Reference_Code"
                           AND  aa.IS_TRADE_IN           = a.IS_TRADE_IN	       
                           AND  aa.IS_TRADE_IN_ELIGIBLE  = a.IS_TRADE_IN_ELIGIBLE  
                           AND  aa.SUBSIDIARY_ID         = a.SUBSIDIARY_ID
                  )
 )
;
-- UPDATE ATUALIZAÇÃO TRADEIN ODS
 UPDATE  U_PRJ_ECOM.ODS_ECOM_HQ_ORDERS_PRODUCTS_TRADEIN       a
           SET a.IS_TRADE_IN        = b.IS_TRADE_IN
             , a.IS_TRADE_IN_ELIGIBLE = b.IS_TRADE_IN_ELIGIBLE
             , a.LAST_UPDATE_DATE     = CURRENT_TIMESTAMP  
          FROM U_PRJ_ECOM.ODS_ECOM_HQ_ORDERS_PRODUCTS_TRADEIN       a
          join  U_PRJ_ECOM.TMP_ECOM_HQ_ORDERS_PRODUCTS_TRADEIN_TST    b         on  a."Order_Id"        = b."Order_Id"
                                                                                 and b."Reference_Code" = a."Reference_Code"
         ;
-- INSERIR NOVOS PEDIDOS TRADEIN ODS
INSERT INTO  U_PRJ_ECOM.ODS_ECOM_HQ_ORDERS_PRODUCTS_TRADEIN 
(
SELECT DISTINCT 
a."Order_Id",
a.PO_CREATION_DATE,
a."Reference_Code",
a.SKU_ID,
a.CATEGORY_NAME,
a.MODEL,
a.BRAND,
a.TRADE_IN_DISCOUNT,
a.IS_TRADE_IN,
a.IS_TRADE_IN_ELIGIBLE,
a.SUBSIDIARY,
a.SUBSIDIARY_ID,
CURRENT_TIMESTAMP AS INSERT_DATE  ,
CURRENT_TIMESTAMP AS LAST_UPDATE_DATE ,
CURRENT_TIMESTAMP AS LOAD_DATE   
FROM  U_PRJ_ECOM.TMP_ECOM_HQ_ORDERS_PRODUCTS_TRADEIN_TST a
WHERE  not exists(
                  select 1
                    from U_PRJ_ECOM.ODS_ECOM_HQ_ORDERS_PRODUCTS_TRADEIN  aa
                  WHERE         aa."Order_Id"            = a."Order_Id"
                           AND  aa."Reference_Code"      = a."Reference_Code"
                            
                  )
)
;
 DROP TABLE U_PRJ_ECOM.TMP_ECOM_HQ_ORDERS_PRODUCTS_TRADEIN_TST;
END
CREATE PROCEDURE OW_SEDA_S.PRC_UPDATE_PIN_TO_PIN (IN ITEM_REF VARCHAR(50), IN PTP_REF VARCHAR(50)) as
BEGIN 
UPDATE mcp SET PIN_TO_PIN_BF_2021 = PTP_REF FROM OW_SEDA_S.MAP_CE_PRODUCTS mcp 
WHERE 1=1
	AND ITEM = ITEM_REF;
UPDATE mptpb SET PIN_TO_PIN = PTP_REF FROM OW_SEDA_S.MAP_PIN_TO_PIN_BF_19 mptpb
WHERE 1=1
	AND ITEM = ITEM_REF;
	
END;
CREATE PROCEDURE OW_SEDA_S.PRC_VD_SALES_REVENUE AS 
--DO 
BEGIN 
TMP_GERENCIAIS=
SELECT
	UPPER(
		CASE 
			WHEN CENSO = 'Fast' THEN 'Fast Shop'
			WHEN CENSO IN ('Carrefour', 'Carrefour.com') THEN 'Carrefour'
			WHEN CENSO = 'G Barbosa' THEN 'GBarbosa'
			WHEN CENSO = 'Lojas Colombo' THEN 'Colombo'
			ELSE CENSO 
		END) CENSO,
	SPMON,
	LEFT(SPMON, 4) YEAR,
	CASE 
		WHEN RIGHT(SPMON, 2) = 01 THEN 'JAN'
		WHEN RIGHT(SPMON, 2) = 02 THEN 'FEB'
		WHEN RIGHT(SPMON, 2) = 03 THEN 'MAR'
		WHEN RIGHT(SPMON, 2) = 04 THEN 'APR'
		WHEN RIGHT(SPMON, 2) = 05 THEN 'MAY'
		WHEN RIGHT(SPMON, 2) = 06 THEN 'JUN'
		WHEN RIGHT(SPMON, 2) = 07 THEN 'JUL'
		WHEN RIGHT(SPMON, 2) = 08 THEN 'AUG'
		WHEN RIGHT(SPMON, 2) = 09 THEN 'SEP'
		WHEN RIGHT(SPMON, 2) = 10 THEN 'OCT'
		WHEN RIGHT(SPMON, 2) = 11 THEN 'NOV'
		WHEN RIGHT(SPMON, 2) = 12 THEN 'DEC'
	END MONTH,
	CASE 
		WHEN RIGHT(SPMON, 2) BETWEEN 1 AND 3 THEN 'Q1'
		WHEN RIGHT(SPMON, 2) BETWEEN 4 AND 6 THEN 'Q2'
		WHEN RIGHT(SPMON, 2) BETWEEN 7 AND 9 THEN 'Q3'
		WHEN RIGHT(SPMON, 2) BETWEEN 10 AND 12 THEN 'Q4'
	END QUARTER,
	SUM(NET_SALES_QTY) NET_SALES_QTY,
	SUM(NET_SALES_BRL) NET_SALES_BRL,
	SUM(NET_SALES_USD) NET_SALES_USD,
	SUM(CASE WHEN mcp.TECHNOLOGY_ITEM LIKE '%QLED%' OR (mcp.CATEGORY_ITEM = 'TV' AND mcp.INCHES_ITEM >= 65) THEN NET_SALES_BRL ELSE 0 END) NET_SALES_PREMIUM_BRL
FROM OW_SEDA_S.FT_CE_MANAGEMENT_INFORMATION vcmi 
LEFT JOIN OW_SEDA_S.MAP_CE_PRODUCTS mcp ON vcmi.SKU = mcp.ITEM 
WHERE 1=1
	AND LEFT(SPMON, 4) >= 2020
	AND CENSO IN ('Via Varejo', 'Fast', 'Magazine Luiza', 'Nagem', 'Gazin', 'Carrefour', 'Carrefour.com', 'G Barbosa', 'Havan', 'Novo Mundo', 'Fujioka', 'Lojas Colombo', 'Lojas Cem', 'Mercado Livre')
	AND DIVISION_DESCRIPTION = 'AV'
GROUP BY
	CENSO,
	SPMON;
TMP_PORTION=
SELECT
	SPMON,
	SUM(NET_SALES_QTY) NET_SALES_QTY,
	SUM(NET_SALES_BRL) NET_SALES_BRL,
	SUM(NET_SALES_USD) NET_SALES_USD,
	SUM(CASE WHEN mcp.TECHNOLOGY_ITEM LIKE '%QLED%' OR (mcp.CATEGORY_ITEM = 'TV' AND mcp.INCHES_ITEM >= 65) THEN NET_SALES_BRL ELSE 0 END) NET_SALES_PREMIUM_BRL
FROM OW_SEDA_S.FT_CE_MANAGEMENT_INFORMATION vcmi 
LEFT JOIN OW_SEDA_S.MAP_CE_PRODUCTS mcp ON vcmi.SKU = mcp.ITEM 
WHERE 1=1
	AND LEFT(SPMON, 4) >= 2020
	AND DIVISION_DESCRIPTION = 'AV'
GROUP BY SPMON;
TMP_PSI=
SELECT
	CASE WHEN mcs.ACCOUNT LIKE 'REGIONAL%' OR mcs.ACCOUNT = 'ONLINE OTHERS' THEN mcs.CHANNEL ELSE mcs.ACCOUNT END ACCOUNT,
	mcc."YEAR" || '.' || LPAD(MCC."MONTH", 3, '0') SPMON,
	SUM(fcp."Sell Out") sell_out_qty
FROM OW_SEDA_S.FT_CE_PIVOT fcp 
INNER JOIN OW_SEDA_S.MAP_CE_STORES mcs ON mcs.SITE_ID = fcp.SITE_ID 
INNER JOIN OW_SEDA_S.MAP_CE_PRODUCTS mcp ON mcp.ITEM = fcp.ITEM 
INNER JOIN OW_SEDA_S.MAP_CE_CALENDAR mcc ON mcc.YEARWEEK = fcp.WEEKNUM 
WHERE 1=1
	AND mcc."YEAR" >= 2020
	AND mcp.CATEGORY_ITEM IN ('AV', 'TV')
	AND CASE WHEN mcs.ACCOUNT LIKE 'REGIONAL%' OR mcs.ACCOUNT = 'ONLINE OTHERS' THEN mcs.CHANNEL ELSE mcs.ACCOUNT END IN ('VIA VAREJO', 'FAST SHOP', 'MAGAZINE LUIZA', 'NAGEM', 'GAZIN', 'LOJAS CEM', 'MERCADO LIVRE', 'HAVAN', 'NOVO MUNDO', 'GBARBOSA', 'FUJIOKA' ,'COLOMBO', 'CARREFOUR')
	AND mcs.STORE_TYPE <> 'GSBN'
	AND fcp."Sell Out" > 0
GROUP BY 
	CASE WHEN mcs.ACCOUNT LIKE 'REGIONAL%' OR mcs.ACCOUNT = 'ONLINE OTHERS' THEN mcs.CHANNEL ELSE mcs.ACCOUNT END,
	mcc."YEAR",
	mcc."MONTH"
UNION ALL 
SELECT
	CASE WHEN mcs.ACCOUNT LIKE 'REGIONAL%' OR mcs.ACCOUNT = 'ONLINE OTHERS' THEN mcs.CHANNEL ELSE mcs.ACCOUNT END ACCOUNT,
	mcc."YEAR" || '.' || LPAD(MCC."MONTH", 3, '0') SPMON,
	SUM(fcp."Sell Out") sell_out_qty
FROM OW_SEDA_S.FT_CE_PIVOT fcp 
INNER JOIN OW_SEDA_S.MAP_CE_STORES mcs ON mcs.SITE_ID = fcp.SITE_ID 
INNER JOIN OW_SEDA_S.MAP_CE_PRODUCTS mcp ON mcp.ITEM = fcp.ITEM 
INNER JOIN OW_SEDA_S.MAP_CE_CALENDAR mcc ON mcc.YEARWEEK = fcp.WEEKNUM 
WHERE 1=1
	AND mcc."YEAR" BETWEEN 2020 AND 2023
	AND mcp.CATEGORY_ITEM IN ('AV', 'TV')
	AND CASE WHEN mcs.ACCOUNT LIKE 'REGIONAL%' OR mcs.ACCOUNT = 'ONLINE OTHERS' THEN mcs.CHANNEL ELSE mcs.ACCOUNT END IN ('LOJAS CEM')
	AND mcs.STORE_TYPE = 'GSBN'
	AND fcp."Sell Out" > 0
GROUP BY 
	CASE WHEN mcs.ACCOUNT LIKE 'REGIONAL%' OR mcs.ACCOUNT = 'ONLINE OTHERS' THEN mcs.CHANNEL ELSE mcs.ACCOUNT END,
	mcc."YEAR",
	mcc."MONTH";
DROP TABLE OW_SEDA_S.FT_VD_SALES_REVENUE;
CREATE TABLE OW_SEDA_S.FT_VD_SALES_REVENUE AS (
SELECT 
	tg.*,
	COALESCE(tp.sell_out_qty, 0) sell_out_qty,
	pp.NET_SALES_QTY NET_SALES_QTY_SEDA,
	pp.NET_SALES_BRL NET_SALES_BRL_SEDA
FROM :TMP_GERENCIAIS tg
LEFT JOIN :TMP_PSI tp ON tg.CENSO = tp.ACCOUNT AND tg.SPMON = tp.SPMON
LEFT JOIN :TMP_PORTION pp ON tg.SPMON = pp.SPMON
ORDER BY tg.SPMON);
END;
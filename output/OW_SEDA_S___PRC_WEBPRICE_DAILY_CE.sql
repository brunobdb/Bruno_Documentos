
CREATE PROCEDURE OW_SEDA_S.PRC_WEBPRICE_DAILY_CE (IN PREVIOUS_DAYS INT) AS
BEGIN
	
tmp_complete = 
SELECT * FROM (
SELECT mcp.BRAND_ITEM BRAND, UPPER(wb.STORE_NAME) STORE_NAME, COALESCE(UPPER(CASE WHEN wb.STORE_NAME = wb.MARKETPLACE_NAME THEN '-' ELSE wb.MARKETPLACE_NAME END),'-') MARKETPLACE_NAME, wb.ITEM, TO_DATE(wb.INPUT_DATE) INPUT_DATE, 'Preco a Vista' PRICE_TYPE, MAX(wb.PRECO_A_VISTA) MAX_PRICE, AVG(wb.PRECO_A_VISTA) AVG_PRICE, MIN(wb.PRECO_A_VISTA) MIN_PRICE, max(moda.MODA_PRECO_A_VISTA) MODA, MIN(recent.PRECO_A_VISTA) RECENT_PRICE, max(recent.LOAD_DATE) LOAD_DATE
FROM OW_SEDA_S.ODS_CE_WEBPRICE_API wb
INNER JOIN OW_SEDA_S.MAP_CE_PRODUCTS mcp ON mcp.ITEM = wb.ITEM 
LEFT JOIN 
(
SELECT ITEM, STORE_NAME, MARKETPLACE_NAME, INPUT_DATE, avg(PRECO_A_VISTA) MODA_PRECO_A_VISTA FROM (
	SELECT 
		ITEM, 
		STORE_NAME STORE_NAME, 
		MARKETPLACE_NAME MARKETPLACE_NAME, 
		to_date(INPUT_DATE) INPUT_DATE, 
		PRECO_A_VISTA, 
		COUNT(*), 
		ROW_NUMBER() OVER (PARTITION BY ITEM, STORE_NAME, MARKETPLACE_NAME, to_date(INPUT_DATE) ORDER BY COUNT(*) DESC) ROW_NUM
	FROM OW_SEDA_S.ODS_CE_WEBPRICE_API ocwa 
	WHERE 1=1
		--AND ITEM = '32LM625B'
		--AND STORE_NAME = 'Americanas'
		--AND MARKETPLACE_NAME = 'Fast Shop'
	GROUP BY ITEM, STORE_NAME, MARKETPLACE_NAME, to_date(INPUT_DATE), PRECO_A_VISTA)
WHERE row_num = 1
GROUP BY ITEM, STORE_NAME, MARKETPLACE_NAME, INPUT_DATE
) moda
ON 1=1
	AND wb.ITEM = moda.ITEM
	AND wb.STORE_NAME = moda.STORE_NAME
	AND COALESCE(wb.MARKETPLACE_NAME,'-') = COALESCE(moda.MARKETPLACE_NAME,'-')
	AND to_date(wb.INPUT_DATE) = moda.INPUT_DATE
LEFT JOIN 
(
	SELECT 
		ITEM, 
		STORE_NAME STORE_NAME, 
		MARKETPLACE_NAME MARKETPLACE_NAME, 
		to_date(INPUT_DATE) INPUT_DATE, 
		PRECO_A_VISTA,
		ROW_NUMBER() OVER (PARTITION BY ITEM, STORE_NAME, MARKETPLACE_NAME, to_date(INPUT_DATE) ORDER BY PRECO_A_VISTA ASC) ROW_NUM,
		INPUT_DATE LOAD_DATE
	FROM OW_SEDA_S.ODS_CE_WEBPRICE_API ocwa 
	WHERE SERIES_ROUND(INPUT_DATE, 'INTERVAL 10 MINUTE') IN (
						SELECT MAX_INPUT_DATE FROM (
							SELECT 
								to_date(INPUT_DATE), 
								SERIES_ROUND(MAX(INPUT_DATE), 'INTERVAL 10 MINUTE') MAX_INPUT_DATE
							FROM OW_SEDA_S.ODS_CE_WEBPRICE_API
							GROUP BY
								to_date(INPUT_DATE)
							)
						)
) recent
ON 1=1
	AND wb.ITEM = recent.ITEM
	AND wb.STORE_NAME = recent.STORE_NAME
	AND COALESCE(wb.MARKETPLACE_NAME,'-') = COALESCE(recent.MARKETPLACE_NAME,'-')
	AND to_date(wb.INPUT_DATE) = recent.INPUT_DATE
	AND recent.ROW_NUM = 1
--WHERE wb.MARKETPLACE_NAME IS NULL 
GROUP BY mcp.BRAND_ITEM, wb.STORE_NAME, wb.MARKETPLACE_NAME, wb.ITEM, TO_DATE(wb.INPUT_DATE)
--HAVING max(moda.MODA_PRECO_A_VISTA) > 0
UNION ALL 
SELECT mcp.BRAND_ITEM BRAND, UPPER(wb.STORE_NAME), COALESCE(UPPER(CASE WHEN wb.STORE_NAME = wb.MARKETPLACE_NAME THEN '-' ELSE wb.MARKETPLACE_NAME END),'-'), wb.ITEM, TO_DATE(wb.INPUT_DATE), 'Preco a Prazo' PRICE_TYPE, MAX(wb.PRECO_A_PRAZO), AVG(wb.PRECO_A_PRAZO), MIN(wb.PRECO_A_PRAZO), max(moda.MODA_PRECO_A_PRAZO) MODA, max(recent.PRECO_A_PRAZO) RECENT_PRICE, max(recent.LOAD_DATE)
FROM OW_SEDA_S.ODS_CE_WEBPRICE_API wb
INNER JOIN OW_SEDA_S.MAP_CE_PRODUCTS mcp ON mcp.ITEM = wb.ITEM 
LEFT JOIN 
(
SELECT ITEM, STORE_NAME, MARKETPLACE_NAME, INPUT_DATE, avg(PRECO_A_PRAZO) MODA_PRECO_A_PRAZO FROM (
	SELECT 
		ITEM, 
		STORE_NAME STORE_NAME, 
		MARKETPLACE_NAME MARKETPLACE_NAME, 
		to_date(INPUT_DATE) INPUT_DATE, 
		PRECO_A_PRAZO, 
		COUNT(*), 
		ROW_NUMBER() OVER (PARTITION BY ITEM, STORE_NAME, MARKETPLACE_NAME, to_date(INPUT_DATE) ORDER BY COUNT(*) DESC) ROW_NUM
	FROM OW_SEDA_S.ODS_CE_WEBPRICE_API ocwa 
	WHERE 1=1
		--AND ITEM = '32LM625B'
		--AND STORE_NAME = 'Americanas'
		--AND MARKETPLACE_NAME = 'Fast Shop'
	GROUP BY ITEM, STORE_NAME, MARKETPLACE_NAME, to_date(INPUT_DATE), PRECO_A_PRAZO)
WHERE row_num = 1
GROUP BY ITEM, STORE_NAME, MARKETPLACE_NAME, INPUT_DATE
) moda
ON 1=1
	AND wb.ITEM = moda.ITEM
	AND wb.STORE_NAME = moda.STORE_NAME
	AND COALESCE(wb.MARKETPLACE_NAME,'-') = COALESCE(moda.MARKETPLACE_NAME,'-')
	AND to_date(wb.INPUT_DATE) = moda.INPUT_DATE
LEFT JOIN 
(
	SELECT 
		ITEM, 
		STORE_NAME STORE_NAME, 
		MARKETPLACE_NAME MARKETPLACE_NAME, 
		to_date(INPUT_DATE) INPUT_DATE, 
		PRECO_A_PRAZO,
		ROW_NUMBER() OVER (PARTITION BY ITEM, STORE_NAME, MARKETPLACE_NAME, to_date(INPUT_DATE) ORDER BY PRECO_A_PRAZO ASC) ROW_NUM,
		INPUT_DATE LOAD_DATE
	FROM OW_SEDA_S.ODS_CE_WEBPRICE_API ocwa 
	WHERE SERIES_ROUND(INPUT_DATE, 'INTERVAL 10 MINUTE') IN (
						SELECT MAX_INPUT_DATE FROM (
							SELECT 
								to_date(INPUT_DATE), 
								SERIES_ROUND(MAX(INPUT_DATE), 'INTERVAL 10 MINUTE') MAX_INPUT_DATE
							FROM OW_SEDA_S.ODS_CE_WEBPRICE_API
							GROUP BY
								to_date(INPUT_DATE)
							)
						)
) recent
ON 1=1
	AND wb.ITEM = recent.ITEM
	AND wb.STORE_NAME = recent.STORE_NAME
	AND COALESCE(wb.MARKETPLACE_NAME,'-') = COALESCE(recent.MARKETPLACE_NAME,'-')
	AND to_date(wb.INPUT_DATE) = recent.INPUT_DATE
	AND recent.ROW_NUM = 1
--WHERE wb.MARKETPLACE_NAME IS NULL 
GROUP BY mcp.BRAND_ITEM, wb.STORE_NAME, wb.MARKETPLACE_NAME, wb.ITEM, TO_DATE(wb.INPUT_DATE)
--HAVING max(moda.MODA_PRECO_A_PRAZO) > 0
)
WHERE INPUT_DATE BETWEEN add_days(CURRENT_DATE, -1 * PREVIOUS_DAYS) AND CURRENT_DATE;
DELETE FROM OW_SEDA_S.ODS_WEBPRICE_TRACKING_DAILY_TV owtdt 
WHERE EXISTS (SELECT 1 FROM :TMP_COMPLETE t WHERE owtdt.DATE_COLLECTED = t.INPUT_DATE);
INSERT INTO OW_SEDA_S.ODS_WEBPRICE_TRACKING_DAILY_TV
SELECT * FROM :TMP_COMPLETE where STORE_NAME is not null;
	
END
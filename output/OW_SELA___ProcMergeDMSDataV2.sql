CREATE PROCEDURE "OW_SELA"."ProcMergeDMSDataV2"
LANGUAGE SQLSCRIPT as
BEGIN
delete from "OW_SELA"."FACT_STOCK_SALES" where dt_yw in (select distinct dt_yw from "OW_SELA"."STAGE2_FACT_STOCK_SALES");
-- create STAGE DIM_PRODUCT
create column table "OW_SELA"."STAGE_DIM_PRODUCT" as
(select DISTINCT 
'MOBILE' AS PRODUCTGROUP,
MARKETNAME,
ITEM, 
CASE WHEN (MARKETNAME LIKE '%alaxy-Note%' or MARKETNAME LIKE '%alaxy-S%' or MARKETNAME LIKE '%alaxy Note%' or MARKETNAME LIKE '%alaxy S%') then 'FLAGSHIP' ELSE 'MASS' END AS PRODUCTTYPE
 FROM "OW_SELA".STAGE2_FACT_STOCK_SALES
 WHERE LENGTH(MARKETNAME) > 1
);
-- MERGE DIM_PRODUCT
MERGE INTO "OW_SELA"."DIM_PRODUCT" D USING "OW_SELA"."STAGE_DIM_PRODUCT" S 
ON 
D."ITEM" 		= S."ITEM"
 WHEN MATCHED THEN UPDATE SET 
D."MARKETNAME" 		= S."MARKETNAME",
D."PRODUCTGROUP" 	= S."PRODUCTGROUP",
D."PRODUCTTYPE"		= S."PRODUCTTYPE"
 
 
 WHEN NOT MATCHED THEN INSERT 
 VALUES(
 s."PRODUCTGROUP",
 s."MARKETNAME",
 s."ITEM",
 s."PRODUCTTYPE");
-- DROP STAGE_DIM_PRODUCT
drop table  "OW_SELA"."STAGE_DIM_PRODUCT";
-- MERGE FACT_STOCK_SALES
MERGE INTO "OW_SELA"."FACT_STOCK_SALES" T USING "OW_SELA"."STAGE2_FACT_STOCK_SALES" S 
ON 
t."ITEM" 		= s."ITEM" and
t."DCID" 		= s."DCID" and
t."VRESELLER" 	= s."VRESELLER" and
t."LOCATIONID" 	= s."LOCATIONID" and
t."DT_YW" 		= s."DT_YW"
 WHEN MATCHED THEN UPDATE SET 
t."EOH(R)_YW" 		= s."EOH(R)_YW",
t."Sell-out_YW" 	= s."Sell-out_YW",
t."Sell-in_YW" 		= s."Sell-in_YW",
t."Sell-thru_YW" 	= s."Sell-thru_YW", 
t."EOH_YW"  		= s."EOH_YW"
 
 
 WHEN NOT MATCHED THEN INSERT 
 VALUES(
 s."ITEM",
 s."DCID",
 s."VRESELLER",
 s."LOCATIONID",
 s."DT_YW",
 s."EOH(R)_YW",
 s."Sell-out_YW",
 s."Sell-in_YW",
 s."Sell-thru_YW" ,
 s."EOH_YW");
 
 truncate table "OW_SELA"."STAGE2_FACT_STOCK_SALES";
 
 END;
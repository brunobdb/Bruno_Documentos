CREATE PROCEDURE OW_SEDA_S.PRC_TT_GABARITO_CHECKLIST_EXECUCAO_785 AS 
--DO 
BEGIN 
	
TMP_AUX =
SELECT * FROM (
	SELECT DISTINCT
		fttcde.ITEM_ID,
		fttcde.VISIT_ID,
		fttcde.CAMPAIGN_ID,
		'AUDITOR' CAMPAIGN_DESCRIPTION,
		fttcde.CODE,
		fttcde.COLLABORATOR_NAME,
		fttcde.ROLE_NAME,
		'' ITEM,
		MAX(fttcde.ANSWERED_AT) ANSWERED_AT,
		'' ESTE_SKU_ESTA_EXPOSTO_NA_ENTRADA_DA_LOJA,
		'' ONDE_ESTE_SKU_ESTA_EXPOSTO,
		'' ESTE_SKU_ESTA_COM_O_VIDEO_DEMO_POSITIVADO,
		'' EPOP_POSITIVADO_ESTA_ADEQUADO_AO_MODELO,
		MAX(fttcde.ESTA_LOJA_POSSUI_INTERNET_DISPONIVEL) ESTA_LOJA_POSSUI_INTERNET_DISPONIVEL,
		'' ESTE_SKU_ESTA_COM_O_QR_CODE_POSITIVADO,
		'' FOTO_AMPLA_DA_TV,
		'' FOTO_PROXIMA_DA_TV,
		CASE WHEN ta.possui_material = 'SIM' THEN 
			CASE 
				WHEN ta.tipo_material LIKE 'FOLHETO%' THEN 'FOLHETO'
				WHEN ta.tipo_material LIKE 'LUVA%' THEN 'LUVA'
				WHEN ta.tipo_material LIKE 'TAKE ONE%' THEN 'TAKE ONE'
			END
		END MATERIAIS_POSITIVADOS,
		CASE WHEN ta.possui_material = 'SIM' THEN ta.tipo_material ELSE NULL END TIPO_DO_MATERIAL_POSITIVADO,
		CASE 
			WHEN ta.tipo_material LIKE 'FOLHETO%' THEN 'FOLHETO'
			WHEN ta.tipo_material LIKE 'LUVA%' THEN 'LUVA'
			WHEN ta.tipo_material LIKE 'TAKE ONE%' THEN 'TAKE ONE'
		END MATERIAL,
		ta.tipo_material TIPO_DE_MATERIAL,
		CASE WHEN ta.possui_material = 'SIM' THEN 1 ELSE 0 END POINTS,
		DENSE_RANK() OVER (PARTITION BY fttcde.CODE ORDER BY fttcde.VISIT_ID DESC) RECENT_VISIT_ID
	FROM OW_SEDA_S.FT_TT_TV_CHECKLIST_DE_EXECUCAO_785 fttcde
	LEFT JOIN (
			SELECT DISTINCT
				CODE,
				VISIT_ID,
				ITEM_ID,
				MAP(element_number, 
					1, 'FOLHETO 3 EM 1',
					2, 'LUVA 3 EM 1',
					3, 'LUVA TV PLUS',
					4, 'TAKE ONE 3 EM 1') AS tipo_material,
				MAP(element_number, 
					1, POSSUI_FOLHETO_3_EM_1,
					2, POSSUI_LUVA_3_EM_1,
					3, POSSUI_LUVA_TV_PLUS,
					4, POSSUI_TAKE_ONE_3_EM_1) AS possui_material
			FROM OW_SEDA_S.FT_TT_TV_CHECKLIST_DE_EXECUCAO_785,
			 	 SERIES_GENERATE_INTEGER(1, 1, 5)
			WHERE 1=1
				--AND VISIT_ID = 8482543
				AND (
					POSSUI_FOLHETO_3_EM_1 = 'SIM'
					OR 
					POSSUI_LUVA_3_EM_1 = 'SIM'
					OR 
					POSSUI_LUVA_TV_PLUS = 'SIM'
					OR 
					POSSUI_TAKE_ONE_3_EM_1 = 'SIM'
					)
	) ta
		ON 1=1
			AND fttcde.CODE = ta.CODE
			AND fttcde.VISIT_ID = ta.VISIT_ID
			AND fttcde.ITEM_ID = ta.ITEM_ID
	GROUP BY 
		fttcde.ITEM_ID,
		fttcde.CAMPAIGN_ID,
		fttcde.CYCLE_ID,
		fttcde.VISIT_ID,
		fttcde.CODE,
		fttcde.COLLABORATOR_NAME,
		fttcde.ROLE_NAME,
		ta.tipo_material,
		ta.possui_material)
WHERE MATERIAL IS NOT NULL
;
	
TMP=
SELECT
	fttcde.ITEM_ID,
	fttcde.VISIT_ID,
	fttcde.CAMPAIGN_ID,
	fttcde.CODE,
	fttcde.COLLABORATOR_NAME,
	fttcde.ROLE_NAME,
	fttcde.ITEM,
	MAX(fttcde.ANSWERED_AT) ANSWERED_AT,
	fttcde.ESTE_SKU_ESTA_EXPOSTO_NA_ENTRADA_DA_LOJA,
	fttcde.ONDE_ESTE_SKU_ESTA_EXPOSTO,
	fttcde.ESTE_SKU_ESTA_COM_O_VIDEO_DEMO_POSITIVADO,
	fttcde.EPOP_POSITIVADO_ESTA_ADEQUADO_AO_MODELO,
	fttcde.ESTA_LOJA_POSSUI_INTERNET_DISPONIVEL,
	fttcde.ESTE_SKU_ESTA_COM_O_QR_CODE_POSITIVADO,
	fttcde.FOTO_AMPLA_DA_TV,
	fttcde.FOTO_PROXIMA_DA_TV,
	mtg.LOCALIZACAO,
	mtg.MATERIAL,
	mtg.TIPO_DE_MATERIAL
FROM OW_SEDA_S.FT_TT_TV_CHECKLIST_DE_EXECUCAO_785 fttcde
RIGHT JOIN OW_SEDA_S.MAP_TT_GABARITO_CHECKLIST_EXECUCAO mtg ON mtg.SKU = fttcde.ITEM
WHERE 1=1
	--AND fttcde.VISIT_ID = '8260635'
	--AND fttcde.ITEM = 'UN65CU8000GXZD'
GROUP BY
	fttcde.ITEM_ID,
	fttcde.VISIT_ID,
	fttcde.CAMPAIGN_ID,
	fttcde.CODE,
	fttcde.COLLABORATOR_NAME,
	fttcde.ROLE_NAME,
	fttcde.ITEM,
	mtg.LOCALIZACAO,
	mtg.MATERIAL,
	mtg.TIPO_DE_MATERIAL,
	fttcde.ESTE_SKU_ESTA_EXPOSTO_NA_ENTRADA_DA_LOJA,
	fttcde.ONDE_ESTE_SKU_ESTA_EXPOSTO,
	fttcde.ESTE_SKU_ESTA_COM_O_VIDEO_DEMO_POSITIVADO,
	fttcde.EPOP_POSITIVADO_ESTA_ADEQUADO_AO_MODELO,
	fttcde.ESTA_LOJA_POSSUI_INTERNET_DISPONIVEL,
	fttcde.ESTE_SKU_ESTA_COM_O_QR_CODE_POSITIVADO,
	fttcde.FOTO_AMPLA_DA_TV,
	fttcde.FOTO_PROXIMA_DA_TV;
INSERT INTO  OW_SEDA_S.FT_TT_GABARITO_CHECKLIST_EXECUCAO
SELECT DISTINCT 
	COALESCE(fttcde.ITEM_ID, mtg.ITEM_ID) ITEM_ID,
	COALESCE(fttcde.VISIT_ID, mtg.VISIT_ID) VISIT_ID,
	COALESCE(fttcde.CAMPAIGN_ID, mtg.CAMPAIGN_ID) CAMPAIGN_ID,
	'AUDITOR' CAMPAIGN_DESCRIPTION,
	COALESCE(fttcde.CODE, mtg.CODE) CODE,
	COALESCE(fttcde.COLLABORATOR_NAME, mtg.COLLABORATOR_NAME) COLLABORATOR_NAME,
	COALESCE(fttcde.ROLE_NAME, mtg.ROLE_NAME) ROLE_NAME,
	COALESCE(fttcde.ITEM, mtg.ITEM) ITEM,
	COALESCE(fttcde.ANSWERED_AT, mtg.ANSWERED_AT) ANSWERED_AT,
	COALESCE(fttcde.ESTE_SKU_ESTA_EXPOSTO_NA_ENTRADA_DA_LOJA, mtg.ESTE_SKU_ESTA_EXPOSTO_NA_ENTRADA_DA_LOJA) O_PRODUTO_ESTA_EXPOSTO,
	COALESCE(fttcde.ONDE_ESTE_SKU_ESTA_EXPOSTO, mtg.ONDE_ESTE_SKU_ESTA_EXPOSTO) ONDE_ESTE_SKU_ESTA_EXPOSTO,
	COALESCE(fttcde.ESTE_SKU_ESTA_COM_O_VIDEO_DEMO_POSITIVADO, mtg.ESTE_SKU_ESTA_COM_O_VIDEO_DEMO_POSITIVADO) ESTE_SKU_ESTA_COM_O_VIDEO_DEMO_POSITIVADO_E_ADEQUADO_AO_MODELO_DA_TV,
	COALESCE(fttcde.EPOP_POSITIVADO_ESTA_ADEQUADO_AO_MODELO, mtg.EPOP_POSITIVADO_ESTA_ADEQUADO_AO_MODELO) ESTE_SKU_ESTA_COM_O_EPOP_POSITIVADO_E_ADEQUADO_AO_MODELO_DA_TV,
	COALESCE(fttcde.ESTA_LOJA_POSSUI_INTERNET_DISPONIVEL, mtg.ESTA_LOJA_POSSUI_INTERNET_DISPONIVEL) ESTA_LOJA_POSSUI_INTERNET_DISPONIVEL,
	COALESCE(fttcde.ESTE_SKU_ESTA_COM_O_QR_CODE_POSITIVADO, mtg.ESTE_SKU_ESTA_COM_O_QR_CODE_POSITIVADO) ESTE_SKU_ESTA_COM_O_QR_CODE_POSITIVADO_E_ADEQUADO_AO_MODELO_DA_TV,
	COALESCE(fttcde.FOTO_AMPLA_DA_TV, mtg.FOTO_AMPLA_DA_TV) FOTO_AMPLA_DA_TV,
	COALESCE(fttcde.FOTO_PROXIMA_DA_TV, mtg.FOTO_PROXIMA_DA_TV) FOTO_PROXIMA_DA_TV,
	fttcde.MATERIAIS_POSITIVADOS,
	fttcde.TIPO_DO_MATERIAL_POSITIVADO,
	mtg.MATERIAL,
	mtg.TIPO_DE_MATERIAL,
	CASE
		WHEN mtg.MATERIAL = 'EPOP' AND mtg.EPOP_POSITIVADO_ESTA_ADEQUADO_AO_MODELO = 'SIM' THEN 1
		WHEN mtg.MATERIAL = 'VIDEO DEMO' AND mtg.ESTE_SKU_ESTA_COM_O_VIDEO_DEMO_POSITIVADO = 'SIM' THEN 1
		WHEN mtg.MATERIAL = 'QR CODE' AND mtg.ESTA_LOJA_POSSUI_INTERNET_DISPONIVEL = 'SIM' AND mtg.ESTE_SKU_ESTA_COM_O_QR_CODE_POSITIVADO = 'SIM' THEN 1
		WHEN mtg.MATERIAL = 'DISPLAY/BOTÃO' AND mtg.ONDE_ESTE_SKU_ESTA_EXPOSTO = 'SIS' AND mtg.ESTA_LOJA_POSSUI_INTERNET_DISPONIVEL = 'NÃO'AND fttcde.TIPO_DO_MATERIAL_POSITIVADO IS NOT NULL THEN 1
		WHEN mtg.MATERIAL = 'MATERIAL POP GERAL' AND mtg.ONDE_ESTE_SKU_ESTA_EXPOSTO = 'SIS' AND fttcde.TIPO_DO_MATERIAL_POSITIVADO IS NOT NULL THEN 1
		WHEN fttcde.TIPO_DO_MATERIAL_POSITIVADO IS NOT NULL AND mtg.TIPO_DE_MATERIAL IS NULL THEN 0
		WHEN fttcde.TIPO_DO_MATERIAL_POSITIVADO IS NOT NULL THEN 1
		ELSE 0
	END POINTS,
	DENSE_RANK() OVER (PARTITION BY COALESCE(fttcde.CODE, mtg.CODE) ORDER BY COALESCE(fttcde.VISIT_ID, mtg.VISIT_ID) DESC) RECENT_VISIT_ID,
	mcp.CURRENT_LINE_UP_TEXT 
FROM :TMP mtg 
FULL JOIN OW_SEDA_S.FT_TT_TV_CHECKLIST_DE_EXECUCAO_785 fttcde ON mtg.ITEM = fttcde.ITEM AND mtg.MATERIAL = fttcde.MATERIAIS_POSITIVADOS  AND mtg.VISIT_ID = fttcde.VISIT_ID AND mtg.TIPO_DE_MATERIAL = fttcde.TIPO_DO_MATERIAL_POSITIVADO
LEFT JOIN OW_SEDA_S.MAP_CE_PRODUCTS mcp ON mcp.ITEM = COALESCE(fttcde.ITEM, mtg.ITEM)
WHERE 1=1
	--AND COALESCE(fttcde.ITEM, mtg.ITEM) = 'UN65CU8000GXZD' 
	--AND COALESCE(fttcde.VISIT_ID, mtg.VISIT_ID) = '8260635'
	AND COALESCE(fttcde.ITEM_ID, mtg.ITEM_ID) IS NOT NULL
	
UNION ALL 
SELECT *, 'Yes' CURRENT_LINE_UP_TEXT  FROM :TMP_AUX;
END;
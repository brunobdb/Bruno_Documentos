CREATE PROCEDURE OW_SEDA_S.PRC_WEBPRICE_UPDT_RECENT_PRICE(IN DATE_REF VARCHAR(10)) AS
BEGIN 
	
tmp=
SELECT 
	ITEM,
	STORE_NAME,
	MARKETPLACE_NAME,
	DATE_COLLECTED,
	PRICE_TYPE,
	AVG(RECENT_PRICE_COLLECTED) RECENT_PRICE_COLLECTED
FROM (
	SELECT DISTINCT
		ITEM,
		STORE_NAME,
		MARKETPLACE_NAME,
		DATE_COLLECTED,
		CASE 
			WHEN ELEMENT_NUMBER = 1 THEN 'Preco a Vista'
			WHEN ELEMENT_NUMBER = 2 THEN 'Preco a Prazo'
		END PRICE_TYPE,
		CASE 
			WHEN ELEMENT_NUMBER = 1 THEN PRECO_A_VISTA
			WHEN ELEMENT_NUMBER = 2 THEN PRECO_A_PRAZO
		END RECENT_PRICE_COLLECTED
	FROM (
		SELECT 
			ITEM,
			UPPER(STORE_NAME) STORE_NAME,
			COALESCE(UPPER(MARKETPLACE_NAME),'-') MARKETPLACE_NAME,
			TO_DATE(INPUT_DATE) DATE_COLLECTED,
			PRECO_A_VISTA,
			PRECO_A_PRAZO,
			DENSE_RANK() OVER (PARTITION BY ITEM, STORE_NAME, MARKETPLACE_NAME ORDER BY INPUT_DATE) recent_index,
			ELEMENT_NUMBER
		FROM OW_SEDA_S.ODS_CE_WEBPRICE_API ocwa, SERIES_GENERATE_INTEGER(1, 1, 3)
		WHERE 1=1
			AND TO_DATE(INPUT_DATE) = DATE_REF
			--AND ITEM = 'UN50BU8000GXZD'
			--AND MARKETPLACE_NAME IS NULL 
			--AND STORE_NAME = 'Magazine Luiza'
		)
	WHERE 1=1
		AND recent_index = 1)
GROUP BY 
	ITEM,
	STORE_NAME,
	MARKETPLACE_NAME,
	DATE_COLLECTED,
	PRICE_TYPE;
UPDATE owtd SET
	RECENT_PRICE_COLLECTED = t.RECENT_PRICE_COLLECTED
FROM ow_seda_s.ods_webprice_tracking_daily_tv owtd
INNER JOIN :tmp t ON 1=1
					AND owtd.ITEM = t.ITEM
					AND owtd.STORE = t.STORE_NAME
					AND owtd.MARKET_PLACE = t.MARKETPLACE_NAME
					AND owtd.DATE_COLLECTED = t.DATE_COLLECTED
					AND owtd.PRICE_TYPE = t.PRICE_TYPE
WHERE 1=1
	AND owtd.RECENT_PRICE_COLLECTED IS NULL;
END;
	

		ELSE MTFASC."1_CATE"
	END) AS "1_CATE"
	,(CASE WHEN MTFASC."KEY" IS NULL
		THEN 'In analysis (1st and 2nd analysis)'
		ELSE MTFASC."2_CATE"
	END) AS "2_CATE"

	,VVP.ACQUIRER
	,VVP.PAYMENT_SYSTEM_NAME_ORIGIN  AS PAYMENT_SYSTEM
	,VVP.PAYMENT_SYSTEM_NAME AS PAYMENT_SYSTEM_NAME
	,NULL AS "ASSIGNMENT_KEY_DISTINTIC"
	,NULL AS "AMOUNT_IN_LOCAL_CURRENCY_KEY_DISTINCT"
	,NOW() AS LAST_UPDATE 
	,NOW() AS LOAD_DATE

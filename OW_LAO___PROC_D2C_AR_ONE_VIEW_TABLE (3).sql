		   			THEN 'Sit'
		   	 	WHEN UPPER(VCRT.RDO_ORDER_TYPE) LIKE '%CORREIOS%'
		   	 		THEN 'Post'
		   	 	WHEN UPPER(VCRT.RDO_ORDER_TYPE) LIKE '%COLLECT%'
		   	 		THEN 'Pick-up'
		   	 		ELSE NULL 
		   	  END) AS RDO_ORDER_TYPE
		   	  ,VCRT.NF_AMT AS RDO_AMT
		     FROM OW_SEDA_S.VW_CELLO_RETURN_TRACKING VCRT
		   WHERE VCRT.RDO_DELIVERY_TYPE <> 'DUMMY'
		   ) AS VUTCRT 
	ON ONZOT.DELIVERY_NO = VUTCRT.ORIG_DO_NO
	
LEFT JOIN (SELECT DISTINCT MAX(ONZCF.CLAIM_CREATION_DATE) AS CLAIM_CREATION_DATE
				 ,MAX(ONZCF.CREDIT_MEMO_NO) AS CREDIT_MEMO_NO
				 ,ONZCF.DELIVERY_NO 
				 ,MAX(TO_DOUBLE(CLAIM_AMOUNT)) AS CLAIM_AMT
		FROM OW_LAO.ODS_NERP_ZLLEB57910_CLAIM_FOLDER ONZCF
		WHERE 
		ONZCF.CLAIM_DESC <> 'POD Request'
		AND TO_DATE(ONZCF.CLAIM_CREATION_DATE) >'2023-05-31'
	  GROUP BY ONZCF.DELIVERY_NO) UONZCF 
	ON (ONZASOT.DELIVERY = UONZCF.DELIVERY_NO)
LEFT JOIN (SELECT (CASE WHEN OPMO.CHANNEL = 'Cnova' 
			THEN SUBSTRING(OPMO.ORIGINAL_ORDER_ID, 5, 99)
		    WHEN OPMO.CHANNEL = 'MagazineLuiza' 
		    	THEN SUBSTRING(OPMO.ORIGINAL_ORDER_ID, 1, LENGTH(OPMO.ORIGINAL_ORDER_ID) - 4)
		    WHEN OPMO.CHANNEL = 'b2w' 
		    	THEN REPLACE(OPMO.ORIGINAL_ORDER_ID, ' ', '_')
			ELSE OPMO.ORIGINAL_ORDER_ID
		   END) AS ORIGINAL_ORDER_ID_2
		   ,OPMO.*
	  	FROM OW_SEDA_S.ODS_PLUGG_MARKETPLACE_ORDER OPMO) OPMO 
	ON (RVSBSSOL.MARKETPLACE_ORDER_ID = OPMO.ORIGINAL_ORDER_ID_2)
LEFT JOIN OW_SEDA_S.RAW_DATA_API_AFTER_SALES_DETAIL_CONSOLIDATED RDAASDC 
	ON (VUTCRT.RDO = (CASE WHEN RDAASDC.RDO  LIKE 'RDO%' 
							THEN RIGHT(SUBSTR_AFTER(UPPER(RDAASDC.RDO), 'RDO:'), 10)
							ELSE NULL
					  END))
LEFT JOIN OW_MD.MAP_AR_MONTH_CUSTOMER MAC 
	ON (ONFNCLIDOI.CUSTOMER = MAC.CUSTOMER_CODE)
LEFT JOIN 	  (SELECT * FROM OW_MD.MAP_AR_WEEK_TO_FROM_AR_SCM_CLASSIFICATION  
	  			WHERE PERIOD = (SELECT DISTINCT MAX(PERIOD) FROM OW_MD.MAP_AR_WEEK_TO_FROM_AR_SCM_CLASSIFICATION)) MTFASC
	ON (IFNULL(ONFNCLIDOI.CUSTOMER,'') || IFNULL(ONFNCLIDOI."ASSIGNMENT",'') || IFNULL(ONFNCLIDOI.DOCUMENT_NUMBER,'') || IFNULL(REPLACE(ONFNCLIDOI.AMOUNT_IN_LOCAL_CURRENCY,'.',','),'') || IFNULL(ONFNCLIDOI.LINE_ITEM,'')
		= MTFASC."KEY"
		--AND (SELECT DISTINCT DC.YYYYWW_NORMAL_CALENDAR
		--		FROM OW_SEDA_S.ODS_NERP_FBL5N_CUSTOMER_LINE_ITEM_DISPLAY_OPEN_ITEMS ONFNCLIDOI 
		--	LEFT JOIN OW_MD.DIM_CALENDAR DC ON (DC.YYYYMMDD =  ADD_DAYS(TO_DATE(SUBSTRING(ONFNCLIDOI.FILE_NAME,20,8)),-7))
		--	WHERE ONFNCLIDOI.FILE_NAME LIKE '%RPASCMAROPEN_%') = MTFASC.PERIOD
		)
			
LEFT JOIN  OW_MD.MAP_AR_ASSIGNMENT_ADJUSTED MAAA ON (IFNULL(ONFNCLIDOI.CUSTOMER,'') || IFNULL(ONFNCLIDOI."ASSIGNMENT",'') || IFNULL(ONFNCLIDOI.DOCUMENT_NUMBER,'') || IFNULL(REPLACE(ONFNCLIDOI.AMOUNT_IN_LOCAL_CURRENCY,'.',','),'') = MAAA.KEY2)		
WHERE --ONFNCLIDOI.FILE_NAME LIKE '%RPASCMAROPEN_%' 
(ONFNCLIDOI.LOAD_DATE, ONFNCLIDOI.FILE_NAME ) = 
(SELECT DISTINCT MAX(LOAD_DATE), FILE_NAME 
FROM OW_SEDA_S.ODS_NERP_FBL5N_CUSTOMER_LINE_ITEM_DISPLAY_OPEN_ITEMS_HIST onfnclidoih 
WHERE FILE_NAME LIKE '%RPASCMAROPEN_%' 	
GROUP BY FILE_NAME 
ORDER BY 1 DESC LIMIT 1)
	--aND ONZASOT.SALES_DOCUMENT = '1102893176'
--)

LEFT JOIN U_PRJ_ECOM.RAW_VTEX_SSG_BR_SHOP_SALES_ORDER RVSBSSOL
	ON (ONFNCLIDOI."ASSIGNMENT" = RVSBSSOL."SEQUENCE"
		OR ONFNCLIDOI."ASSIGNMENT" = RVSBSSOL.ORDER_ID
		OR ONFNCLIDOI.REFERENCE = RVSBSSOL."SEQUENCE")
LEFT JOIN OW_LAO.VIEW_VTEX_PAYMENTS VVP 
	ON (ONFNCLIDOI."ASSIGNMENT" = VVP."SEQUENCE"
		OR ONFNCLIDOI."ASSIGNMENT" = VVP.ORDER_ID)
LEFT JOIN U_PRJ_ECOM.RAW_VTEX_SSG_BR_SALES_ORDER RVSBSO  	
	ON (RVSBSSOL.MARKETPLACE_ORDER_ID = RVSBSO.ORDER_ID)
LEFT JOIN U_PRJ_ECOM.ODS_VTEX_SSG_BR_SHOP_DATA_ENTITIES_STORES_SDS OVSBSDESS 
	ON ((CASE WHEN (CASE
				-- CD_STORE_INFORMATION
	       			WHEN RVSBSSOL.CD_STORE_INFORMATION IS NOT NULL 
					THEN RVSBSSOL.CD_STORE_INFORMATION
					ELSE RVSBSO.CD_STORE_INFORMATION
			  END) IS NOT NULL 
				THEN(CASE
					 -- CD_STORE_INFORMATION 
					 WHEN RVSBSSOL.CD_STORE_INFORMATION IS NOT NULL 
					 	THEN RVSBSSOL.CD_STORE_INFORMATION
						ELSE RVSBSO.CD_STORE_INFORMATION
				     END)
				ELSE(CASE
					  -- UTM_SOURCE
					  WHEN RVSBSSOL.UTM_SOURCE IS NOT NULL 
					  	THEN RVSBSSOL.UTM_SOURCE
						ELSE RVSBSO.UTM_SOURCE
				    END)
		END) = OVSBSDESS.ID_STORE)
LEFT JOIN (SELECT DISTINCT RVSBSSOP.ORDER_ID
				,STRING_AGG(RVSBSSOP.GIFT_CARD_ID, ', ') AS GIFT_CARD_ID
				,STRING_AGG(RVSBSSOP.REDEMPTION_CODE, ', ') AS VOUCHER_NO
				,STRING_AGG(RVSBSSOP.TID, ', ') AS TID
			FROM U_PRJ_ECOM.RAW_VTEX_SSG_BR_SHOP_SALES_ORDER_PAYMENT RVSBSSOP
			WHERE	RVSBSSOP.GIFT_CARD_ID IS NOT NULL
				AND RVSBSSOP.REDEMPTION_CODE IS NOT NULL
				AND RVSBSSOP.TID IS NOT NULL
			GROUP BY  RVSBSSOP.ORDER_ID) DRVSBSSOP
	ON (RVSBSSOL.ORDER_ID = DRVSBSSOP.ORDER_ID)	

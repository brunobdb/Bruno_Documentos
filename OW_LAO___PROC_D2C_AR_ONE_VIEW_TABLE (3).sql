	,OPMO.STATUS AS MKP_STATUS
	,OPMO.SUBTOTAL AS MKP_AMT
	
	,ONZASOT.SALES_DOCUMENT
	,ONZASOT.REJECT_REASON_1
	,(CASE WHEN DRVSBSSOP.VOUCHER_NO IS NULL 
		THEN 'N'
		ELSE 'Y'

SELECT	DISTINCT
	
	--,OW_LAO.AFFILIATE_ID_ADJUSTED(OVSBSDESS.ID_STORE, RVSBSSOL.AFFILIATE_ID, RVSBSSOL.SALES_CHANNEL) AS AFFILIATE_ID_ADJUSTED
	--,DAC.AFFILIATE_CHANNEL
	 MAC.CUSTOMER_NAME_SUMMARY AS AFFILIATE_CHANNEL
	,MAC.CUSTOMER_NAME_DETAIL AS AFFILIATE_SUB_CHANNEL
	,ONFNCLIDOI.CUSTOMER

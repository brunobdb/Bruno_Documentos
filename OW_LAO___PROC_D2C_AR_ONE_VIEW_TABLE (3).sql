				,RVSBSSOL."SEQUENCE"
			    ,STRING_AGG(RVSBSSOI.NAME, ', ') AS NAME
				,STRING_AGG(RVSBSSOI.REF_ID, ', ') AS REF_ID
				,SUM(RVSBSSOI.QUANTITY) AS QUANTITY
			    ,SUM(RVSBSSOI.QUANTITY*(RVSBSSOI.SELLING_PRICE/100)) AS SELLING_PRICE
			FROM U_PRJ_ECOM.RAW_VTEX_SSG_BR_SHOP_SALES_ORDER RVSBSSOL
			LEFT JOIN U_PRJ_ECOM.RAW_VTEX_SSG_BR_SHOP_SALES_ORDER_ITEM RVSBSSOI 
				ON (RVSBSSOL.ORDER_ID = RVSBSSOI.ORDER_ID)
			WHERE UPPER(RVSBSSOI.REF_ID) LIKE '%BRASIL%' OR (RVSBSSOI.NAME LIKE '%Samsung Care+%' AND RVSBSSOI.REF_ID IS NULL)
			GROUP BY RVSBSSOL.ORDER_ID, RVSBSSOL."SEQUENCE") URVSBSSOL
	ON (ONFNCLIDOI."ASSIGNMENT" = URVSBSSOL."SEQUENCE" OR ONFNCLIDOI."ASSIGNMENT" = URVSBSSOL.ORDER_ID)
--Dados de Instalação
LEFT JOIN (SELECT RVSBSSOL.ORDER_ID
				,RVSBSSOL."SEQUENCE"
				,STRING_AGG(RVSBSSOI.NAME, ', ') AS NAME
				,STRING_AGG(RVSBSSOI.REF_ID, ', ') AS REF_ID
				,SUM(RVSBSSOI.QUANTITY) AS QUANTITY
				,SUM(RVSBSSOI.QUANTITY*(RVSBSSOI.SELLING_PRICE/100)) AS SELLING_PRICE
			FROM U_PRJ_ECOM.RAW_VTEX_SSG_BR_SHOP_SALES_ORDER RVSBSSOL
			LEFT JOIN U_PRJ_ECOM.RAW_VTEX_SSG_BR_SHOP_SALES_ORDER_ITEM RVSBSSOI 
				ON (RVSBSSOL.ORDER_ID = RVSBSSOI.ORDER_ID)
			WHERE UPPER(RVSBSSOI.REF_ID) in ('WSM','AC1','AC2','DTV1','DTV2','DTV3','REF3','REF4','WSM3')
		  	GROUP BY RVSBSSOL.ORDER_ID, RVSBSSOL."SEQUENCE") URVSBSSOL2
	ON (ONFNCLIDOI."ASSIGNMENT" = URVSBSSOL2."SEQUENCE" OR ONFNCLIDOI."ASSIGNMENT" = URVSBSSOL2.ORDER_ID)
LEFT JOIN OW_LAO.ODS_NERP_ZRSDD6A120_SALES_ORDER_TRACKING ONZASOT 
	ON (RVSBSSOL.ORDER_ID =  ONZASOT.CUSTOMER_PO  OR TO_CHAR(RVSBSSOL."SEQUENCE") =  ONZASOT.CUSTOMER_PO)
LEFT JOIN (SELECT ONZOT.* 
			FROM OW_LAO.ODS_NERP_ZLLEJ50090_OUTBOUND_TRACKING ONZOT
			WHERE  ONZOT.SO_TYPE = 'YS10' AND ONZOT.DO_TYPE = 'ZND1') ONZOT
	ON (ONZASOT.SALES_DOCUMENT =ONZOT.REFERENCE_DOC_SO_PO AND ONZASOT.MATERIAL = ONZOT.MATERIAL
	AND ONZASOT.DELIVERY_ITEM = ONZOT.DELIVERY_ITEM AND ONZASOT.DELIVERY = ONZOT.DELIVERY_NO)
LEFT JOIN (SELECT DISTINCT
				   ONZDDTIR.RETURN_DO_NO
				  ,ONZDDTIR.MATERIAL
				  ,ONZDDTIR.R_SO_ITEM
				  ,ONZDDTIR.R_DO_ITEM
				  ,ONZDDTIR.R_SO_TYPE
				  ,ONZDDTIR.R_DO_TYPE
				  ,ONZDDTIR.O_SO_NO 
				  ,ONZDDTIR.O_DO_NO 
				  ,ONZDDTIR.O_SO_ITEM 
				  ,ONZDDTIR.O_DO_ITEM 
				  ,ONZDDTIR.REMARK 
			FROM OW_LAO.ODS_NERP_ZLLEE50090_DISPLAY_DO_TRACKING_INFO_RETURN ONZDDTIR
			WHERE(R_SO_TYPE = 'YR01' AND R_DO_TYPE = 'ZRC1')
			OR   (R_SO_TYPE = 'YS10' AND R_DO_TYPE = 'ZRLA')
			OR   (R_SO_TYPE = 'YRT1' AND R_DO_TYPE = 'ZRT1')
			OR   (R_SO_TYPE = 'YN01' AND R_DO_TYPE = 'ZRLA')
			OR   (R_SO_TYPE = 'YS03' AND R_DO_TYPE = 'ZRLA')
			OR   (R_SO_TYPE = 'YS02' AND R_DO_TYPE = 'ZRLA')
			OR   (R_SO_TYPE = 'YRT3' AND R_DO_TYPE = 'ZRLA')
			OR   (R_SO_TYPE = 'YNC1' AND R_DO_TYPE = 'ZRLA')
			OR   (R_SO_TYPE = 'YFT1' AND R_DO_TYPE = 'ZRLA')
			OR   (R_SO_TYPE = 'YRH1' AND R_DO_TYPE = 'ZRC1')
			OR   (R_SO_TYPE = 'YF01' AND R_DO_TYPE = 'ZRLA')
			OR   (R_SO_TYPE = 'YP01' AND R_DO_TYPE = 'ZRLA')
		   ) ONZDDTIR 
	ON (ONZOT.REFERENCE_DOC_SO_PO = ONZDDTIR.O_SO_NO AND ONZOT.MATERIAL = ONZDDTIR.MATERIAL
		AND ONZOT.DELIVERY_ITEM = ONZDDTIR.O_DO_ITEM AND ONZOT.DELIVERY_NO = ONZDDTIR.O_DO_NO )
LEFT JOIN (SELECT RONZOT.* FROM OW_LAO.ODS_NERP_ZLLEJ50090_OUTBOUND_TRACKING RONZOT) RONZOT 
	ON (ONZDDTIR.RETURN_DO_NO = RONZOT.DELIVERY_NO AND ONZDDTIR.MATERIAL = RONZOT.MATERIAL)		   				 	
LEFT JOIN OW_LAO.DIM_AFFILIATE_CHANNEL DAC 
	ON DAC.AFFILIATE_ID = OW_LAO.AFFILIATE_ID_ADJUSTED(OVSBSDESS.ID_STORE, RVSBSSOL.AFFILIATE_ID, RVSBSSOL.SALES_CHANNEL)
LEFT JOIN (SELECT DISTINCT FUTC."DO No." 
			  ,FUTC."Order Status " AS "DO_STATUS" 
			  ,FUTC."NF Amt" AS "DO_AMT"
		  	FROM OW_SEDA_S.FT_UNION_TSS_CELLO FUTC 
	  	  WHERE YEAR(FUTC."DO Insert Date") >= YEAR(ADD_YEARS(CURRENT_DATE,-1))
	  	  		AND SUBSTRING("DO No.",1,1)  = '7') AS FUTCA 
	ON (ONZASOT.DELIVERY = FUTCA."DO No.")  
LEFT JOIN (SELECT * 
		      ,VCRT.RDO_NUMBER AS RDO
			  --,ORIG_DO_NO
			  --,VCRT.STATUS_NM
			  --,VCRT.RDO_INSERT_DATE
			  ,VCRT.RDO_RETURN_IOD_DATE AS RDO_IOD
			  --,VCRT.GR_DATE
			  --,VCRT.IOD_DT 
			  --,VCRT.RDO_RETURN_IOD_DATE 

			THEN '31~45 Indue'
		WHEN ONFNCLIDOI.ARREARS_BY_NET_DUE_DATE BETWEEN 1 AND 7
			THEN '1 ~ 7 days'
		WHEN ONFNCLIDOI.ARREARS_BY_NET_DUE_DATE BETWEEN 8 AND 14

	,RVSBSSOL.STATUS_DESCRIPTION AS VTEX_STATUS
	,(RVSBSSOL.VALUE/100) AS VTEX_AMOUNT
	,IFNULL(URVSBSSOL.SELLING_PRICE,0) AS VTEX_SC_PLUS-- Vtex( SC+)

	,DRVSBSSOP.VOUCHER_NO
	
	--Pegar dados do NERP 
	,COUNT(DISTINCT ONZASOT.DELIVERY) OVER (PARTITION BY ONZASOT.CUSTOMER_PO) AS "DO Count"
	
	,ONZOT.DELIVERY_NO AS DO_NERP
	
	,ONZOT.EPOD AS DO_IOD_NERP --Era EPOD_DATE
	,ONZOT.AR_AMOUNT AS DO_AMT_NERP

	FROM OW_SEDA_S.ODS_NERP_FBL5N_CUSTOMER_LINE_ITEM_DISPLAY_OPEN_ITEMS_HIST ONFNCLIDOI2 
	WHERE UPPER(ONFNCLIDOI2.FILE_NAME) LIKE '%ALLITEM_WEEK%'
	-- TO REPROCESS THE COMPLETE BASE, COMMENT ON THE TEN LINES BELOW
	
	AND TO_DATE(SUBSTRING(ONFNCLIDOI2.FILE_NAME,25,8)) = (CASE WHEN DAYOFWEEK(CURRENT_DATE) = 6
									THEN ADD_DAYS(CURRENT_DATE,-1)
								WHEN DAYOFWEEK(CURRENT_DATE) = 2 
									THEN ADD_DAYS(CURRENT_DATE,-4)
								WHEN DAYOFWEEK(CURRENT_DATE) = 3 
									THEN ADD_DAYS(CURRENT_DATE,-5)
								WHEN DAYOFWEEK(CURRENT_DATE) = 4 
									THEN ADD_DAYS(CURRENT_DATE,-6)	
								ELSE NULL 
							     END)
	
		ORDER BY  ROW_NUMBER() OVER () ASC, ONFNCLIDOI2.CUSTOMER, ONFNCLIDOI2."ASSIGNMENT", ONFNCLIDOI2.DOCUMENT_NUMBER, REPLACE(ONFNCLIDOI2.AMOUNT_IN_LOCAL_CURRENCY,'.',',')
	) ONFNCLIDOI 
	LEFT JOIN (SELECT * FROM (SELECT --DISTINCT 
				 	ROW_NUMBER() OVER (PARTITION BY IFNULL(RVSBSSOL."SEQUENCE",RVSBSSOL.ORDER_ID) 
	         				ORDER BY IFNULL(RVSBSSOL."SEQUENCE",RVSBSSOL.ORDER_ID) DESC, RVSBSSOI.PRICE DESC) AS ROW_NUM

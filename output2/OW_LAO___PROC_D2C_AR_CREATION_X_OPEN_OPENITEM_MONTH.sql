		 END) AS WEEK_MONTH_FILE_NAME
		,(CASE WHEN ONFNCLIDOI2.FILE_NAME LIKE '%ALL%' 
			THEN 'ALL'
		       WHEN ONFNCLIDOI2.FILE_NAME LIKE'%OPEN%'
		 	THEN 'OPEN'
		 	ELSE NULL
		 END) AS OPEN_ALL_FILE_NAME
		 
		 ,(SELECT DC.YYYYWW_NORMAL_CALENDAR FROM OW_MD.DIM_CALENDAR DC WHERE DC.YYYYMMDD = TO_DATE(SUBSTRING(ONFNCLIDOI2.FILE_NAME,24,8))) AS "YEAR_WEEK_FILE_NAME"
		 ,(SELECT DC.YYYYMM_NORMAL_CALENDAR FROM OW_MD.DIM_CALENDAR DC WHERE DC.YYYYMMDD = TO_DATE(SUBSTRING(ONFNCLIDOI2.FILE_NAME,24,8))) AS "YEAR_MONTH_FILE_NAME"

					                        		, MAX(CITY) AS CITY
					                        		, MAX(SELECTED_SLA) AS SELECTED_SLA
					                        		, STRING_AGG(WAREHOUSE_ID, ' | ') AS WAREHOUSE_ID_GROUP
							FROM U_PRJ_ECOM.RAW_VTEX_SSG_BR_SHOP_SALES_ORDER_SHIPPING rvsbssos

	CREATE TABLE OW_LAO.TF_D2C_ONE_VIEW_TABLE_01 AS (
		SELECT DISTINCT URVSBSSOL.REF_ID
				,MSRBP.MANAUS_SKU_REFERENCE AS MATERIAL_ADJUSTED
				,MSRBP.CAJAMAR_SKU_REFERENCE
				,OW_LAO.AFFILIATE_ID_ADJUSTED(URVSBSSOL.ID_STORE, URVSBSSOL.AFFILIATE_ID, URVSBSSOL.SALES_CHANNEL) AS AFFILIATE_ID_ADJUSTED
				,NULL  AS DIMPROD_PRODUCT_GROUP 
				,NULL  AS DIMPROD_DIVISION 
				,NULL  AS DIMPROD_PRODUCT 
				,URVSBSSOL.QUANTITY
				,URVSBSSOL.PO_AMOUNT
				,URVSBSSOL.STATUS_DESCRIPTION
				,URVSBSSOL."SEQUENCE"
				,URVSBSSOL.ORDER_ID
				,URVSBSSOL.MARKETPLACE_ORDER_ID
				,NULL  AS SALES_DOCUMENT
				,URVSBSSOL.CREATION_DATE
				,URVSBSSOL.CANCELLATION_DATE
				,NULL  AS SO_CREATED_ON
				,NULL  AS REJECT_REASON
				,NULL  AS REJECT_REASON_1
				,NULL  AS DELIVERY_BLOCK 
				,NULL  AS SOLD_TO_PARTY 
				,CASE WHEN O2O_TYPE = 'BOPIS' 
					THEN
			                CASE WHEN (UPPER(SELECTED_SLA) LIKE 'CLIQUE RETIRE%') AND UPPER(ADDRESSTYPE) = 'PICKUP' 
			                 	THEN 'LOCKER' -- BOPIL
			                      WHEN TRIM(SUBSTRING_REGEXPR( '(CSP[a-zA-Z0-9]+)' IN SELECTED_SLA FROM 1 OCCURRENCE 1)) LIKE 'CSP%' 
			                      	THEN 'CSP'
			                END
		               	        ELSE TRIM(SUBSTRING_REGEXPR('[^|]+' IN NAME_STORE FROM 1 OCCURRENCE 1))
		                END AS CHANNEL_O2O
		
				,CASE WHEN O2O_TYPE = 'BOPIS' 
					THEN
		                  	CASE WHEN (UPPER(SELECTED_SLA) LIKE 'CLIQUE RETIRE%') AND UPPER(ADDRESSTYPE) = 'PICKUP' 
		                        	THEN 'Clique Retire' -- BOPIL
					     WHEN TRIM(SUBSTRING_REGEXPR( '(CSP[a-zA-Z0-9]+)' IN SELECTED_SLA FROM 1 OCCURRENCE 1)) LIKE 'CSP%' 
		                       		THEN 'CSP'
		                  	END
				        ELSE TRIM(SUBSTRING_REGEXPR('[^|]+' IN NAME_STORE FROM 1 OCCURRENCE 2))
				END AS PARTNER_O2O 
				,TRIM(SUBSTRING_REGEXPR('[^|]+' IN NAME_STORE FROM 1 OCCURRENCE 3)) AS STORE_TYPE_O2O
				,CASE WHEN O2O_TYPE = 'BOPIS'
					THEN
		                        IFNULL( CAST( OW_LAO.REPLACE_TEXT(TRIM(SUBSTRING_REGEXPR( '(CSP[a-zA-Z0-9]+)' IN SELECTED_SLA FROM 1 OCCURRENCE 1)),'CSP','',FALSE) AS VARCHAR(5000))
						,CASE WHEN UPPER(SELECTED_SLA) LIKE 'CLIQUE RETIRE%' THEN CAST(FRIENDLYNAME AS VARCHAR(5000))  END)
		               	        ELSE TRIM(SUBSTRING_REGEXPR('[^|]+' IN NAME_STORE FROM 1 OCCURRENCE 4)) 
				END AS STORE_NAME_O2O
				,URVSBSSOL.LAST_CHANGE
				,NULL  AS CUSTOMER_PO 
				,NULL  AS MATERIAL 
				,NULL  AS DELIVERY_ITEM 
				,NULL  AS DELIVERY 
				,URVSBSSOL.SKU_AMT_TTL

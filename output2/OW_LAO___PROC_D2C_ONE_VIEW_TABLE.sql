							END) = OVSBSDESS.ID_STORE)	   				             
		        WHERE  YEAR(TO_DATE(RVSBSSOL.CREATION_TIMESTAMP)) >= YEAR(ADD_YEARS(CURRENT_DATE,-1)) --TO_DATE(RVSBSSOL.CREATION_TIMESTAMP) >= '2023.01.01'
		        AND RVSBSSOL.STATUS_DESCRIPTION IS NOT NULL) URVSBSSOL	
			LEFT JOIN "OW_MD"."MAP_SKU_REFERENCE_BY_PLANT" MSRBP ON (URVSBSSOL.REF_ID = MSRBP.CAJAMAR_SKU_REFERENCE)	        
			--LEFT JOIN OW_LAO.ODS_NERP_ZRSDD6A120_SALES_ORDER_TRACKING ONZASOT ON  
			--	(URVSBSSOL.ORDER_ID =  ONZASOT.CUSTOMER_PO  OR TO_CHAR(URVSBSSOL."SEQUENCE") =  ONZASOT.CUSTOMER_PO )  

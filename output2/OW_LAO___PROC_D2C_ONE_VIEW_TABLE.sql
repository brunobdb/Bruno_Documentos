	/*********************************************************
	* CRIA A TF_ONE_VIEW_TABLE_BASE_ORDERS
	* *******************************************************/
	IF EXISTS ( SELECT TABLE_NAME FROM SYS.TABLES WHERE SCHEMA_NAME = 'OW_LAO' AND TABLE_NAME = 'TF_ONE_VIEW_TABLE_BASE_ORDERS' ) THEN
		DROP TABLE OW_LAO.TF_ONE_VIEW_TABLE_BASE_ORDERS;
	END IF ;
	CREATE TABLE OW_LAO.TF_ONE_VIEW_TABLE_BASE_ORDERS AS (
	 SELECT 
	        RVSBSSOL.ORDER_ID,
	        RVSBSSOL.MARKETPLACE_ORDER_ID,
	        RVSBSSOL.AFFILIATE_ID,
	        RVSBSSOL."SEQUENCE",
	        TO_DATE(RVSBSSOL.CREATION_TIMESTAMP) AS CREATION_DATE,
	        RVSBSSOL.CANCELLATION_DATE,
	        RVSBSSOL.STATUS_DESCRIPTION,
	        RVSBSSOL.SALES_CHANNEL,
	        RVSBSSOL.LAST_CHANGE,
	        (RVSBSSOL.VALUE / 100) AS PO_AMOUNT,
	        RVSBSSOI.ITEM_INDEX,
	        CASE 
	            WHEN RVSBSSOIC.REF_ID IS NULL THEN RVSBSSOI.REF_ID
	            ELSE RVSBSSOIC.REF_ID
	        END AS REF_ID,
	        (RVSBSSOI.QUANTITY * IFNULL(RVSBSSOIC.QUANTITY, 1)) AS QUANTITY,
	        ((RVSBSSOI.SELLING_PRICE / 100) * RVSBSSOI.QUANTITY) AS SKU_AMT_TTL,
	        -- ID_STORE calculado
	        CASE 
	            WHEN RVSBSSOL.CD_STORE_INFORMATION IS NOT NULL THEN RVSBSSOL.CD_STORE_INFORMATION
	            WHEN RVSBSO.CD_STORE_INFORMATION IS NOT NULL THEN RVSBSO.CD_STORE_INFORMATION
	            WHEN RVSBSSOL.UTM_SOURCE IS NOT NULL THEN RVSBSSOL.UTM_SOURCE
	            ELSE RVSBSO.UTM_SOURCE
	        END AS ID_STORE
	    FROM U_PRJ_ECOM.RAW_VTEX_SSG_BR_SHOP_SALES_ORDER RVSBSSOL
	    LEFT JOIN U_PRJ_ECOM.RAW_VTEX_SSG_BR_SHOP_SALES_ORDER_ITEM RVSBSSOI
	        ON RVSBSSOL.ORDER_ID = RVSBSSOI.ORDER_ID
	    LEFT JOIN U_PRJ_ECOM.RAW_VTEX_SSG_BR_SHOP_SALES_ORDER_ITEM_COMPONENTS RVSBSSOIC
	        ON RVSBSSOI.ORDER_ID = RVSBSSOIC.ORDER_ID AND RVSBSSOI.SKU_ID = RVSBSSOIC.SKU_ID
	    LEFT JOIN U_PRJ_ECOM.RAW_VTEX_SSG_BR_SALES_ORDER RVSBSO
	        ON RVSBSSOL.MARKETPLACE_ORDER_ID = RVSBSO.ORDER_ID
	    WHERE TO_DATE(RVSBSSOL.CREATION_TIMESTAMP) >= ADD_YEARS(CURRENT_DATE, -1)
	      AND RVSBSSOL.STATUS_DESCRIPTION IS NOT NULL
	 );
	/*********************************************************
	* CRIA A TF_ONE_VIEW_TABLE_SHIPPING_INFO
	* *******************************************************/
	IF EXISTS ( SELECT TABLE_NAME FROM SYS.TABLES WHERE SCHEMA_NAME = 'OW_LAO' AND TABLE_NAME = 'TF_ONE_VIEW_TABLE_SHIPPING_INFO' ) THEN
		DROP TABLE OW_LAO.TF_ONE_VIEW_TABLE_SHIPPING_INFO;
	END IF ;
	CREATE TABLE OW_LAO.TF_ONE_VIEW_TABLE_SHIPPING_INFO AS (
	    SELECT 
	        ORDER_ID,
	        ITEM_INDEX,
	        MAX(JSON_VALUE('[' || PICKUP_STORE_INFO || ']', '$.address.addressType')) AS ADDRESSTYPE,
	        MAX(JSON_VALUE('[' || PICKUP_STORE_INFO || ']', '$.friendlyName')) AS FRIENDLYNAME,
	        MAX(STATE) AS STATE,
	        MAX(CITY) AS CITY,
	        MAX(SELECTED_SLA) AS SELECTED_SLA,
	        STRING_AGG(WAREHOUSE_ID, ' | ') AS WAREHOUSE_ID_GROUP,
	        SELLING_PRICE / 100 AS SHIPPING_AMT_TTL
	    FROM U_PRJ_ECOM.RAW_VTEX_SSG_BR_SHOP_SALES_ORDER_SHIPPING
	    WHERE ORDER_ID IN (SELECT DISTINCT ORDER_ID FROM OW_LAO.TF_ONE_VIEW_TABLE_BASE_ORDERS)
	    GROUP BY ORDER_ID, ITEM_INDEX, SELLING_PRICE
	);
	/*********************************************************
	* CRIA A TF_ONE_VIEW_TABLE_STORE_INFO
	* *******************************************************/
	IF EXISTS ( SELECT TABLE_NAME FROM SYS.TABLES WHERE SCHEMA_NAME = 'OW_LAO' AND TABLE_NAME = 'TF_ONE_VIEW_TABLE_STORE_INFO' ) THEN
		DROP TABLE OW_LAO.TF_ONE_VIEW_TABLE_STORE_INFO;
	END IF ;
	CREATE TABLE OW_LAO.TF_ONE_VIEW_TABLE_STORE_INFO AS (
	    SELECT 
	        ID_STORE,
	        NAME AS NAME_STORE
	    FROM U_PRJ_ECOM.ODS_VTEX_SSG_BR_SHOP_DATA_ENTITIES_STORES_SDS
	);
	/*********************************************************
	* CRIA A TF_ONE_VIEW_TABLE_O2O_DATA
	* *******************************************************/
	IF EXISTS ( SELECT TABLE_NAME FROM SYS.TABLES WHERE SCHEMA_NAME = 'OW_LAO' AND TABLE_NAME = 'TF_ONE_VIEW_TABLE_O2O_DATA' ) THEN
		DROP TABLE OW_LAO.TF_ONE_VIEW_TABLE_O2O_DATA;
	END IF ;
	CREATE TABLE OW_LAO.TF_ONE_VIEW_TABLE_O2O_DATA AS (
	  SELECT 
	        BO.*,
	        SI.SELECTED_SLA,
	        SI.ADDRESSTYPE,
	        SI.FRIENDLYNAME,
	        SI.WAREHOUSE_ID_GROUP,
	        SI.SHIPPING_AMT_TTL,
	        (BO.SKU_AMT_TTL + SI.SHIPPING_AMT_TTL) AS TTL_SKU_SHIPPING_TTL,
	        ST.NAME_STORE,
	
	        -- O2O_TYPE
	        CASE 
	            WHEN TRIM(UPPER(SI.SELECTED_SLA)) LIKE 'SHIP TO STORE%' 
	              OR TRIM(UPPER(SI.SELECTED_SLA)) LIKE 'PONTO DE RETIRADA%' 
	              OR TRIM(UPPER(SI.SELECTED_SLA)) LIKE 'CLIQUE%' THEN
	                CASE 
	                    WHEN BO.ID_STORE IS NOT NULL THEN 'BOPIS + EA'
	                    ELSE 'BOPIS'
	                END
	            WHEN BO.ID_STORE IS NOT NULL THEN 'EA'
	            ELSE NULL
	        END AS O2O_TYPE
	    FROM OW_LAO.TF_ONE_VIEW_TABLE_BASE_ORDERS BO
	    LEFT JOIN OW_LAO.TF_ONE_VIEW_TABLE_SHIPPING_INFO SI 
	        ON BO.ORDER_ID = SI.ORDER_ID AND BO.ITEM_INDEX = SI.ITEM_INDEX
	    LEFT JOIN OW_LAO.TF_ONE_VIEW_TABLE_STORE_INFO ST 
	        ON BO.ID_STORE = ST.ID_STORE
	);
	/*********************************************************
	* CRIA A TF_ONE_VIEW_TABLE_SKU_REF
	* *******************************************************/
	IF EXISTS ( SELECT TABLE_NAME FROM SYS.TABLES WHERE SCHEMA_NAME = 'OW_LAO' AND TABLE_NAME = 'TF_ONE_VIEW_TABLE_SKU_REF' ) THEN
		DROP TABLE OW_LAO.TF_ONE_VIEW_TABLE_SKU_REF;
	END IF ;
	CREATE TABLE OW_LAO.TF_ONE_VIEW_TABLE_SKU_REF AS (
	    SELECT 
	        CAJAMAR_SKU_REFERENCE,
	        MANAUS_SKU_REFERENCE
	    FROM "OW_MD"."MAP_SKU_REFERENCE_BY_PLANT"
	);
	/*********************************************************
	* CRIA A TF_D2C_ONE_VIEW_TABLE_01
	* *******************************************************/
	IF EXISTS ( SELECT TABLE_NAME FROM SYS.TABLES WHERE SCHEMA_NAME = 'OW_LAO' AND TABLE_NAME = 'TF_D2C_ONE_VIEW_TABLE_01' ) THEN
		DROP TABLE OW_LAO.TF_D2C_ONE_VIEW_TABLE_01;
	END IF ;
	CREATE TABLE OW_LAO.TF_D2C_ONE_VIEW_TABLE_01 AS (
	SELECT DISTINCT 
	    OD.REF_ID,
	    SR.MANAUS_SKU_REFERENCE AS MATERIAL_ADJUSTED,
	    SR.CAJAMAR_SKU_REFERENCE,
	    OW_LAO.AFFILIATE_ID_ADJUSTED(OD.ID_STORE, OD.AFFILIATE_ID, OD.SALES_CHANNEL) AS AFFILIATE_ID_ADJUSTED,
	    NULL AS DIMPROD_PRODUCT_GROUP,
	    NULL AS DIMPROD_DIVISION,
	    NULL AS DIMPROD_PRODUCT,
	    OD.QUANTITY,
	    OD.PO_AMOUNT,
	    OD.STATUS_DESCRIPTION,
	    OD."SEQUENCE",
	    OD.ORDER_ID,
	    OD.MARKETPLACE_ORDER_ID,
	    NULL AS SALES_DOCUMENT,
	    OD.CREATION_DATE,
	    OD.CANCELLATION_DATE,
	    NULL AS SO_CREATED_ON,
	    NULL AS REJECT_REASON,
	    NULL AS REJECT_REASON_1,
	    NULL AS DELIVERY_BLOCK,
	    NULL AS SOLD_TO_PARTY,
	
	    -- Campos O2O usando NAME_STORE
	    CASE 
	        WHEN O2O_TYPE = 'BOPIS' THEN
	            CASE 
	                WHEN (UPPER(SELECTED_SLA) LIKE 'CLIQUE RETIRE%') AND UPPER(ADDRESSTYPE) = 'PICKUP' THEN 'LOCKER'
	                WHEN TRIM(SUBSTRING_REGEXPR('(CSP[a-zA-Z0-9]+)' IN SELECTED_SLA FROM 1 OCCURRENCE 1)) LIKE 'CSP%' THEN 'CSP'
	            END
	        ELSE TRIM(SUBSTRING_REGEXPR('[^|]+' IN NAME_STORE FROM 1 OCCURRENCE 1))
	    END AS CHANNEL_O2O,
	
	    CASE 
	        WHEN O2O_TYPE = 'BOPIS' THEN
	            CASE 
	                WHEN (UPPER(SELECTED_SLA) LIKE 'CLIQUE RETIRE%') AND UPPER(ADDRESSTYPE) = 'PICKUP' THEN 'Clique Retire'
	                WHEN TRIM(SUBSTRING_REGEXPR('(CSP[a-zA-Z0-9]+)' IN SELECTED_SLA FROM 1 OCCURRENCE 1)) LIKE 'CSP%' THEN 'CSP'
	            END
	        ELSE TRIM(SUBSTRING_REGEXPR('[^|]+' IN NAME_STORE FROM 2 OCCURRENCE 1))
	    END AS PARTNER_O2O,
	
	    TRIM(SUBSTRING_REGEXPR('[^|]+' IN NAME_STORE FROM 3 OCCURRENCE 1)) AS STORE_TYPE_O2O,
	
	    CASE 
	        WHEN O2O_TYPE = 'BOPIS' THEN
	            IFNULL(
	                CAST(OW_LAO.REPLACE_TEXT(TRIM(SUBSTRING_REGEXPR('(CSP[a-zA-Z0-9]+)' IN SELECTED_SLA FROM 1 OCCURRENCE 1)), 'CSP', '', FALSE) AS VARCHAR(5000)),
	                CASE WHEN UPPER(SELECTED_SLA) LIKE 'CLIQUE RETIRE%' THEN CAST(FRIENDLYNAME AS VARCHAR(5000)) END
	            )
	        ELSE TRIM(SUBSTRING_REGEXPR('[^|]+' IN NAME_STORE FROM 4 OCCURRENCE 1))
	    END AS STORE_NAME_O2O,
	
	    OD.LAST_CHANGE,
	    NULL AS CUSTOMER_PO,
	    NULL AS MATERIAL,
	    NULL AS DELIVERY_ITEM,
	    NULL AS DELIVERY,
	    OD.SKU_AMT_TTL,
	    OD.SHIPPING_AMT_TTL,
	    OD.TTL_SKU_SHIPPING_TTL
	
	FROM OW_LAO.TF_ONE_VIEW_TABLE_O2O_DATA OD
	LEFT JOIN OW_LAO.TF_ONE_VIEW_TABLE_SKU_REF SR ON OD.REF_ID = SR.CAJAMAR_SKU_REFERENCE);
	
	--Truncar Tabela com os dados no nivel granular mais baixo para tratamento de dados 
	--TRUNCATE TABLE OW_LAO.TF_D2C_ONE_VIEW_TABLE_02;
	
	/*********************************************************
	* CRIA A TF_D2C_ONE_VIEW_TABLE_02
	* *******************************************************/
	IF EXISTS ( SELECT TABLE_NAME FROM SYS.TABLES WHERE SCHEMA_NAME = 'OW_LAO' AND TABLE_NAME = 'TF_D2C_ONE_VIEW_TABLE_02' ) THEN
		DROP TABLE OW_LAO.TF_D2C_ONE_VIEW_TABLE_02;
	END IF ;
	--Inserir os dados no nivel granular mais baixo na tabela de transformação select top 100 DIMPROD_PRODUCT_GROUP, DIMPROD_DIVISION, DIMPROD_PRODUCT  from OW_LAO.TF_D2C_ONE_VIEW_TABLE_02
	--INSERT INTO  OW_LAO.TF_D2C_ONE_VIEW_TABLE_02
	CREATE TABLE OW_LAO.TF_D2C_ONE_VIEW_TABLE_02 AS (
	SELECT 
			TDCOVT.REF_ID
			,(CASE WHEN TDCOVT.REF_ID = ONZASOT.MATERIAL
					THEN TDCOVT.REF_ID
				   WHEN TDCOVT.REF_ID = ONZASOT.MATERIAL AND TDCOVT.MATERIAL_ADJUSTED IS NOT NULL
					THEN TDCOVT.MATERIAL_ADJUSTED
				   ELSE TDCOVT.REF_ID		
			END) AS MATERIAL_ADJUSTED
			,TDCOVT.CAJAMAR_SKU_REFERENCE
			,TDCOVT.AFFILIATE_ID_ADJUSTED
			,DP.SEDA_BU_ESTORE AS DIMPROD_PRODUCT_GROUP -- ,DP.PRODUCT_GROUP_1 AS DIMPROD_PRODUCT_GROUP 

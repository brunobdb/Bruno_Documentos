	SELECT
		  PO_.DATE_REF
		, PO_.PO_CREATION_DATE
		, PO_.SALES_CHANNEL
		, OW_LAO.AFFILIATE_ID_ADJUSTED(ES.ID_STORE, PO_.AFFILIATE_ID, PO_.SALES_CHANNEL) AS AFFILIATE_ID_ADJUSTED

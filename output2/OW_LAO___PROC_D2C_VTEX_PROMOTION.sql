				 	CASE WHEN TT.SELLING_AMOUNT_LOCAL_TOTAL > 0 THEN 
						( ( CAST(PM.SELLING_AMOUNT_LOCAL AS DECIMAL(18,6)) / TT.SELLING_AMOUNT_LOCAL_TOTAL ) * CAST(PM.PRC_TAG_RAWVALUE AS DECIMAL(18,6)) ) -- RATIO
					END
				 ELSE -- SENÃO PEGA O VALOR TODO DO ITEM

-- CALL OW_LAO.PROC_D2C_VTEX_PROMOTION( ADD_DAYS(CURRENT_TIMESTAMP, -1),  ADD_DAYS(CURRENT_TIMESTAMP, 1))
***********************************************************************************************/
CREATE PROCEDURE OW_LAO.PROC_D2C_VTEX_PROMOTION (
	 p_DATE_INI DATE DEFAULT NULL
	,P_DATE_FIM DATE DEFAULT NULL
) LANGUAGE SQLSCRIPT
AS
BEGIN
	
	/*********************************************************
	* DECLARAÇÃO DE VARIAVEIS E CURSOR
	* *******************************************************/
	DECLARE v_ORDER_ID VARCHAR(80); 
	DECLARE v_SKU_ID VARCHAR(80);
	DECLARE v_SKU_ID_COMPONENT VARCHAR(80);
	DECLARE v_PRICE_TAGS VARCHAR(5000);
	DECLARE v_PRICE_TAGS_ORIGIN VARCHAR(5000);	
	DECLARE v_PRICE_TAGS_EPP VARCHAR(5000);
	DECLARE v_PRICE_TAGS_SSGBR VARCHAR(5000);
	DECLARE v_PRICE_TAGS_B2B VARCHAR(5000);
	DECLARE v_REF_ID_COUNT INTEGER;
	DECLARE v_PRICE_TAGS_INSTANCES NVARCHAR(10000);
	DECLARE CURSOR c_select FOR 
		SELECT ORDER_ID
			, SKU_ID
			, SKU_ID_COMPONENT
			, REF_ID_COUNT
			, PRICE_TAGS
			, PRICE_TAGS_ORIGIN	
			, PRICE_TAGS_EPP
			, PRICE_TAGS_SSGBR
			, PRICE_TAGS_B2B
		FROM OW_LAO.TMP_PO_VTEX_PROMOTION;
	-- OBS PRECISA CRIAR A TABELA OW_LAO.TMP_PO_VTEX_PROMOTION PARA PODER CRIAR A PROC
	
	/*********************************************************
	* CRIA A TMP_PARAMETER_VTEX_PROMOTION
	* *******************************************************/
	IF EXISTS ( SELECT TABLE_NAME FROM SYS.TABLES WHERE SCHEMA_NAME = 'OW_LAO' AND TABLE_NAME = 'TMP_PARAMETER_VTEX_PROMOTION' ) THEN
		DROP TABLE OW_LAO.TMP_PARAMETER_VTEX_PROMOTION;
	END IF ;
	CREATE COLUMN TABLE OW_LAO.TMP_PARAMETER_VTEX_PROMOTION AS (
		SELECT ADD_DAYS(CURRENT_TIMESTAMP, -1) AS DATE_INI, ADD_DAYS(CURRENT_TIMESTAMP, 1) AS DATE_FIM FROM DUMMY
	);
	UPDATE OW_LAO.TMP_PARAMETER_VTEX_PROMOTION SET
		 DATE_INI = IFNULL(p_DATE_INI, ADD_DAYS(CURRENT_TIMESTAMP, -1))
		,DATE_FIM = IFNULL(P_DATE_FIM, ADD_DAYS(CURRENT_TIMESTAMP, 1)) 
	;
	
	 /*********************************************************
	 * CRIA TEMP CUSTOMER_PO E FAZ FILTRO
	 * CRIA TMP_PO_ORDER_ID_PO_VTEX_PROMOTION E ( FAZ O CORTE DO PERIODO CLASSIFICA O CUSTOMER_PO E E AGRUPA AS ORDERS)
	 * *******************************************************/	
	IF EXISTS ( SELECT TABLE_NAME FROM SYS.TABLES WHERE SCHEMA_NAME = 'OW_LAO' AND TABLE_NAME = 'TMP_PO_ORDER_ID_PO_VTEX_PROMOTION' ) THEN
		DROP TABLE OW_LAO.TMP_PO_ORDER_ID_PO_VTEX_PROMOTION;
	END IF;
	CREATE COLUMN TABLE OW_LAO.TMP_PO_ORDER_ID_PO_VTEX_PROMOTION AS (
		SELECT DISTINCT
			  LI.ORDER_ID
			, LI.CUSTOMER_PO
		FROM (
				SELECT V.ORDER_ID
					, MAX( CASE WHEN S.CUSTOMER_PO IS NOT NULL THEN S.CUSTOMER_PO ELSE CAST(V."SEQUENCE" AS VARCHAR(100)) END ) AS CUSTOMER_PO
					, MAX(V.UPDATED_AT) AS UPDATED_AT 
				FROM U_PRJ_ECOM.RAW_VTEX_SSG_BR_SHOP_SALES_ORDER V 
					LEFT JOIN OW_LAO.ODS_NERP_ZRSDD6A120_SALES_ORDER_TRACKING S ON V.ORDER_ID = S.CUSTOMER_PO
				WHERE V.CREATION_TIMESTAMP BETWEEN ( SELECT DATE_INI FROM OW_LAO.TMP_PARAMETER_VTEX_PROMOTION ) AND (SELECT DATE_FIM FROM OW_LAO.TMP_PARAMETER_VTEX_PROMOTION )
				--WHERE V.ORDER_ID = '1520759668523-01'
				GROUP BY V.ORDER_ID
			) LI
			
			/********** BR SHOP ***********/
			INNER JOIN U_PRJ_ECOM.RAW_VTEX_SSG_BR_SHOP_SALES_ORDER BSO -- (BR SHOP - ORDER )
				ON BSO.ORDER_ID = LI.ORDER_ID
			INNER JOIN U_PRJ_ECOM.RAW_VTEX_SSG_BR_SHOP_SALES_ORDER_ITEM BSI -- (BR SHOP - ITEM)
				ON BSO.ORDER_ID = BSI.ORDER_ID
				
			/********** SSG BR ***********/
			LEFT JOIN U_PRJ_ECOM.RAW_VTEX_SSG_BR_SALES_ORDER SSO -- (SSG BR - ORDER )
				ON BSO.MARKETPLACE_ORDER_ID = SSO.ORDER_ID
			LEFT JOIN U_PRJ_ECOM.RAW_VTEX_SSG_BR_SALES_ORDER_ITEM SSI -- (BR SHOP - ITEM)
				ON BSO.MARKETPLACE_ORDER_ID = SSI.ORDER_ID ----
				   AND BSI.REF_ID = CASE WHEN RIGHT(SSI.REF_ID,5) LIKE '_OUT%' THEN SUBSTRING(SSI.REF_ID, 1, LENGTH(SSI.REF_ID) - 5) ELSE SSI.REF_ID END
				   AND BSI.ITEM_INDEX = SSI.ITEM_INDEX
				   
			/********** EPP2 ***********/
			LEFT JOIN U_PRJ_ECOM.RAW_VTEX_SSG_BR_EPP2_SALES_ORDER EPO --(EPP2 - ORDER)
				ON BSO.MARKETPLACE_ORDER_ID = EPO.ORDER_ID
			LEFT JOIN U_PRJ_ECOM.RAW_VTEX_SSG_BR_EPP2_SALES_ORDER_ITEM EPI -- (BR SHOP - ITEM)
				ON BSO.MARKETPLACE_ORDER_ID = EPI.ORDER_ID
				   AND BSI.REF_ID = CASE WHEN RIGHT(EPI.REF_ID,5) LIKE '_OUT%' THEN SUBSTRING(EPI.REF_ID, 1, LENGTH(EPI.REF_ID) - 5) ELSE EPI.REF_ID END
				   AND BSI.ITEM_INDEX = EPI.ITEM_INDEX		
				   
			/********** B2B ***********/
			LEFT JOIN U_PRJ_ECOM.RAW_VTEX_SSG_BR_B2B_SALES_ORDER B2O --(EPP2 - ORDER)
				ON BSO.MARKETPLACE_ORDER_ID = B2O.ORDER_ID
			LEFT JOIN U_PRJ_ECOM.RAW_VTEX_SSG_BR_B2B_SALES_ORDER_ITEM B2I -- (BR SHOP - ITEM)
				ON BSO.MARKETPLACE_ORDER_ID = B2I.ORDER_ID
				   AND BSI.REF_ID = CASE WHEN RIGHT(B2I.REF_ID,5) LIKE '_OUT%' THEN SUBSTRING(B2I.REF_ID, 1, LENGTH(B2I.REF_ID) - 5) ELSE B2I.REF_ID END
				   AND BSI.ITEM_INDEX = B2I.ITEM_INDEX
				   
		WHERE 
			   (       ( IFNULL(B2I.PRICE_TAGS,'') NOT IN ('','[]') )
			   		OR ( IFNULL(EPI.PRICE_TAGS,'') NOT IN ('','[]') )
					OR ( IFNULL(SSI.PRICE_TAGS,'') NOT IN ('','[]') )
					OR ( IFNULL(BSI.PRICE_TAGS,'') NOT IN ('','[]') )
					-- OU PRECISA TER UM COUPON
					OR COALESCE(EPO.COUPON,SSO.COUPON,BSO.COUPON,B2O.COUPON) IS NOT NULL
				)
			AND BSO.STATUS IS NOT NULL
			AND ( CASE WHEN B2O.ORDER_ID IS NOT NULL THEN B2O.STATUS
					   WHEN EPO.ORDER_ID IS NOT NULL THEN EPO.STATUS
				       WHEN SSO.ORDER_ID IS NOT NULL THEN SSO.STATUS
				       ELSE BSO.STATUS
			      END 
			    ) IS NOT NULL
	);
	/***********************************
	-- CRIA TABELA TMP_ITEM_COMPONENTS_PO_VTEX_PROMOTION DO DISCO
	***********************************/
	IF EXISTS( SELECT TABLE_NAME FROM SYS.TABLES WHERE SCHEMA_NAME = 'OW_LAO' AND TABLE_NAME = 'TMP_ITEM_COMPONENTS_PO_VTEX_PROMOTION') THEN
		DROP TABLE OW_LAO.TMP_ITEM_COMPONENTS_PO_VTEX_PROMOTION;
	END IF;
	CREATE COLUMN TABLE OW_LAO.TMP_ITEM_COMPONENTS_PO_VTEX_PROMOTION AS(
		SELECT --DISTINCT
			  CP.ORDER_ID
			, CP.SKU_ID
			, CP.SKU_ID_COMPONENT
			, CP.REF_ID
			, CP.NAME
			, CP.QUANTITY
			, CP.PRICE
			, CP.COST_PRICE
			, CP.SELLING_PRICE
			, ( CP.SELLING_PRICE * CP.QUANTITY ) AS SELLING_PRICE_AMOUNT
			, CAST( 0 AS DECIMAL(18,4) ) AS SELLING_PRICE_TOTAL
			, 1 AS ITEM_INDEX_COMPONENT
			, ROW_NUMBER() OVER (PARTITION BY CP.ORDER_ID, CP.SKU_ID ORDER BY CP.ORDER_ID, CP.SKU_ID, CP.SKU_ID_COMPONENT, CP.QUANTITY, ( CP.SELLING_PRICE * CP.QUANTITY )) AS ITEM_INDEX_KIT
		FROM U_PRJ_ECOM.RAW_VTEX_SSG_BR_SHOP_SALES_ORDER_ITEM_COMPONENTS CP
			 INNER JOIN OW_LAO.TMP_PO_ORDER_ID_PO_VTEX_PROMOTION TP ON CP.ORDER_ID = TP.ORDER_ID
		WHERE (CP.REF_ID IS NOT NULL)
	);
	
	-- ATUALIZA ITEM_INDEX_COMPONENT (PARA CASOS DE SKU_ID DUPLICADOS NOS KITS)
	UPDATE CP SET 
		  ITEM_INDEX_COMPONENT = CT.ITEM_INDEX_COMPONENT 
	FROM OW_LAO.TMP_ITEM_COMPONENTS_PO_VTEX_PROMOTION CP
		INNER JOIN (
			SELECT ORDER_ID
			    , SKU_ID
			    , SKU_ID_COMPONENT
			    , ROW_NUMBER() OVER (PARTITION BY ORDER_ID, SKU_ID ORDER BY ORDER_ID, SKU_ID) AS ITEM_INDEX_COMPONENT
			FROM (
			     SELECT DISTINCT ORDER_ID, SKU_ID, SKU_ID_COMPONENT
			     FROM OW_LAO.TMP_ITEM_COMPONENTS_PO_VTEX_PROMOTION
			)
		) CT ON  CP.ORDER_ID = CT.ORDER_ID
			    AND CP.SKU_ID = CT.SKU_ID
			    AND CP.SKU_ID_COMPONENT = CT.SKU_ID_COMPONENT
	;
	
	/*******************************
	-- ATUALIZA SELLING_PRICE_TOTAL PARA RATEIO
	*******************************/
	UPDATE TP SET TP.SELLING_PRICE_TOTAL = TT.SELLING_PRICE_TOTAL
	FROM OW_LAO.TMP_ITEM_COMPONENTS_PO_VTEX_PROMOTION TP
		INNER JOIN (
				SELECT ORDER_ID
					 , SKU_ID
					 , SUM(SELLING_PRICE_AMOUNT) AS SELLING_PRICE_TOTAL 
				FROM OW_LAO.TMP_ITEM_COMPONENTS_PO_VTEX_PROMOTION
				GROUP BY
					  ORDER_ID
					, SKU_ID				
		) TT ON TP.ORDER_ID = TT.ORDER_ID
				AND TP.SKU_ID = TT.SKU_ID
	;
	
	/***********************************
	-- CRIA TABELA ITENS SOMENTE PARA (COMPONENTS)
	***********************************/
	IF EXISTS( SELECT TABLE_NAME FROM SYS.TABLES WHERE SCHEMA_NAME = 'OW_LAO' AND TABLE_NAME = 'TMP_ORDER_ITEM_TO_COMPONENTS_PO_VTEX_PROMOTION' ) THEN
		DROP TABLE OW_LAO.TMP_ORDER_ITEM_TO_COMPONENTS_PO_VTEX_PROMOTION;
	END IF;
	CREATE COLUMN TABLE OW_LAO.TMP_ORDER_ITEM_TO_COMPONENTS_PO_VTEX_PROMOTION AS (
		SELECT *
			, ROW_NUMBER() OVER (PARTITION BY ORDER_ID, SKU_ID ORDER BY ORDER_ID, SKU_ID) AS ITEM_INDEX_COMPONENT
			, 1 AS ITEM_INDEX_COMPONENT_COUNT -- DEFAULT 1
		FROM U_PRJ_ECOM.RAW_VTEX_SSG_BR_SHOP_SALES_ORDER_ITEM
		WHERE ORDER_ID IN ( SELECT DISTINCT ORDER_ID FROM OW_LAO.TMP_ITEM_COMPONENTS_PO_VTEX_PROMOTION )
	);
	
	UPDATE OW_LAO.TMP_ORDER_ITEM_TO_COMPONENTS_PO_VTEX_PROMOTION SET 
		ITEM_INDEX_COMPONENT_COUNT = 0 -- IF ORDER HAS MORE THEN 1 SAME ITEM 
	WHERE ORDER_ID IN (
			SELECT ORDER_ID	
			FROM OW_LAO.TMP_ORDER_ITEM_TO_COMPONENTS_PO_VTEX_PROMOTION
			GROUP BY ORDER_ID
			HAVING MAX(ITEM_INDEX_COMPONENT) > 1
		);
	 /*********************************************************
	 * CRIA TMP_SSG_BR_SHOP_SALES_ORDER_SHIPPING_VTEX_PROMOTION   
	 * *******************************************************/	 
	IF EXISTS( SELECT TABLE_NAME FROM SYS.TABLES WHERE SCHEMA_NAME = 'OW_LAO' AND TABLE_NAME = 'TMP_SSG_BR_SHOP_SALES_ORDER_SHIPPING_VTEX_PROMOTION' ) THEN
		DROP TABLE OW_LAO.TMP_SSG_BR_SHOP_SALES_ORDER_SHIPPING_VTEX_PROMOTION;
	END IF ;
	CREATE COLUMN TABLE OW_LAO.TMP_SSG_BR_SHOP_SALES_ORDER_SHIPPING_VTEX_PROMOTION AS (
		-- PEGA O SELECTED_SLA
		SELECT CP.ORDER_ID
			 , CP.ITEM_INDEX
			 , MAX(JSON_VALUE('[' || CP.PICKUP_STORE_INFO || ']', '$.address.addressType')) AS ADDRESSTYPE
			 , MAX(JSON_VALUE('[' || CP.PICKUP_STORE_INFO || ']', '$.friendlyName')) AS FRIENDLYNAME
			 , MAX(CP.STATE) AS STATE
			 , MAX(CP.CITY) AS CITY
			 , MAX(CP.SELECTED_SLA) AS SELECTED_SLA
			 , STRING_AGG(CP.WAREHOUSE_ID, ' | ') AS WAREHOUSE_ID_GROUP
			 , MAX(CP.SELLING_PRICE) AS SHIPPING_PRICE
		FROM U_PRJ_ECOM.RAW_VTEX_SSG_BR_SHOP_SALES_ORDER_SHIPPING CP
			INNER JOIN OW_LAO.TMP_PO_ORDER_ID_PO_VTEX_PROMOTION TP ON CP.ORDER_ID = TP.ORDER_ID
		GROUP BY CP.ORDER_ID
			   , CP.ITEM_INDEX
	);
	/*********************************************************
	* CRIA TMP_PO_VTEX_PROMOTION    
	* *******************************************************/
	IF EXISTS ( SELECT TABLE_NAME FROM SYS.TABLES WHERE SCHEMA_NAME = 'OW_LAO' AND TABLE_NAME = 'TMP_PO_VTEX_PROMOTION' ) THEN
		DROP TABLE OW_LAO.TMP_PO_VTEX_PROMOTION;
	END IF ;
	CREATE COLUMN TABLE OW_LAO.TMP_PO_VTEX_PROMOTION AS (
		SELECT
			  TO_DATE(BSO.CREATION_TIMESTAMP) AS DATE_REF
			, BSO.CREATION_TIMESTAMP AS PO_CREATION_DATE
			, BSO.AFFILIATE_ID
			, BSO.ORDER_ID
			, BSO.MARKETPLACE_ORDER_ID
			, BSO.HOSTNAME AS ENVIRONMENT
			, BSO.STATUS AS STATUS_PO 
			, CASE
				 -- CD_STORE_INFORMATION
				 WHEN ( CASE WHEN BSO.CD_STORE_INFORMATION IS NOT NULL THEN BSO.CD_STORE_INFORMATION ELSE SSO.CD_STORE_INFORMATION END ) IS NOT NULL
				 -- CD_STORE_INFORMATION
				 THEN ( CASE WHEN BSO.CD_STORE_INFORMATION IS NOT NULL THEN BSO.CD_STORE_INFORMATION ELSE SSO.CD_STORE_INFORMATION END )
				 -- UTM_SOURCE
				 ELSE ( CASE WHEN BSO.UTM_SOURCE IS NOT NULL THEN BSO.UTM_SOURCE ELSE SSO.UTM_SOURCE END )
			  END AS STORE_ID
			, BSO.SALES_CHANNEL
			, CASE 
				WHEN BSO.CD_VENDEDOR IS NOT NULL THEN BSO.CD_VENDEDOR
				WHEN SSO.CD_VENDEDOR IS NOT NULL THEN SSO.CD_VENDEDOR
			  END AS STORE_EMPLOYEE_CPF
			, LI.CUSTOMER_PO
			, BSI.ITEM_INDEX
			, '' AS REFERENCE_CODE_KIT -- NULO PARA ITEM POIS NÃO É KIT
			, BSI.REF_ID AS REFERENCE_CODE -- não é kit (item)
			, BSI.NAME AS ITEM_NAME
			  
			, COALESCE( B2I.SKU_ID , EPI.SKU_ID ,SSI.SKU_ID ,BSI.SKU_ID) AS SKU_ID -- não é kit (item)
			, NULL AS SKU_ID_COMPONENT -- NULO POIS NÃO É KIT
			
			--, IFNULL(IFNULL(EPO.COUPON,SSO.COUPON),BSO.COUPON) AS COUPON
			, COALESCE( B2O.COUPON, EPO.COUPON, SSO.COUPON, BSO.COUPON) AS COUPON
			  
			, CASE -- NETE PROCESSO ESPECIFICO  RETORNA PRIMEIRO BR SHOP E AS INSTANCIAS CASO BR SHOP FIQUE NULO 
				  WHEN IFNULL(BSI.PRICE_TAGS,'') NOT IN ('','[]') THEN BSI.PRICE_TAGS
				  WHEN IFNULL(B2I.PRICE_TAGS,'') NOT IN ('','[]') THEN B2I.PRICE_TAGS
				  WHEN IFNULL(EPI.PRICE_TAGS,'') NOT IN ('','[]') THEN EPI.PRICE_TAGS
				  WHEN IFNULL(SSI.PRICE_TAGS,'') NOT IN ('','[]') THEN SSI.PRICE_TAGS
			  END
			  AS PRICE_TAGS
			  			 
			, CASE -- NETE PROCESSO ESPECIFICO  RETORNA PRIMEIRO BR SHOP E AS INSTANCIAS CASO BR SHOP FIQUE NULO
				  WHEN IFNULL(BSI.PRICE_TAGS,'') NOT IN ('','[]') THEN 'BRSHOP'
				  WHEN IFNULL(B2I.PRICE_TAGS,'') NOT IN ('','[]') THEN 'B2B'
				  WHEN IFNULL(EPI.PRICE_TAGS,'') NOT IN ('','[]') THEN 'EPP2'
				  WHEN IFNULL(SSI.PRICE_TAGS,'') NOT IN ('','[]') THEN 'SSGBR'
			  END
			  AS PRICE_TAGS_ORIGIN
			  
			, EPI.PRICE_TAGS AS PRICE_TAGS_EPP
			, SSI.PRICE_TAGS AS PRICE_TAGS_SSGBR
			, B2I.PRICE_TAGS AS PRICE_TAGS_B2B
			, ROW_NUMBER () OVER ( ORDER BY BSI.REF_ID ) AS REF_ID_COUNT -- Não é KIT
			
			, CAST((
					( BSI.SELLING_PRICE * BSI.QUANTITY) 
					  + IFNULL(SP.SHIPPING_PRICE,0) -- FRETE SOMA O FRETE
			  ) / 100
			  AS DECIMAL(18,4)) AS SELLING_AMOUNT_LOCAL
			  
			, NULL AS ITEM_INDEX_KIT	
			
		FROM OW_LAO.TMP_PO_ORDER_ID_PO_VTEX_PROMOTION LI -- (LISTA DE ALTERAÇÕES E INSERÇÕES)
		
			/********** BR SHOP  ***********/
			INNER JOIN U_PRJ_ECOM.RAW_VTEX_SSG_BR_SHOP_SALES_ORDER BSO -- (BR SHOP - ORDER )
				ON BSO.ORDER_ID = LI.ORDER_ID
			INNER JOIN U_PRJ_ECOM.RAW_VTEX_SSG_BR_SHOP_SALES_ORDER_ITEM BSI -- (BR SHOP - ITEM)
				ON BSO.ORDER_ID = BSI.ORDER_ID
			LEFT JOIN OW_LAO.TMP_ITEM_COMPONENTS_PO_VTEX_PROMOTION BSC -- (BR SHOP - COMPONENTES) [NÃO DEVE TER COMPONENTS POR ISSO LEFT]
				ON BSI.ORDER_ID = BSC.ORDER_ID
				AND BSI.SKU_ID = BSC.SKU_ID
			
			LEFT JOIN OW_LAO.TMP_SSG_BR_SHOP_SALES_ORDER_SHIPPING_VTEX_PROMOTION SP -- SHIPPING
				ON BSI.ORDER_ID = SP.ORDER_ID 
				   AND BSI.ITEM_INDEX = SP.ITEM_INDEX				
			
			/********** SSG BR  ***********/
			LEFT JOIN U_PRJ_ECOM.RAW_VTEX_SSG_BR_SALES_ORDER SSO -- (SSG BR - ORDER )
				ON BSO.MARKETPLACE_ORDER_ID = SSO.ORDER_ID
			LEFT JOIN U_PRJ_ECOM.RAW_VTEX_SSG_BR_SALES_ORDER_ITEM SSI -- (BR SHOP - ITEM)
				ON BSO.MARKETPLACE_ORDER_ID = SSI.ORDER_ID
				   AND BSI.REF_ID = CASE WHEN RIGHT(SSI.REF_ID,5) LIKE '_OUT%' THEN SUBSTRING(SSI.REF_ID, 1, LENGTH(SSI.REF_ID) - 5) ELSE SSI.REF_ID END
				   AND BSI.ITEM_INDEX = SSI.ITEM_INDEX
				   
			/********** EPP2  ***********/
			LEFT JOIN U_PRJ_ECOM.RAW_VTEX_SSG_BR_EPP2_SALES_ORDER EPO --(EPP2 - ORDER)
				ON BSO.MARKETPLACE_ORDER_ID = EPO.ORDER_ID
			LEFT JOIN U_PRJ_ECOM.RAW_VTEX_SSG_BR_EPP2_SALES_ORDER_ITEM EPI -- (BR SHOP - ITEM)
				ON BSO.MARKETPLACE_ORDER_ID = EPI.ORDER_ID
				   AND BSI.REF_ID = CASE WHEN RIGHT(EPI.REF_ID,5) LIKE '_OUT%' THEN SUBSTRING(EPI.REF_ID, 1, LENGTH(EPI.REF_ID) - 5) ELSE EPI.REF_ID END
				   AND BSI.ITEM_INDEX = EPI.ITEM_INDEX
			
			/********** B2B ***********/
			LEFT JOIN U_PRJ_ECOM.RAW_VTEX_SSG_BR_B2B_SALES_ORDER B2O --(EPP2 - ORDER)
				ON BSO.MARKETPLACE_ORDER_ID = B2O.ORDER_ID
			LEFT JOIN U_PRJ_ECOM.RAW_VTEX_SSG_BR_B2B_SALES_ORDER_ITEM B2I -- (BR SHOP - ITEM)
				ON BSO.MARKETPLACE_ORDER_ID = B2I.ORDER_ID
				   AND BSI.REF_ID = CASE WHEN RIGHT(B2I.REF_ID,5) LIKE '_OUT%' THEN SUBSTRING(B2I.REF_ID, 1, LENGTH(B2I.REF_ID) - 5) ELSE B2I.REF_ID END
				   AND BSI.ITEM_INDEX = B2I.ITEM_INDEX
		WHERE BSC.REF_ID IS NULL -- NÃO DEVE TER COMPONENTS
			AND BSI.QUANTITY IS NOT NULL
			AND BSI.PRICE IS NOT NULL
	
		/*****************************************************************
		 *  PO (VTEX-[SOMENTE COMPONENTES] {CREATION_TIMESTAMP}) 
		******************************************************************/
		UNION ALL
		SELECT 
			  TO_DATE(BSO.CREATION_TIMESTAMP) AS DATE_REF
			, BSO.CREATION_TIMESTAMP AS PO_CREATION_DATE
			, BSO.AFFILIATE_ID
			, BSO.ORDER_ID
			, BSO.MARKETPLACE_ORDER_ID
			, BSO.HOSTNAME AS ENVIRONMENT
			, BSO.STATUS AS STATUS_PO
			, CASE
				 -- CD_STORE_INFORMATION
				 WHEN ( CASE WHEN BSO.CD_STORE_INFORMATION IS NOT NULL THEN BSO.CD_STORE_INFORMATION ELSE SSO.CD_STORE_INFORMATION END ) IS NOT NULL
				 -- CD_STORE_INFORMATION
				 THEN ( CASE WHEN BSO.CD_STORE_INFORMATION IS NOT NULL THEN BSO.CD_STORE_INFORMATION ELSE SSO.CD_STORE_INFORMATION END )
				 -- UTM_SOURCE
				 ELSE ( CASE WHEN BSO.UTM_SOURCE IS NOT NULL THEN BSO.UTM_SOURCE ELSE SSO.UTM_SOURCE END )
			  END AS STORE_ID
			, BSO.SALES_CHANNEL
			
			, CASE 	
				WHEN BSO.CD_VENDEDOR IS NOT NULL THEN BSO.CD_VENDEDOR
				WHEN SSO.CD_VENDEDOR IS NOT NULL THEN SSO.CD_VENDEDOR
			  END AS STORE_EMPLOYEE_CPF
			  
			, LI.CUSTOMER_PO
			, BSI.ITEM_INDEX
			, BSI.REF_ID AS REFERENCE_CODE_KIT
			, BSC.REF_ID AS REFERENCE_CODE -- é kit (components)
			, BSC.NAME AS ITEM_NAME
			
			, COALESCE( B2I.SKU_ID, EPI.SKU_ID, SSI.SKU_ID, BSI.SKU_ID ) AS SKU_ID 
			, BSC.SKU_ID_COMPONENT AS SKU_ID_COMPONENT
			, COALESCE(B2O.COUPON, EPO.COUPON, SSO.COUPON, BSO.COUPON) AS COUPON
			
			--, IFNULL(IFNULL(EPI.PRICE_TAGS, SSI.PRICE_TAGS), BSI.PRICE_TAGS) AS PRICE_TAGS			
			, CASE -- NETE PROCESSO ESPECIFICO  RETORNA PRIMEIRO BR SHOP E AS INSTANCIAS CASO BR SHOP FIQUE NULO 
				  WHEN IFNULL(BSI.PRICE_TAGS,'') NOT IN ('','[]') THEN BSI.PRICE_TAGS
				  WHEN IFNULL(B2I.PRICE_TAGS,'') NOT IN ('','[]') THEN B2I.PRICE_TAGS 
				  WHEN IFNULL(EPI.PRICE_TAGS,'') NOT IN ('','[]') THEN EPI.PRICE_TAGS
				  WHEN IFNULL(SSI.PRICE_TAGS,'') NOT IN ('','[]') THEN SSI.PRICE_TAGS
			  END			
			  AS PRICE_TAGS
			 
			, CASE -- NETE PROCESSO ESPECIFICO  RETORNA PRIMEIRO BR SHOP E AS INSTANCIAS CASO BR SHOP FIQUE NULO				
				  WHEN IFNULL(BSI.PRICE_TAGS,'') NOT IN ('','[]') THEN 'BRSHOP'
				  WHEN IFNULL(B2I.PRICE_TAGS,'') NOT IN ('','[]') THEN 'B2B'
				  WHEN IFNULL(EPI.PRICE_TAGS,'') NOT IN ('','[]') THEN 'EPP2'
				  WHEN IFNULL(SSI.PRICE_TAGS,'') NOT IN ('','[]') THEN 'SSGBR'
			  END
			  AS PRICE_TAGS_ORIGIN
			 
			, EPI.PRICE_TAGS AS PRICE_TAGS_EPP
			, SSI.PRICE_TAGS AS PRICE_TAGS_SSGBR
			, B2I.PRICE_TAGS AS PRICE_TAGS_B2B
			, ROW_NUMBER () OVER ( ORDER BY BSC.REF_ID ) AS REF_ID_COUNT -- é KIT
			
			/****************************

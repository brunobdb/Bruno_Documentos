	UPDATE NS SET
         TAX_SKU = TS.TAX_SKU --, TC.TAX_SEDA_CATEGORY_ESTORE ) 
       , TAX_INCENTIVE_SKU = TS.TAX_INCENTIVE_SKU --, TC.TAX_INCENTIVE_SEDA_CATEGORY_ESTORE)
       , COGS_UNIT = CG.COGS_UNIT
       , COGS_TTL = (CG.COGS_UNIT * NS.QTY) -- AS COGS_TTL
       , NET_SALES = (NS.SELLING_AMOUNT_LOCAL * COALESCE ( TS.TAX_SKU, TC.TAX_SEDA_CATEGORY_ESTORE )) + (NS.SELLING_AMOUNT_LOCAL * COALESCE ( TS.TAX_INCENTIVE_SKU, TC.TAX_INCENTIVE_SEDA_CATEGORY_ESTORE)) -- AS NET_SALES
       , GROSS_PROFIT =  (NS.SELLING_AMOUNT_LOCAL * COALESCE ( TS.TAX_SKU, TC.TAX_SEDA_CATEGORY_ESTORE ) ) +  (NS.SELLING_AMOUNT_LOCAL * COALESCE ( TS.TAX_INCENTIVE_SKU, TC.TAX_INCENTIVE_SEDA_CATEGORY_ESTORE)) - (CG.COGS_UNIT * NS.QTY) -- AS GROSS_PROFIT_SKU

		--		   'PB', 'PE', 'PI', 'PR', 'RJ', 'RN', 'RO', 'RR', 'RS', 'SC', 'SE', 'SP', 'TO')
		 -- AND NS.DATE_REF BETWEEN ADD_DAYS(NOW (), -30) AND NOW()

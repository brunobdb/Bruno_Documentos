			     AND BILLING_DATE BETWEEN ADD_DAYS(NOW (), -60) AND NOW()
			     AND AFFILIATE_SUB_CHANNEL <> 'Outlet'
			     AND SALES_DOCUMENT_TYPE = 'YS10'
			     AND AMOUNT_ZKE >= 0
			     AND TAX_INCENTIVE_ZKE >= 0
		     GROUP BY SKU, REGION
		) TS ON IFNULL(MSK.SKU_MAN, NS.REFERENCE_CODE) = TS.SKU --NS.REFERENCE_CODE = TS.SKU
			AND TRIM(UPPER(NS.STATE)) = TRIM(UPPER(TS.REGION))
			
		/****************
		LEFT JOIN (
			SELECT -- CATEGORIA MAIS RECENTE NO BILLING_DATE_MIN
				  SK.SEDA_CATEGORY_ESTORE
				, SK.REGION
				, SK.TAX_SEDA_CATEGORY_ESTORE
				, SK.TAX_INCENTIVE_SEDA_CATEGORY_ESTORE
			FROM OW_LAO.DIM_TAX_GROSS_MARGIN_BY_CATEGORY SK
				INNER JOIN (
					SELECT SEDA_CATEGORY_ESTORE
						, REGION
						, MAX(BILLING_DATE_MIN) AS BILLING_DATE_MIN
					FROM OW_LAO.DIM_TAX_GROSS_MARGIN_BY_CATEGORY
					WHERE BILLING_DATE_MIN <= ADD_DAYS(CURRENT_TIMESTAMP, -60)--( SELECT DATE_FIM FROM OW_LAO.TMP_PARAMETER_PO_VTEX_TMP )
					GROUP BY SEDA_CATEGORY_ESTORE
						, REGION
				) DT ON SK.SEDA_CATEGORY_ESTORE  = DT.SEDA_CATEGORY_ESTORE
						AND UPPER(SK.REGION) = UPPER(DT.REGION)
						AND SK.BILLING_DATE_MIN  = DT.BILLING_DATE_MIN
		) TC ON TRIM(UPPER(NS.SEDA_CATEGORY_ESTORE)) = TRIM(UPPER(TC.SEDA_CATEGORY_ESTORE))
			AND TRIM(UPPER(NS.STATE)) = TRIM(UPPER(TC.REGION))
		****************/	
			
		--/****************
		LEFT JOIN (
			     SELECT SEDA_CATEGORY_ESTORE
			            , REGION
			            , SUM (AMOUNT_ZKE) / SUM (NF_TOTAL_AMT) AS TAX_SEDA_CATEGORY_ESTORE
			            , SUM (TAX_INCENTIVE_ZKE) / SUM (NF_TOTAL_AMT) AS TAX_INCENTIVE_SEDA_CATEGORY_ESTORE

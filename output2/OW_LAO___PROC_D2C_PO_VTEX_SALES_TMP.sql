CALL OW_LAO.PROC_D2C_PO_VTEX_SALES_TMP ( ADD_DAYS(CURRENT_TIMESTAMP, -32),  ADD_DAYS(CURRENT_TIMESTAMP, 2))
***********************************************************************************************/
CREATE PROCEDURE OW_LAO.PROC_D2C_PO_VTEX_SALES_TMP (
	  p_DATE_INI DATE DEFAULT NULL 
	, P_DATE_FIM DATE DEFAULT NULL 
) LANGUAGE SQLSCRIPT
AS
BEGIN
	
	/*********************************************************
	* CRIA A TMP_PARAMETER_PO_VTEX
	********************************************************/
	IF EXISTS ( SELECT '' FROM SYS.TABLES WHERE SCHEMA_NAME = 'OW_LAO' AND TABLE_NAME = 'TMP_PARAMETER_PO_VTEX' ) THEN
		DROP TABLE OW_LAO.TMP_PARAMETER_PO_VTEX_TMP;
	END IF ;
	CREATE COLUMN TABLE OW_LAO.TMP_PARAMETER_PO_VTEX_TMP AS (
		SELECT ADD_DAYS(CURRENT_TIMESTAMP, -30) AS DATE_INI, ADD_DAYS(CURRENT_TIMESTAMP, 2) AS DATE_FIM FROM DUMMY
	);
	UPDATE OW_LAO.TMP_PARAMETER_PO_VTEX_TMP SET
		  DATE_INI = IFNULL( p_DATE_INI, ADD_DAYS(CURRENT_TIMESTAMP, -7) ) -- 30 dias dafault
		, DATE_FIM = IFNULL( P_DATE_FIM, ADD_DAYS(CURRENT_TIMESTAMP, 2) ) 
	;
	
	/*************************************************************
 	CRIA TMP_PO_ORDER_ID_PO_VTEX PARA CAPTURAR O CUSTOMER PO NA ORDER ID
 	TAMBÉM VERIFICA SE JÁ EXISTE NA TF_D2C_NERP_SALES
	*************************************************************/
	IF EXISTS( SELECT '' FROM SYS.TABLES WHERE SCHEMA_NAME = 'OW_LAO' AND TABLE_NAME = 'TMP_PO_ORDER_ID_PO_VTEX') THEN
		DROP TABLE OW_LAO.TMP_PO_ORDER_ID_PO_VTEX_TMP;
	END IF;
	CREATE COLUMN TABLE OW_LAO.TMP_PO_ORDER_ID_PO_VTEX_TMP AS(
		SELECT 
			   V.ORDER_ID
			 , V.MARKETPLACE_ORDER_ID
			 , MAX( CREATION_TIMESTAMP ) AS CREATION_TIMESTAMP
			 , MAX( CASE WHEN S.CUSTOMER_PO IS NOT NULL THEN S.CUSTOMER_PO
				   		ELSE CAST("SEQUENCE" AS VARCHAR(100)) END
			   ) AS CUSTOMER_PO
			--, 1 AS IS_NEW
		    --, 1 AS IS_UPDATE  
		FROM U_PRJ_ECOM.RAW_VTEX_SSG_BR_SHOP_SALES_ORDER V
			 LEFT JOIN OW_LAO.ODS_NERP_ZRSDD6A120_SALES_ORDER_TRACKING S ON V.ORDER_ID = S.CUSTOMER_PO
		WHERE 1=1
			AND V.CREATION_TIMESTAMP BETWEEN ( SELECT DATE_INI FROM OW_LAO.TMP_PARAMETER_PO_VTEX_TMP ) 
				 						      AND ( SELECT DATE_FIM FROM OW_LAO.TMP_PARAMETER_PO_VTEX_TMP )
			AND V.ORDER_ID IN ( 						      
					SELECT DISTINCT ORDER_ID
					FROM  OW_LAO.TF_D2C_NERP_SALES
					WHERE 1 = 1
					      AND SUBSIDIARY = 'SEDA'
					      AND SOURCE = 'PO'
					      --ND REFERENCE_CODE IN ('F-AR12DYFAAWK', 'F-AR18DXFAAWK')
					      AND SEDA_DIVISION_ESTORE IS NULL				      
			) 						      
			/******************************	 						      
			AND V.MARKETPLACE_ORDER_ID IN(
							SELECT DISTINCT ORDER_ID
							FROM U_PRJ_ECOM.RAW_VTEX_SSG_BR_B2B_SALES_ORDER
							WHERE EMAIL_DOMAIN IS NOT NULL
			)
			AND  V.ORDER_ID IN(
				SELECT DISTINCT ORDER_ID
				FROM OW_LAO.TF_D2C_NERP_SALES
				WHERE SOURCE = 'PO'
					AND EMAIL_DOMAIN IS NULL
			)
			 **************************/			
		GROUP BY
			   V.ORDER_ID
			 , V.MARKETPLACE_ORDER_ID
	);
	/***********************************
	-- CRIA TABELA TMP_ITEM_COMPONENTS_PO_VTEX DO DISCO
	***********************************/
	IF EXISTS( SELECT TABLE_NAME FROM SYS.TABLES WHERE SCHEMA_NAME = 'OW_LAO' AND TABLE_NAME = 'TMP_ITEM_COMPONENTS_PO_VTEX') THEN
		DROP TABLE OW_LAO.TMP_ITEM_COMPONENTS_PO_VTEX_TMP;
	END IF;
	CREATE COLUMN TABLE OW_LAO.TMP_ITEM_COMPONENTS_PO_VTEX_TMP AS(
		SELECT --DISTINCT
			  CP.ORDER_ID
			, CP.SKU_ID
			, CP.SKU_ID_COMPONENT
			, CP.REF_ID
			, CP.NAME
			, CP.QUANTITY
			, CP.PRICE
			, CP.COST_PRICE
			, CP.SELLING_PRICE
			, ( CP.SELLING_PRICE * CP.QUANTITY ) AS SELLING_PRICE_AMOUNT
			, CAST( 0 AS DECIMAL(18,4) ) AS SELLING_PRICE_TOTAL
			, 1 AS ITEM_INDEX_COMPONENT
			, ROW_NUMBER() OVER (PARTITION BY CP.ORDER_ID, CP.SKU_ID ORDER BY CP.ORDER_ID, CP.SKU_ID, CP.SKU_ID_COMPONENT, CP.QUANTITY, ( CP.SELLING_PRICE * CP.QUANTITY )) AS ITEM_INDEX_KIT
		FROM U_PRJ_ECOM.RAW_VTEX_SSG_BR_SHOP_SALES_ORDER_ITEM_COMPONENTS CP
			 INNER JOIN OW_LAO.TMP_PO_ORDER_ID_PO_VTEX_TMP TP ON CP.ORDER_ID = TP.ORDER_ID
		WHERE (CP.REF_ID IS NOT NULL)
	);
	
	-- ATUALIZA ITEM_INDEX_COMPONENT (PARA CASOS DE SKU_ID DUPLICADOS NOS KITS)
	UPDATE CP SET 
		  ITEM_INDEX_COMPONENT = CT.ITEM_INDEX_COMPONENT 
	FROM OW_LAO.TMP_ITEM_COMPONENTS_PO_VTEX_TMP CP
		INNER JOIN (
			SELECT ORDER_ID
			    , SKU_ID
			    , SKU_ID_COMPONENT
			    , ROW_NUMBER() OVER (PARTITION BY ORDER_ID, SKU_ID ORDER BY ORDER_ID, SKU_ID) AS ITEM_INDEX_COMPONENT
			FROM (
			     SELECT DISTINCT ORDER_ID, SKU_ID, SKU_ID_COMPONENT
			     FROM OW_LAO.TMP_ITEM_COMPONENTS_PO_VTEX_TMP
			)
		) CT ON  CP.ORDER_ID = CT.ORDER_ID
			    AND CP.SKU_ID = CT.SKU_ID
			    AND CP.SKU_ID_COMPONENT = CT.SKU_ID_COMPONENT
	;
	
	/*******************************
	-- ATUALIZA SELLING_PRICE_TOTAL PARA RATEIO
	*******************************/
	UPDATE TP SET TP.SELLING_PRICE_TOTAL = TT.SELLING_PRICE_TOTAL
	FROM OW_LAO.TMP_ITEM_COMPONENTS_PO_VTEX_TMP TP
		INNER JOIN (
				SELECT ORDER_ID
					 , SKU_ID
					 , SUM(SELLING_PRICE_AMOUNT) AS SELLING_PRICE_TOTAL 
				FROM OW_LAO.TMP_ITEM_COMPONENTS_PO_VTEX_TMP
				GROUP BY
					  ORDER_ID
					, SKU_ID				
		) TT ON TP.ORDER_ID = TT.ORDER_ID
				AND TP.SKU_ID = TT.SKU_ID
	;
	
	/***********************************
	-- CRIA TABELA ITENS SOMENTE PARA (COMPONENTS)
	***********************************/
	IF EXISTS( SELECT TABLE_NAME FROM SYS.TABLES WHERE SCHEMA_NAME = 'OW_LAO' AND TABLE_NAME = 'TMP_ORDER_ITEM_TO_COMPONENTS_PO_VTEX' ) THEN
		DROP TABLE OW_LAO.TMP_ORDER_ITEM_TO_COMPONENTS_PO_VTEX_TMP;
	END IF;
	CREATE COLUMN TABLE OW_LAO.TMP_ORDER_ITEM_TO_COMPONENTS_PO_VTEX_TMP AS (
		SELECT *
			, ROW_NUMBER() OVER (PARTITION BY ORDER_ID, SKU_ID ORDER BY ORDER_ID, SKU_ID) AS ITEM_INDEX_COMPONENT
			, 1 AS ITEM_INDEX_COMPONENT_COUNT -- DEFAULT 1
		FROM U_PRJ_ECOM.RAW_VTEX_SSG_BR_SHOP_SALES_ORDER_ITEM
		WHERE ORDER_ID IN ( SELECT DISTINCT ORDER_ID FROM OW_LAO.TMP_ITEM_COMPONENTS_PO_VTEX_TMP )
	);
	
	UPDATE OW_LAO.TMP_ORDER_ITEM_TO_COMPONENTS_PO_VTEX_TMP SET 
		ITEM_INDEX_COMPONENT_COUNT = 0 -- IF ORDER HAS MORE THEN 1 SAME ITEM 
	WHERE ORDER_ID IN (
			SELECT ORDER_ID	
			FROM OW_LAO.TMP_ORDER_ITEM_TO_COMPONENTS_PO_VTEX_TMP
			GROUP BY ORDER_ID
			HAVING MAX(ITEM_INDEX_COMPONENT) > 1
		);
	
	/***********************************
	-- CRIA TABELA SHIPPING_TMP
	***********************************/
	IF EXISTS( SELECT TABLE_NAME FROM SYS.TABLES WHERE SCHEMA_NAME = 'OW_LAO' AND TABLE_NAME = 'TMP_SHIPPING_VTEX') THEN
		DROP TABLE OW_LAO.TMP_SHIPPING_VTEX_TMP;
	END IF;
	CREATE TABLE OW_LAO.TMP_SHIPPING_VTEX_TMP AS ( -- PEGA O SELECTED_SLA
		SELECT CP.ORDER_ID
			 , CP.ITEM_INDEX
			 , MAX(JSON_VALUE('[' || CP.PICKUP_STORE_INFO || ']', '$.address.addressType')) AS ADDRESSTYPE
			 , MAX(JSON_VALUE('[' || CP.PICKUP_STORE_INFO || ']', '$.friendlyName')) AS FRIENDLYNAME
			 , MAX(CP.STATE) AS STATE
			 , MAX(CP.CITY) AS CITY
			 , MAX(CP.SELECTED_SLA) AS SELECTED_SLA
			 , STRING_AGG(CP.WAREHOUSE_ID, ' | ') AS WAREHOUSE_ID_GROUP
			 , MAX(CP.SELLING_PRICE) AS SHIPPING_PRICE
		FROM U_PRJ_ECOM.RAW_VTEX_SSG_BR_SHOP_SALES_ORDER_SHIPPING CP
			INNER JOIN OW_LAO.TMP_PO_ORDER_ID_PO_VTEX_TMP TP ON CP.ORDER_ID = TP.ORDER_ID
		GROUP BY CP.ORDER_ID
			   , CP.ITEM_INDEX
	);
	/**************************************
	-- PROMOTION
	**************************************/
	IF EXISTS( SELECT TABLE_NAME FROM SYS.TABLES WHERE SCHEMA_NAME = 'OW_LAO' AND TABLE_NAME = 'TMP_PROMOTION_VTEX_NERP_SALES') THEN
		DROP TABLE OW_LAO.TMP_PROMOTION_VTEX_NERP_SALES_TMP;
	END IF;
	CREATE TABLE OW_LAO.TMP_PROMOTION_VTEX_NERP_SALES_TMP AS ( -- PEGA O SELECTED_SLA		
		SELECT 
			  ORDER_ID
			, ITEM_INDEX
			, ITEM_INDEX_KIT --, REFERENCE_CODE_KIT,	REFERENCE_CODE, ITEM_NAME
			, STRING_AGG(
				CASE WHEN LOWER(PRC_TAG_NAME) LIKE '%giftcard_ssg_rewards%' THEN '-'  ELSE ID_CALCULATOR_CONFIGURATION END
				, CHAR(13) || CHAR(10)  || ','
			) AS PROMOS_IDS
			, STRING_AGG(
				CASE WHEN LOWER(PRC_TAG_NAME) LIKE '%giftcard_ssg_rewards%' THEN PRC_TAG_NAME  ELSE PROM_NAME END
				, CHAR(13) || CHAR(10)  || ',' 
			) AS PROMOS_NAME
			, STRING_AGG(
				  ROUND((AMOUNT_DISCOUNT * -1), 2)
				, CHAR(13) || CHAR(10)  || ',' 
			) AS PROMOS_DISCOUNTS    
		FROM (
			SELECT
				  ORDER_ID
				, ITEM_INDEX
				, ITEM_INDEX_KIT --, REFERENCE_CODE_KIT,	REFERENCE_CODE, ITEM_NAME
				, ID_CALCULATOR_CONFIGURATION
				, PROM_NAME
				, PRC_TAG_NAME
				, AMOUNT_DISCOUNT
			FROM OW_LAO.FT_D2C_VTEX_PROMOTION
			WHERE 1=1 -- AND REFERENCE_CODE = 'EF-PS931CMEGWW'
				  AND ( ORDER_ID IN ( SELECT ORDER_ID FROM OW_LAO.TMP_PO_ORDER_ID_PO_VTEX_TMP)
						OR ORDER_ID IN ( SELECT MARKETPLACE_ORDER_ID FROM OW_LAO.TMP_PO_ORDER_ID_PO_VTEX_TMP)
				  )
			GROUP BY
				  ORDER_ID
				, ITEM_INDEX
				, ITEM_INDEX_KIT --, REFERENCE_CODE_KIT,	REFERENCE_CODE, ITEM_NAME
				, ID_CALCULATOR_CONFIGURATION
				, PROM_NAME
				, PRC_TAG_NAME
				, AMOUNT_DISCOUNT
			ORDER BY 
				  ORDER_ID
				, ITEM_INDEX
				, ITEM_INDEX_KIT --, REFERENCE_CODE_KIT,	REFERENCE_CODE, ITEM_NAME
				, AMOUNT_DISCOUNT
				/*Adicionado dia 01/05/2025*/
				, PRC_TAG_NAME
				, ID_CALCULATOR_CONFIGURATION
				, PROM_NAME
		)
		GROUP BY
			  ORDER_ID
			, ITEM_INDEX
			, ITEM_INDEX_KIT --, REFERENCE_CODE_KIT,	REFERENCE_CODE, ITEM_NAME
		/*Adicionado dia 01/05/2025*/
		ORDER BY ORDER_ID
			, ITEM_INDEX
			, ITEM_INDEX_KIT
	);
	/***********************************
	-- APAGA DADOS ANTERIORES DE PO
	***********************************/
	DELETE FROM OW_LAO.TF_D2C_NERP_SALES
	WHERE SOURCE = 'PO' 
	AND SUBSIDIARY = 'SEDA'
		  AND ORDER_ID IN(
				SELECT ORDER_ID
				FROM OW_LAO.TMP_PO_ORDER_ID_PO_VTEX_TMP
				--WHERE IS_UPDATE = 1 -- ATUALIZAÇÃO
		  )
	;
	
	/***********************************	
	-- ATUALIZA MOEDA DE PO ULTIMO DIA
	***********************************/	
	UPDATE NS SET AMOUNT_USD = CAST( NS.AMOUNT_LOCAL / EX.EXCHANGE_RATE AS DECIMAL(18,2) )
	FROM OW_LAO.TF_D2C_NERP_SALES NS
		 INNER JOIN OW_LAO.VIEW_PTAX_EXCHANGE_RATE EX ON EX.VALID_FROM = NS.DATE_REF
													 AND EX.TO_CURRENCY = NS.CURRENCY --'BRL'
													 AND EX.FROM_CURRENCY = 'USD'
	WHERE "SOURCE" = 'PO' AND SUBSIDIARY = 'SEDA'
		  AND NS.DATE_REF >=  ADD_DAYS(CURRENT_DATE,-1) -- ULTIMO DIA
	;
	
	/***********************************
	-- INSERE NOVOS DADOS DE PO (VTEX)
	***********************************/		
	INSERT INTO OW_LAO.TF_D2C_NERP_SALES (
		  "SOURCE"
		, DATE_REF
		, YYYYWW
		, YYYYMM
		, YYYYQQ
		, PO_CREATION_DATE
		, "PO_WEEK_DAY_NUM"
		, "PO_WEEK_DAY_NAME"
		, "PO_HOUR"
		, SALES_CHANNEL
		, SUBSIDIARY
		, CHANNEL
		, SUB_CHANNEL
		, SALES_CHANNEL_ATTR_1
		, SALES_CHANNEL_ATTR_2
		, AFFILIATE_ID
		, SKU
		, PDROD_DIVISION
		, PDROD_PRODUCT_GROUP
		, PDROD_PRODUCT
		, PROD_ATTB_1
		, SEDA_BU_ESTORE
		, SEDA_DIVISION_ESTORE
		, SEDA_CATEGORY_ESTORE
		, SEDA_FAMILY_ESTORE
		, SEDA_DESC_ESTORE
		, QTY
		, AMOUNT_LOCAL
		, AMOUNT_USD
		, PRICE_TO
		, AMOUNT_DISCOUNT
		, AMOUNT_SHIPPING
		, ITEM_NAME
		, ORDER_ID
		, "SELECTED_SLA"
		, "WAREHOUSE_ID_GROUP"
		, "ADDRESSTYPE"
		, "FRIENDLYNAME"
		, "STATE"
		, "CITY"
		, MARKETPLACE_ORDER_ID
		, CUSTOMER_PO
		, ENVIRONMENT
		, STORE_ID
		, NAME_STORE
		, "STORE_EMPLOYEE_CPF"
		, CHANNEL_TYPE
		, "O2O_TYPE" -- 020
		, REFERENCE_CODE_KIT
		, REFERENCE_CODE
		, STATUS_PO
		, AFFILIATE_ID_ADJUSTED
		, AFFILIATE_CHANNEL
		, AFFILIATE_SUB_CHANNEL
		, AFFILIATE_PARTNER_LEVEL
		, GLOBAL_CHANNEL
		, BIZ_TYPE
		, AUDIENCE_TYPE
		, "COUPON"
		, COUNTRY
		, CURRENCY
		, MODEL_TYPE
		, KPI_LAST_UPDATE
		, EMAIL_DOMAIN
		, SKU_ID
		, SKU_ID_COMPONENT
		, PO_MINUTE
		, SELLING_PRICE
		, UTM_SOURCE
		, UTM_MEDIUM 
		, UTM_PARTNER
		, UTM_CAMPAIGN
		, MARKETING_TAGS
		, CORPORATENAME
		, ITEM_INDEX
		, SELLING_AMOUNT_SHIPPING
		, SELLING_AMOUNT_LOCAL
		--, PAYMENT_DETAILS
		--, PROMOTION_DETAILS
		, ITEM_INDEX_KIT
		, PROMOS_IDS
		, PROMOS_NAME
		, PROMOS_DISCOUNTS
	)
	SELECT
		 'PO' AS SOURCE
		, PO.DATE_REF
		, CL.YYYYWW AS YYYYWW
		, CL.YYYYMM AS YYYYMM
		, CL.YYYYQQ AS YYYYQQ
		, PO.PO_CREATION_DATE
		, WEEKDAY(PO.PO_CREATION_DATE) AS "PO_WEEK_DAY_NUM"
		, DAYNAME(PO.PO_CREATION_DATE) AS "PO_WEEK_DAY_NAME"
		, EXTRACT_HOUR(PO.PO_CREATION_DATE) AS "PO_HOUR"
		-- CHANNEL
		, PO.SALES_CHANNEL
		, CASE WHEN AF.SUBSIDIARY IS NOT NULL THEN TRIM(AF.SUBSIDIARY) ELSE 'SEDA' END AS SUBSIDIARY
		, CH.CHANNEL 
		, CH.SUB_CHANNEL 
		, CH.SALES_CHANNEL_ATTR_1 
		, CH.SALES_CHANNEL_ATTR_2
		, PO.AFFILIATE_ID
		-- PRODUCT
		, PO.REFERENCE_CODE AS SKU --PD.SKU
		, PD."DIVISION" AS PDROD_DIVISION
		, PD.PRODUCT_GROUP_1 AS PDROD_PRODUCT_GROUP 
		, PD.PRODUCT_1 AS PDROD_PRODUCT 
		, PD.ATTB01 AS PROD_ATTB_1 
		, PD.SEDA_BU_ESTORE
		, PD.SEDA_DIVISION_ESTORE
		, PD.SEDA_CATEGORY_ESTORE
		, PD.SEDA_FAMILY_ESTORE
		, PD.SEDA_DESC_ESTORE		
		, PO.QTY
		, PO.AMOUNT_LOCAL
		--,0 AS AMOUNT_USD
		, CAST( PO.AMOUNT_LOCAL / IFNULL(EX.EXCHANGE_RATE, EX2.EXCHANGE_RATE) AS DECIMAL(18,2) ) AS AMOUNT_USD
		--,PO.PRICE_FROM
		, PO.PRICE_TO
		, PO.AMOUNT_DISCOUNT
		, PO.AMOUNT_SHIPPING
		, PO.ITEM_NAME
		, PO.ORDER_ID
		, SL."SELECTED_SLA"
		, SL."WAREHOUSE_ID_GROUP"
		, SL.ADDRESSTYPE
		, SL.FRIENDLYNAME
		, SL.STATE
		, SL.CITY
		, PO.MARKETPLACE_ORDER_ID
		, PO.CUSTOMER_PO
		, PO.ENVIRONMENT
		, PO.STORE_ID
		, PO.NAME_STORE
		, PO."STORE_EMPLOYEE_CPF"
		, PO.CHANNEL_TYPE
		, CASE 
			WHEN ( TRIM(UPPER(SL."SELECTED_SLA")) LIKE 'SHIP TO STORE %' 
					OR TRIM(UPPER(SL."SELECTED_SLA"))LIKE 'PONTO DE RETIRADA %'
					OR TRIM(UPPER(SL."SELECTED_SLA"))LIKE 'CLIQUE%'
				 ) AND PO.CHANNEL_TYPE = 'Store+'
			THEN 'BOPIS + EA'
			WHEN ( TRIM(UPPER(SL."SELECTED_SLA")) LIKE 'SHIP TO STORE %'
				   OR TRIM(UPPER(SL."SELECTED_SLA"))LIKE 'PONTO DE RETIRADA %'
				   OR TRIM(UPPER(SL."SELECTED_SLA"))LIKE 'CLIQUE%' )
			THEN 'BOPIS'
			WHEN ( PO.CHANNEL_TYPE = 'Store+' )
			THEN 'EA'
		  ELSE NULL END AS O2O_TYPE
		, PO.REFERENCE_CODE_KIT
		, PO.REFERENCE_CODE
		, PO.STATUS_PO
		-- AFFILIATE INFORMATION
		, PO.AFFILIATE_ID_ADJUSTED
		, AF.AFFILIATE_CHANNEL
		, AF.AFFILIATE_SUB_CHANNEL
		, AF.AFFILIATE_PARTNER_LEVEL
		, AF.GLOBAL_CHANNEL
		, AF.BIZ_TYPE
		, AF.AUDIENCE_TYPE
		, PO."COUPON"
		, AF.COUNTRY
		, AF.CURRENCY
		-- PREMIUM MODEL
		, CASE WHEN PR.MATERIAL IS NOT NULL THEN 'PREMIUM MODEL' ELSE 'NORMAL MODEL' END AS MODEL_TYPE
		--KPI_LAST_UPDATE
		, CURRENT_TIMESTAMP AS KPI_LAST_UPDATE
		, PO.EMAIL_DOMAIN
		
		, PO.SKU_ID
		, PO.SKU_ID_COMPONENT
		, PO.PO_MINUTE
		, PO.SELLING_PRICE
		, PO.UTM_SOURCE
		, PO.UTM_MEDIUM 
		, PO.UTM_PARTNER
		, PO.UTM_CAMPAIGN
		, PO.MARKETING_TAGS
		, PO.CORPORATENAME
		, PO.ITEM_INDEX
		, PO.SELLING_AMOUNT_SHIPPING
		, PO.SELLING_AMOUNT_LOCAL
		--, PMT.PAYMENT_DETAILS
		--, PRM.PROMOTION_DETAILS
		, PO.ITEM_INDEX_KIT
		, PRM.PROMOS_IDS
		, PRM.PROMOS_NAME
		, PRM.PROMOS_DISCOUNTS    		
	FROM(
		SELECT
			  PO_.DATE_REF
			, PO_.PO_CREATION_DATE
			, PO_.SALES_CHANNEL
			, PO_.AFFILIATE_ID
			--,'BRL' AS CURRENCY
			, PO_.ORDER_ID
			, PO_.MARKETPLACE_ORDER_ID
			, PO_.CUSTOMER_PO
			, PO_.ITEM_INDEX
			, PO_.ITEM_INDEX_KIT
			, PO_.ENVIRONMENT
			, ES.ID_STORE AS STORE_ID --,PO_.STORE_ID
			, ES.NAME AS NAME_STORE
			, PO_."STORE_EMPLOYEE_CPF"
			, CASE WHEN ES.ID_STORE IS NOT NULL THEN 'Store+' ELSE 'Shop' END AS CHANNEL_TYPE				 
			, PO_.REFERENCE_CODE_KIT
			
			--, PO_.REFERENCE_CODE
			, CASE WHEN UPPER(PO_.REFERENCE_CODE) LIKE '%_OUT%' THEN SUBSTRING(PO_.REFERENCE_CODE, 1, LENGTH(PO_.REFERENCE_CODE) - 5 ) ELSE PO_.REFERENCE_CODE END AS REFERENCE_CODE			
			
			, PO_.ITEM_NAME
			, PO_.STATUS_PO
			--, PO_.PRICE_FROM
			, PO_.PRICE_TO
			, PO_.AMOUNT_DISCOUNT
			, PO_.AMOUNT_SHIPPING
			, PO_.QTY
			, PO_.AMOUNT_LOCAL
			
			--, OW_LAO.AFFILIATE_ID_ADJUSTED(ES.ID_STORE, PO_.AFFILIATE_ID, PO_.SALES_CHANNEL) AS AFFILIATE_ID_ADJUSTED
			, CASE
				WHEN UPPER(PO_.REFERENCE_CODE) LIKE '%_OUT1' THEN 'TLB'
				WHEN UPPER(PO_.REFERENCE_CODE) LIKE '%_OUT3' THEN 'TLD'
				ELSE OW_LAO.AFFILIATE_ID_ADJUSTED(ES.ID_STORE, PO_.AFFILIATE_ID, PO_.SALES_CHANNEL) 
			END AS AFFILIATE_ID_ADJUSTED			
			
			, PO_.SKU_ID
			, PO_.SKU_ID_COMPONENT
			, PO_.COUPON
			, PO_.EMAIL_DOMAIN
			, PO_.PO_MINUTE
			, PO_.SELLING_PRICE
			, PO_.UTM_SOURCE
			, PO_.UTM_MEDIUM 
			, PO_.UTM_PARTNER
			, PO_.UTM_CAMPAIGN
			, PO_.MARKETING_TAGS
			, PO_.CORPORATENAME
			, PO_.SELLING_AMOUNT_SHIPPING
			, PO_.SELLING_AMOUNT_LOCAL
		FROM(
			/*****************************************************************
				PO (VTEX [SOMENTE ITENS]) {CREATION_TIMESTAMP}
			*****************************************************************/			
			SELECT
				  TO_DATE(VO.CREATION_TIMESTAMP) AS DATE_REF
				, VO.CREATION_TIMESTAMP AS PO_CREATION_DATE
				, VO.AFFILIATE_ID
				, VO.ORDER_ID
				, VO.MARKETPLACE_ORDER_ID
				, VO.HOSTNAME AS ENVIRONMENT
				, VO.STATUS AS STATUS_PO
				  --CASE WHEN EP.ORDER_ID IS NOT NULL THEN EP.STATUS
					--   WHEN VD.ORDER_ID IS NOT NULL THEN VD.STATUS
					--   ELSE VO.STATUS

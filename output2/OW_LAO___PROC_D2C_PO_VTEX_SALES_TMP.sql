			 ON NS.REFERENCE_CODE = MSK.SKU_SE
			   AND TRIM(UPPER(NS.STATE)) = TRIM(UPPER(MSK.UF))
			   
		/*********
		LEFT JOIN (
			SELECT 
				  SK.SKU
				, SK.REGION
				, SK.TAX_SKU
				, SK.TAX_INCENTIVE_SKU

					GROUP BY SKU
						, REGION
				) DT ON SK.SKU  = DT.SKU
						AND SK.REGION  = DT.REGION
						AND SK.BILLING_DATE_MIN  = DT.BILLING_DATE_MIN
		) TS ON IFNULL(MSK.SKU_MAN, NS.REFERENCE_CODE) = TS.SKU --NS.REFERENCE_CODE = TS.SKU
			AND TRIM(UPPER(NS.STATE)) = TRIM(UPPER(TS.REGION))
		********/
			
		LEFT JOIN (
		     SELECT SKU
		            ,REGION
		            ,SUM (AMOUNT_ZKE) / SUM (NF_TOTAL_AMT) AS TAX_SKU
		            ,SUM (TAX_INCENTIVE_ZKE) / SUM (NF_TOTAL_AMT) AS TAX_INCENTIVE_SKU
		     FROM OW_LAO.TF_NERP_GROSS_MARGIN

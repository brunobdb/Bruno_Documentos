				     AND BILLING_DATE BETWEEN ADD_DAYS(NOW (), -60) AND NOW()
				     AND AFFILIATE_SUB_CHANNEL <> 'Outlet'
				     AND SALES_DOCUMENT_TYPE = 'YS10'
				     AND AMOUNT_ZKE >= 0

		WHERE RW."FILE_NAME" = :v_file_name
			AND RW.LAST_MODIFICATION_FILE = ( -- CASO O RPA GERE MAIS DE 1 ARQUIVO
									SELECT MAX(LAST_MODIFICATION_FILE)
									FROM OW_LAO.RAW_DATA_NERP_ZRSDD6A120_SALES_ORDER_TRACKING
									WHERE "FILE_NAME" = v_file_name
								)
		;	
		
		-- ATUALIZA LAST_TIME_PROCESSED
		UPDATE OW_LAO.RAW_DATA_NERP_ZRSDD6A120_SALES_ORDER_TRACKING SET
			LAST_TIME_PROCESSED = CURRENT_TIMESTAMP
		WHERE "FILE_NAME" = :v_file_name
			AND LAST_MODIFICATION_FILE = ( -- CASO O RPA GERE MAIS DE 1 ARQUIVO
									SELECT MAX(LAST_MODIFICATION_FILE)
									FROM OW_LAO.RAW_DATA_NERP_ZRSDD6A120_SALES_ORDER_TRACKING
									WHERE "FILE_NAME" = :v_file_name
								)
		;
		
		-- APAGA ARQUIVOS DA RAW_DATA COM MAIS DE 90 DIAS
		DELETE FROM OW_LAO.RAW_DATA_NERP_ZRSDD6A120_SALES_ORDER_TRACKING
		WHERE LAST_MODIFICATION_FILE <= ADD_DAYS(CURRENT_TIMESTAMP, -40)
		;
		
		-- APAGA ARQUIVOS DA RAW_DATA COM MAIS DE 90 DIAS
		DELETE FROM OW_LAO.RAW_DATA_NERP_ZLLEJ50090_OUTBOUND_TRACKING
		WHERE LOAD_DATE <= ADD_DAYS(CURRENT_TIMESTAMP, -40)
		;
		
	END FOR;

			,ROUND(REPLACE(RW."1ST_GI_QTY", ',', '')) AS "1ST_GI_QTY"
			,RW."1ST_GI_CREATE_ON"
			,RW."1ST_GI_CREATE_ON_TIME"
			,RW."2ND_GI_NO"
			,RW."ITEM_3"
			,ROUND(REPLACE(RW."2ND_GI_QTY", ',', '')) AS "2ND_GI_QTY"
			,RW."POSTING_DATE"
			,RW."2ND_GI_CREATE_ON"
			,RW."2ND_GI_CREATE_ON_TIME"
			,RW."BILLING_DOC"
			,RW."ITEM_4"
			,ROUND(REPLACE(RW."BILLED_QTY_BASE", ',', '')) AS "BILLED_QTY_BASE"
			,RW."BILLING_NET_VALUE"
			,RW."BILLING_CURR"
			,RW."BILLING_DATE"

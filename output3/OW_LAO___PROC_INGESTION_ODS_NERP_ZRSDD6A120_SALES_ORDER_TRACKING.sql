			,"SO_CURR"
			,"SO_CREATE_ON"
			,"SO_CREATE_ON_TIME"
			,"FIRST_SC_DATE"
			,"SALES_ORG"
			,"DISTR_CHANNEL"
			,"DIVISION"
			,"PLANT"
			,"STOR_LOC"
			,"ACCOUNT_CODE"
			,"ACCOUNT_NAME"
			,"GC_ID_GSCM"
			,"GC_NAME"
			,"AP1_CODE"
			,"AP1_NAME"
			,"AP2_CODE"
			,"AP2_NAME"
			,"SCM_SITE_ID"
			,"TRANSPORT_ZONE"
			,"DELIVERY"
			,"DELIVERY_ITEM"
			,"DELIVERY_QTY_BASE"
			,"BASE_UNIT_1"
			,"DOCUMENT_DATE"
			,"DO_CREATE_ON"
			,"DO_CREATE_ON_TIME"
			,"SR_NO"
			,"SR_ITEM"
			,"SR_DATE"
			,"SR_TYPE"
			,"SR_TYPE_DESC"
			,"1ST_GI_NO"
			,"1ST_GI_ITEM"
			,"1ST_GI_QTY"
			,"1ST_GI_CREATE_ON"
			,"1ST_GI_CREATE_ON_TIME"
			,"2ND_GI_NO"
			,"2ND_GI_ITEM"
			,"2ND_GI_QTY"
			,"POSTING_DATE"
			,"2ND_GI_CREATE_ON"
			,"2ND_GI_CREATE_ON_TIME"
			,"BILLING_DOC"
			,"BILLING_DOC_ITEM"
			,"BILLED_QTY_BASE"
			,"BILLING_NET_VALUE"
			,"BILLING_CURR"
			,"BILLING_DATE"
			,"BILLING_CREATE_ON"
			,"BILLING_CREATE_ON_TIME"
			,"PARTIAL_DELIVERY_SEQ"
			,"STATUS"
			,"1ST_GI_DATE"
			,"DELIVERY_BLOCK"
			,"ORDER_REASON"
			,"REJECT_REASON"
			,"REJECT_REASON_1"
			,"ORDER_QTY"
			,"CONFIRMED_QTY"
			,"SPEC_PROCESSING"
			,"MAT_AVAIL_DATE"
			,"MATERIAL_GROUP"
			,"SO_LOCAL_CREATE_ON_D"
			,"DO_LOCAL_CREATE_ON_D"
			,"1ST_GI_LOCAL_CREATE"
			,"BILLING_LOCAL_CREATE"
			,"FINAL_SCH_DATE"
			,"SHIPPING_TYPE"
			
            --Alteração solicitada para acréscimo destes 4 campos 05/02/2024 
			,"SO_LOCAL_CREATE_ON_T"
			,"DO_LOCAL_CREATE_ON_T"
			,"1ST_GI_LOCAL_CREATE_TIME"
			,"2ST_GI_LOCAL_CREATE_TIME"			
			

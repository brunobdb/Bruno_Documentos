			,ROUND(REPLACE(RW."CONFIRMED_QTY", ',', '')) AS "CONFIRMED_QTY"
			,RW."SPEC_PROCESSING"
			,RW."MAT_AVAIL_DATE"
			,RW."MATERIAL_GROUP"
			,RW."SO_LOCAL_CREATE_ON_D"
			,RW."DO_LOCAL_CREATE_ON_D"
			,RW."1ST_GI_LOCAL_CREATE"
			,RW."BILLING_LOCAL_CREATE"
			,RW."FINAL_SCH_DATE"
			,RW."SHIPPING_TYPE"
			
            --Alteração solicitada para acréscimo destes 4 campos 05/02/2024 
			,RW."SO_LOCAL_CREATE_ON_T"
			,RW."DO_LOCAL_CREATE_ON_T"
			,RW."1ST_GI_LOCAL_CREATE_TIME"
			,RW."2ST_GI_LOCAL_CREATE_TIME"			
			
			,RW."FILE_NAME"
			,RW."LOAD_DATE"
			,RW."LAST_MODIFICATION_FILE"

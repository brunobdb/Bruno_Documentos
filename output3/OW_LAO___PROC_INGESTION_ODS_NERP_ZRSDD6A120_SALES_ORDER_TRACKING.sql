BEGIN
	
	/****************************************************************************************
	-- REPROCESSAR TODOS OS ARQUIVOS PARA A ODS A PARTIR DA  RAW NÃO PROCESSADA MAIS ANTIGA
	****************************************************************************************/
	DECLARE v_file_name NVARCHAR(4000);
	
	-- CURSOR PASSA POR CADA ARQUIVO
	DECLARE CURSOR c_select FOR
		SELECT 
			 RANKING_PERIOD_START
			,"FILE_NAME" AS F_FILE_NAME
			--,PERIOD_START ,PERIOD_END ,GENERATED_IN ,LAST_TIME_PROCESSED ,RANKING_PERIOD_START ,RANKING_PERIOD_END ,RANKING_LAST_TIME_PROCESSED
		FROM(
			SELECT 
				  "FILE_NAME"
				--,PERIOD_START ,PERIOD_END ,GENERATED_IN ,LAST_TIME_PROCESSED 
				, PROCESSED
				, RANK() OVER (ORDER BY GENERATED_IN, PERIOD_START) AS RANKING_PERIOD_START
				--, RANK() OVER (ORDER BY GENERATED_IN, PERIOD_END) AS RANKING_PERIOD_END
				, RANK() OVER (ORDER BY LAST_TIME_PROCESSED, PERIOD_START) AS RANKING_LAST_TIME_PROCESSED
			FROM( 
				SELECT DISTINCT 
					  "FILE_NAME"
					, REPLACE(SUBSTRING("FILE_NAME",22,10),'.','-') AS PERIOD_START
					--, REPLACE(SUBSTRING("FILE_NAME",33,10),'.','-') AS PERIOD_END
					, CASE WHEN LENGTH("FILE_NAME") > 50 THEN 
						        REPLACE(SUBSTRING("FILE_NAME",44,10),'.','-') || ' ' || REPLACE(SUBSTRING("FILE_NAME",55,5),'.',':')
					 	   ELSE SUBSTRING(LAST_MODIFICATION_FILE,1,16) END AS GENERATED_IN
					, CASE WHEN LAST_TIME_PROCESSED IS NOT NULL THEN LAST_TIME_PROCESSED
						   ELSE CURRENT_TIMESTAMP END AS LAST_TIME_PROCESSED
					, CASE WHEN LAST_TIME_PROCESSED IS NOT NULL THEN 1 ELSE 0 END AS PROCESSED
				FROM OW_LAO.RAW_DATA_NERP_ZRSDD6A120_SALES_ORDER_TRACKING
				WHERE 1=1
					AND LAST_MODIFICATION_FILE BETWEEN IFNULL(:p_DATE_INI, ADD_DAYS(CURRENT_TIMESTAMP, -1)) 
												   AND IFNULL(:P_DATE_FIM, ADD_DAYS(CURRENT_TIMESTAMP, 2))
					--AND LAST_MODIFICATION_FILE < '2024-01-29 15:28:55'	-- ******** RETIRAR LINHA PARA VOLTAR A PROCESSAR ***************************		
			)
		)
		WHERE
			( PROCESSED = 0) -- NÃO PROCESSADOS  (OU)
			OR ( IFNULL(:p_DATE_INI, ADD_DAYS(CURRENT_TIMESTAMP, -1)) <> ADD_DAYS(CURRENT_TIMESTAMP, -1) ) -- PARAMETRO PASSADO
		ORDER BY
			RANKING_PERIOD_START
		;
	FOR cursorRow as c_select DO
	
		-- SETA PROXIMA ARQUIVO
		v_file_name := cursorRow.F_FILE_NAME; -- SELECT :v_file_name AS FILE_ FROM DUMMY;
		
		--*************************************************************************
		-- APAGA "SALES_DOCUMENT" DA ODS QUE ESTÃO NO NA RAW
		-- ************************************************************************
		DELETE
		FROM OW_LAO.ODS_NERP_ZRSDD6A120_SALES_ORDER_TRACKING
		WHERE "SALES_DOCUMENT" IN(
			SELECT DISTINCT
				"SALES_DOCUMENT"
			FROM OW_LAO.RAW_DATA_NERP_ZRSDD6A120_SALES_ORDER_TRACKING
			WHERE "FILE_NAME" = v_file_name
		);
		
		--*************************************************************************
		-- INSERE NOVOS REGISTROS DO ARQUIVO QUE ESTÃO NA RAW E NÃO ESTÃO NA OSD
		--*************************************************************************
		INSERT INTO OW_LAO.ODS_NERP_ZRSDD6A120_SALES_ORDER_TRACKING(
			 "SALES_DOCUMENT"
			,"SALES_DOCUMENT_ITEM"
			,"SALES_DOC_TYPE"
			,"CUSTOMER_PO"
			,"SOLD_TO_PARTY"
			,"NAME"

CREATE PROCEDURE OW_LAO.PROC_INGESTION_ODS_NERP_ZRSDD6A120_SALES_ORDER_TRACKING(
	--IN p_Process_all BOOLEAN DEFAULT FALSE
	 p_DATE_INI DATE DEFAULT NULL
	,P_DATE_FIM DATE DEFAULT NULL
)
